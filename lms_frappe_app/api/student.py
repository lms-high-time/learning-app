@frappe.whitelist()
@контракт
def list_my_courses(space: str | None = None) -> dict:
	"""Курсы пространства с прогрессом, дедлайнами и просрочками.

	`space` — организация или `personal`; без него — выбранное пространство.
	В личном — все курсы человека, в организации — её (learning-services#346).
	`programs` — программы курса: место в цепочке и что пройти раньше
	(learning-services#405).
	"""
	ученик = текущий_пользователь()
	организация = _названное_или_текущее(ученик, space)
	записи = пространства.курсы(ученик, организация)
	по_программам = программы.программы_курсов([запись["course"] for запись in записи], ученик)
	курсы = []
	for запись in записи:
		# Уроки и пройденное читаются один раз на курс: прежняя редакция
		# строила их заново для прогресса и для следующего урока.
		уроки = уроки_курса(запись["course"])
		пройдены = _пройденные(ученик, запись["course"])
		пройдено = len([урок for урок in уроки if урок in пройдены])
		всего = len(уроки)
		следующий = _первый_непройденный(уроки, пройдены)
		курсы.append(
			{
				"id": запись["course"],
				"title": frappe.db.get_value("LMS Course", запись["course"], "title"),
				"organization": запись["organization"],
				"mandatory": запись["mandatory"],
				"deadline": запись["deadline"],
				"overdue": запись["overdue"],
				"progress": {"lessons_total": всего, "lessons_completed": пройдено},
				"next_lesson": следующий,
				"programs": по_программам.get(запись["course"], []),
			}
		)
	return {"space": пространства.наружу(организация), "courses": курсы}


