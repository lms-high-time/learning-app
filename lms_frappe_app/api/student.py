def _цель_пункта(значение, цели: list[str]) -> str:
	"""Цель пункта итога: текст как есть, номер — цель с этим номером."""
	if isinstance(значение, int) or (isinstance(значение, str) and значение.strip().isdigit()):
		номер = int(значение)
		if 1 <= номер <= len(цели):
			return цели[номер - 1]
	return str(значение or "").strip()


def _записать_цели(занятие, цели: list[str], итог: dict) -> None:
	"""Строки отметок в порядке директивы, а не в порядке прихода.

	Порядок из директивы: строки читаются так, как автор задумывал урок.
	"""
	занятие.outcomes = []
	for цель in цели:
		if цель in итог:
			статус, продолжить, сделано = итог[цель]
			занятие.append(
				"outcomes",
				{
					"objective": цель,
					"status": статус,
					"resume_from": продолжить,
					"evidence": сделано,
				},
			)
	занятие.save(ignore_permissions=True)


def _прогресс_курса(ученик: str, course: str) -> dict | None:
	"""Прогресс открытого занятия ученика по курсу; `None`, если занятия нет."""
	открытые = frappe.get_all(
		"Agent Learning Session",
		filters={"student": ученик, "course": course, "status": ("in", ОТКРЫТЫЕ)},
		pluck="name",
		order_by="last_activity_at desc",
		limit=1,
		ignore_permissions=True,
	)
	return _прогресс(frappe.get_doc("Agent Learning Session", открытые[0])) if открытые else None


def _прогресс(занятие, цели: list[str] | None = None) -> dict:
	"""Сколько целей урока отмечено и какие ещё нет — с номерами.

	Отмеченной считается цель с любым статусом: так её видит страница
	курса. Номера — те же, которыми отмечает `mark_objective`.
	"""
	цели = _цели_урока(занятие.lesson) if цели is None else цели
	отмечены = {с.objective for с in занятие.outcomes}
	открытые = [
		{"number": номер, "text": цель}
		for номер, цель in enumerate(цели, start=1)
		if цель not in отмечены
	]
	return {"marked": len(цели) - len(открытые), "total": len(цели), "open": открытые}


def _требовать_отчёт(занятие) -> None:
	"""Отказывает, пока отчёт по целям не сдан.

	Урок без целей отчёта не требует: требовать нечего, и отказ загнал бы
	агента в тупик без способа из него выйти.
	"""
	цели = _цели_урока(занятие.lesson)
	отмечены = {с.objective for с in занятие.outcomes}
	нет = [цель for цель in цели if цель not in отмечены]
	if not нет:
		return
	# Все цели, а не хотя бы одна: отметки по ходу копятся по одной, и
	# «строка есть» больше не значит «итог сдан» (learning-services#409).
	raise Отказ(
		НЕТ_ОТЧЁТА,
		"Сначала отметьте все цели урока: mark_objective или report_outcomes",
		session=занятие.name,
		missing=нет,
	)


def _требовать_покрытие(занятие) -> None:
	"""Отказывает в квизе, пока в отчёте есть цели со статусом `skipped`.

	`touched` не блокирует. Тупика отказ не создаёт: повторный
	`report_outcomes` замещает прежний отчёт целиком, и после разбора
	пропущенного проверка проходит.
	"""
	пропущены = [с.objective for с in занятие.outcomes if с.status == "skipped"]
	if not пропущены:
		return
	raise Отказ(
		ЦЕЛИ_ПРОПУЩЕНЫ,
		"Сначала разберите пропущенные цели урока и сдайте отчёт заново",
		skipped=пропущены,
		session=занятие.name,
	)


def _курс_урока(lesson: str) -> str:
	"""Курс урока — или отказ агенту: без курса занятию неоткуда взяться."""
	курс = курс_урока(lesson)
	if not курс:
		raise Отказ(УРОК_НЕ_НАЙДЕН, "Такого урока нет", lesson=lesson)
	return курс


def _выбрать_урок(ученик: str, организация: str | None) -> str:
	"""Урок, который продолжать, — первый из `_кандидаты`."""
	кандидаты = _кандидаты(ученик, организация)
	if not кандидаты:
		raise Отказ(НЕЧЕГО_УЧИТЬ, "Незакрытых уроков не осталось")
	return кандидаты[0]["lesson"]["id"]


def _место_урока(lesson: str, курс: str) -> dict:
	"""Номер урока в курсе, их число и название курса."""
	уроки = уроки_курса(курс)
	return {
		"number": уроки.index(lesson) + 1 if lesson in уроки else None,
		"total": len(уроки),
		"course_title": frappe.get_cached_value("LMS Course", курс, "title"),
	}


def _кандидаты(ученик: str, организация: str | None) -> list[dict]:
	"""Что продолжать в пространстве, по порядку: по уроку на курс.

	Первым — урок последнего занятия, если он не пройден, иначе следующий урок
	его курса; дальше курсы по сроку — сначала просроченные и срочные.
	`Why:` раньше выбор шёл только по сроку, и кто проходил курс Б, попадал в
	урок курса А, у которого был срок, — «неуместно и сбивает с толку»
	(learning-services#403). Горящий курс не пропадает: он следующий в списке,
	и развилка веб-чата показывает его со сроком.
	"""
	курсы = пространства.курсы(ученик, организация)
	if not курсы:
		return []
	по_курсу = {запись["course"]: запись for запись in курсы}
	порядок = sorted(
		курсы,
		key=lambda к: (к["deadline"] is None, к["deadline"] or "", not к["mandatory"]),
	)
	последнее = frappe.get_all(
		"Agent Learning Session",
		filters={"student": ученик, "course": ("in", list(по_курсу))},
		fields=["lesson", "course"],
		order_by="last_activity_at desc, creation desc",
		limit=1,
	)
	урок_последнего = None
	if последнее:
		курс_последнего = последнее[0].course
		порядок = [по_курсу[курс_последнего]] + [
			к for к in порядок if к["course"] != курс_последнего
		]
		урок_последнего = последнее[0].lesson

	названия_курсов = dict(
		frappe.get_all(
			"LMS Course",
			filters={"name": ("in", list(по_курсу))},
			fields=["name", "title"],
			as_list=True,
		)
	)
	# Курс, запертый программой, не предлагается: `start_lesson` на нём
	# откажет (#405).
	запертые = программы.запертые(ученик, list(по_курсу))
	итог = []
	for номер_курса, курс in enumerate(порядок):
		if курс["course"] in запертые:
			continue
		уроки = уроки_курса(курс["course"])
		пройдены = _пройденные(ученик, курс["course"])
		урок, причина = None, None
		if номер_курса == 0 and урок_последнего in уроки and урок_последнего not in пройдены:
			урок, причина = урок_последнего, "last_lesson"
		else:
			следующий = _первый_непройденный(уроки, пройдены)
			if следующий:
				урок = следующий["id"]
				причина = (
					"last_course"
					if номер_курса == 0 and последнее
					else ("deadline" if курс["deadline"] else "next")
				)
		if not урок:
			continue
		итог.append(
			{
				"lesson": {
					"id": урок,
					"title": frappe.db.get_value("Course Lesson", урок, "title"),
					"number": уроки.index(урок) + 1,
					"total": len(уроки),
				},
				"course": {"id": курс["course"], "title": названия_курсов.get(курс["course"])},
				"deadline": str(курс["deadline"]) if курс["deadline"] else None,
				"overdue": bool(курс.get("overdue")),
				"mandatory": bool(курс["mandatory"]),
				"reason": причина,
			}
		)
	return итог


@frappe.whitelist()
@контракт
def study_options(space: str | None = None) -> dict:
	"""Что продолжать: рекомендованный урок, другие курсы и остаток пробных уроков.

	Зовёт веб-чат, открытый без урока: вместо того чтобы молча начать урок и
	потратить пробный, он показывает развилку — главной кнопкой урок, который
	открыл бы `start_lesson` без аргументов, ниже другие курсы
	(learning-services#403). `web` — пустит ли веб-чат на этот урок: урок, уже
	начатый в браузере, пробного не тратит.
	"""
	ученик = текущий_пользователь()
	кандидаты = _кандидаты(ученик, _названное_или_текущее(ученик, space))
	использовано = веб_уроки_ученика(ученик)
	пробные = пробные_уроки_ученика(ученик, использовано)
	for кандидат in кандидаты:
		кандидат["web"] = bool(пробные["left"]) or кандидат["lesson"]["id"] in использовано
	return {
		"recommended": кандидаты[0] if кандидаты else None,
		"others": кандидаты[1:4],
		"web_demo": пробные,
	}


def _выбрать_урок_курса(ученик: str, курс: str) -> str:
	"""Следующий незакрытый урок одного курса — доступ проверяется до выбора.

	Отказ по доступу идёт раньше «всё пройдено»: иначе чужой курс отвечал бы
	тем, пройден ли он.
	"""
	_требовать_доступ_к_курсу(ученик, курс)
	следующий = _следующий_урок(ученик, курс)
	if not следующий:
		raise Отказ(НЕЧЕГО_УЧИТЬ, "В этом курсе незакрытых уроков не осталось", course=курс)
	return следующий["id"]


def _пройденные(ученик: str, курс: str) -> set[str]:
	return set(
		frappe.get_all(
			"LMS Course Progress",
			filters={"member": ученик, "course": курс, "status": ПРОЙДЕН},
			pluck="lesson",
		)
	)


def _доля_пройденного(ученик: str, курс: str) -> float:
	"""Доля пройденных уроков курса — её обещает контракт в сводке."""
	уроки = уроки_курса(курс)
	if not уроки:
		return 0.0
	пройдены = _пройденные(ученик, курс)
	return round(len([урок for урок in уроки if урок in пройдены]) / len(уроки), 2)


def _названия_уроков(уроки: list[str]) -> dict[str, str]:
	"""Названия списка уроков одним запросом."""
	if not уроки:
		return {}
	return {
		урок.name: урок.title
		for урок in frappe.get_all(
			"Course Lesson", filters={"name": ("in", уроки)}, fields=["name", "title"]
		)
	}


def _первый_непройденный(
	уроки: list[str], пройдены: set[str], названия: dict[str, str] | None = None
) -> dict | None:
	"""Первый урок, до которого ученик ещё не дошёл.

	Названия можно передать готовыми: кто уже вычитал их списком, второй раз
	за одним названием в базу не ходит.
	"""
	for урок in уроки:
		if урок not in пройдены:
			название = (
				названия[урок]
				if названия is not None
				else frappe.db.get_value("Course Lesson", урок, "title")
			)
			return {"id": урок, "title": название}
	return None


def _следующий_урок(ученик: str, курс: str) -> dict | None:
	return _первый_непройденный(уроки_курса(курс), _пройденные(ученик, курс))


def _директива(lesson: str) -> dict:
	"""Действующая директива урока — отдельным полем и с пометкой адресата.

	Материал и директива приходят разными полями, а сама директива помечена
	`audience: teacher_only`. Это одна из трёх митигаций против пересказа
	директивы ученику; гарантий она не даёт — гарантию даёт серверный квиз.
	"""
	д = directives.запись(
		"Agent Lesson Directive",
		{"lesson": lesson},
		(
			"objectives",
			"teaching_directive",
			"probing_questions",
			"common_misconceptions",
			"success_criteria",
		),
	)
	if not д:
		return {}
	return {
		"objectives": _строки(д.objectives),
		"directive": {
			"audience": "teacher_only",
			"teaching_directive": д.teaching_directive,
			"probing_questions": _строки(д.probing_questions),
			"common_misconceptions": _строки(д.common_misconceptions),
			"success_criteria": _строки(д.success_criteria),
		},
	}


def _директива_курса(course: str) -> dict:
	"""Сквозная директива курса — тем же способом, что и урочная.

	Цели курса идут наружу, а не внутрь директивы: их агент вправе озвучить
	ученику, как и цели урока.
	"""
	д = directives.запись(
		"Agent Course Directive",
		{"course": course},
		(
			"objectives",
			"teaching_directive",
			"student_profile",
			"glossary",
			"remember_about_student",
		),
	)
	if not д:
		return {}
	return {
		"objectives": _строки(д.objectives),
		"directive": {
			"audience": "teacher_only",
			"teaching_directive": д.teaching_directive,
			"student_profile": д.student_profile,
			"glossary": _строки(д.glossary),
			# Внутрь директивы, а не рядом: по каким признакам его оценивают,
			# ученику знать не нужно — начнёт подстраиваться.
			"remember_about_student": _строки(д.remember_about_student),
		},
	}


#: Правило разбора многострочных полей директивы живёт в `directives`: его же
#: применяет карта курса, и две копии дали бы разный состав целей.
_строки = directives.строки


