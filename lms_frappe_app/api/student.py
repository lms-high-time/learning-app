@frappe.whitelist(methods=["POST"])
@контракт
def enroll(course: str, space: str | None = None) -> dict:
	"""Записывает ученика на курс из каталога пространства.

	В организации запись — её назначение по выбору ученика: курс попадает в её
	пространство и отчёт.
	"""
	ученик = текущий_пользователь()
	организация = _названное_или_текущее(ученик, space)
	можно, причина = пространства.можно_записаться(ученик, course, организация)
	if not можно:
		raise Отказ(причина, "На этот курс записаться нельзя", course=course)
	# Участник программы с обязательным порядком не записывается через голову
	# предыдущего курса (learning-services#405).
	программы.требовать_порядок(ученик, course)
	пространства.записать(ученик, course, организация)

	return {
		"space": пространства.наружу(организация),
		"course": course,
		"title": frappe.db.get_value("LMS Course", course, "title"),
		"first_lesson": _следующий_урок(ученик, course),
	}


@frappe.whitelist(methods=["POST"])
@контракт
def notify_when_released(course: str, notify: bool | int | str = True) -> dict:
	"""Подписывает ученика на письмо о выходе анонсированного курса — или,
	с `notify=false`, снимает подписку.

	На анонс записаться нельзя (`enroll` отказывает `course_upcoming`), и это
	то, что можно сделать вместо записи. Повторный вызов ничего не меняет.
	Письмо уходит, когда куратор открывает курс (learning-services#389).
	Отписаться можно и от курса, который уже не анонс: подписка без анонса
	никому не нужна (learning-services#391).
	"""
	ученик = текущий_пользователь()
	подписать = notify not in (False, 0, "0", "false", "False")
	if подписать:
		if not announcements.анонсирован(course):
			raise Отказ(КУРС_НЕ_АНОНС, "Этот курс не готовится к выходу", course=course)
		announcements.подписать(ученик, course)
	else:
		announcements.отписать(ученик, course)
	return {
		"course": course,
		"title": frappe.db.get_value("LMS Course", course, "title"),
		"notify": подписать,
	}


@frappe.whitelist()
@контракт
def course_outline(course: str) -> dict:
	"""Структура курса: главы, уроки и что из них пройдено.

	`Why:` без этого агент видит только следующий незакрытый урок и не может
	вернуться к пройденному — идентификатор взять неоткуда. «Повторим
	прошлую тему перед экзаменом» было невыполнимо при живом доступе к
	материалу.
	"""
	ученик = текущий_пользователь()
	_требовать_доступ_к_курсу(ученик, course)

	пройдены = _пройденные(ученик, course)
	# Порядок берётся тот же, что у остального кода: через ссылки глав и
	# уроков, иначе структура разойдётся с тем, что считает «следующим уроком».
	# Принадлежность урока главе известна из этого же обхода: раньше её
	# выясняли запросом на каждую пару «глава × урок».
	структура = уроки_по_главам(course)
	порядок = [урок for глава in структура for урок in глава["lessons"]]
	названия = _названия_уроков(порядок)
	следующий = _первый_непройденный(порядок, пройдены, названия)

	главы = []
	for глава in структура:
		главы.append(
			{
				"title": глава["title"],
				"lessons": [
					{
						"id": урок,
						"title": названия.get(урок),
						"completed": урок in пройдены,
						"current": bool(следующий and следующий["id"] == урок),
					}
					for урок in глава["lessons"]
				],
			}
		)
	return {
		"course": course,
		"chapters": главы,
		# Место курса в программах — агент видит цепочку и из программы курса
		# (learning-services#405).
		"programs": программы.программы_курса(course, ученик),
	}


@frappe.whitelist(methods=["POST"])
@контракт
def start_lesson(
	lesson: str | None = None,
	segment: int = 1,
	channel: str = "agent",
	course: str | None = None,
	space: str | None = None,
	brief: bool | int | str = False,
) -> dict:
	"""Начинает занятие: создаёт сессию и отдаёт всё нужное для урока.

	`brief` — лёгкий старт: занятие, цели, зачин и обещание, `opening`, без
	материала, указаний и контекста ученика — их агент берёт `lesson_material`,
	`teaching_notes` и `student_context`, когда они нужны. `Why:` полный ответ
	приходил до первой реплики десятками тысяч знаков, и агент тонул в нём, а
	не решал, что нужно сейчас (learning-services#407, #410). Без `brief` —
	прежний полный ответ: подключения с кэшем инструментов не знают новых
	методов, и лёгкий ответ послал бы их к тому, чего у них нет.

	`segment` — часть длинного урока, считая с единицы. Без него агент видел
	бы только начало: материал режется по заголовкам, а способа попросить
	продолжение не было вовсе.

	`course` без `lesson` — следующий незакрытый урок этого курса. `Why:`
	без него выбор шёл по всем курсам ученика, и «продолжим Lean Canvas»
	открывало урок другого курса (lms-platform#337). `lesson` важнее.

	`channel` — `web`, когда урок идёт в веб-чате платформы: там модель
	оплачивает платформа, и число уроков ограничено настройкой.

	`space` — пространство, в чей документ пишет занятие (организация или
	`personal`). Без него — пространство открытого занятия по курсу, иначе
	выбранное, если курс в нём есть, иначе личное (learning-services#346).
	"""
	ученик = текущий_пользователь()
	brief = _флаг(brief)
	if channel not in КАНАЛЫ:
		raise Отказ(НЕИЗВЕСТНЫЙ_КАНАЛ, "Канал занятия — agent или web", channel=channel)
	lesson = lesson or (
		_выбрать_урок_курса(ученик, course)
		if course
		else _выбрать_урок(ученик, _названное_или_текущее(ученик, space))
	)

	курс = _курс_урока(lesson)
	# Назначения читаются один раз на вызов: они нужны и списку курсов, и
	# политике квиза ниже, а прежде каждый спрашивал их у базы сам.
	назначения = назначения_ученика(ученик)
	# Один обход вместо трёх: доступ, сведения о курсе и просрочка берутся
	# из одного и того же списка.
	доступные = {
		запись["course"]: запись for запись in курсы_ученика(ученик, назначения)
	}
	if курс not in доступные:
		причина = (
			ОРГАНИЗАЦИЯ_ПРИОСТАНОВЛЕНА
			if frappe.db.exists("LMS Enrollment", {"member": ученик, "course": курс})
			else НЕ_ЗАЧИСЛЕН
		)
		raise Отказ(причина, "Этот курс сейчас недоступен", course=курс)
	# Запись могла появиться раньше вступления в программу: порядок
	# проверяется и на занятии, а не только при записи (#405).
	программы.требовать_порядок(ученик, курс)

	if channel == "web":
		_проверить_пробные_уроки(ученик, lesson)

	# Одно на вызов: оно же нужно блокам документа в ответе ниже.
	пространство = пространства.пространство_курса(ученик, курс, space)
	# Продолжение урока не заводит второе занятие: иначе на один урок копились
	# бы незакрытые сессии, которые потом закрывает фоновая задача. Занятие
	# того же урока в другом пространстве — другое: оно пишет в другой документ.
	занятие = _текущее_занятие(ученик, lesson, пространство) or frappe.get_doc(
		{
			"doctype": "Agent Learning Session",
			"student": ученик,
			"lesson": lesson,
			"course": курс,
			"organization": пространство,
			"via_trusted_service": 1,
			"brief_start": int(brief),
		}
	).insert(ignore_permissions=True)
	# Отметка при любом веб-вызове, а не только при создании: иначе урок,
	# начатый своим агентом, продолжался бы в веб-чате вне счёта.
	if channel == "web" and not занятие.web_chat:
		занятие.db_set("web_chat", 1)
	# Режим — по последнему старту: продолженное занятие могли начать другим
	# подключением, и предупреждения порядка должны знать, что пришло агенту.
	if bool(занятие.brief_start) != brief:
		занятие.db_set("brief_start", int(brief))

	материал = нормализовать_урок(lesson)
	segment = max(1, int(segment or 1))
	директива = _директива(lesson)
	курсовая = _директива_курса(курс)
	if not brief:
		# Событие одно: занятие выдало инструкцию, а из скольких она частей —
		# деталь, за которой в журнале нет смысла следить.
		занятие.записать_событие(СОБЫТИЕ_ДИРЕКТИВА_ВЫДАНА, f"урок {lesson}")

	политика = политика_квиза_для_курса(ученик, курс, назначения)
	сведения = доступные[курс]
	перенос, сделанное = _незакрытые_цели(ученик, курс, кроме=lesson)
	сегмент = min(segment, материал.total_segments or 1)
	# Итоги репортов — один раз: агент говорит о них на ближайшем занятии
	# курса, а повтор на каждом старте превратил бы новость в шум.
	итоги = _репорты_ученика(ученик, course=курс, только_новые_итоги=True)

	if brief:
		ответ = {
			"session": занятие.name,
			"space": пространства.наружу(пространство),
			"lesson": {
				"id": lesson,
				"title": материал.title,
				"course": курс,
				"overdue": bool(сведения.get("overdue")),
			},
			"content": {"segment_index": сегмент, "total_segments": материал.total_segments},
			"objectives": директива.get("objectives", []),
			"objectives_progress": _прогресс(занятие, директива.get("objectives", [])),
			"course_promise": frappe.db.get_value("LMS Course", курс, "course_promise") or None,
			"lesson_hook": frappe.db.get_value("Course Lesson", lesson, "lesson_hook") or None,
			"start": _состояние_старта(ученик, курс, lesson, занятие.name, сегмент, перенос),
			"course_objectives": курсовая.get("objectives", []),
			"quiz": {
				"required": политика["quiz_required"],
				"pass_threshold": политика["pass_threshold"],
				"attempts_left": _осталось_попыток(ученик, lesson, политика),
			},
			# Сколько ждёт в `student_context`: по нулям агенту незачем туда
			# ходить, а по новостям о репортах — стоит до зачина. Итоги здесь
			# не отмечаются доставленными: их доставит `student_context`.
			"context": {
				"notes": sum(len(набор) for набор in _заметки(ученик, курс).values()),
				"carried_over": len(перенос),
				"recent_work": len(сделанное),
				"closed_reports": len(итоги),
			},
			"signals": _сигналы_старта(ученик, курс, lesson, занятие, директива, сведения),
			# Задание урока — целиком. По прошлому уроку — статус и комментарий
			# куратора, ответ ученика — `my_homework(lesson=…)`
			# (learning-services#439).
			**домашка.для_старта(ученик, lesson, курс, пространство, полное=False),
		}
		if channel == "web":
			ответ["lesson"].update(_место_урока(lesson, курс))
			ответ["web_demo"] = пробные_уроки_ученика(ученик)
		return ответ

	ответ = {
		"session": занятие.name,
		"space": пространства.наружу(пространство),
		"lesson": {
			"id": lesson,
			"title": материал.title,
			"course": курс,
			"overdue": bool(сведения.get("overdue")),
		},
		"content": {
			"markdown": материал.сегмент(segment),
			"segment_index": сегмент,
			"total_segments": материал.total_segments,
		},
		"media": [
			{"kind": м.kind, "title": м.title, "url": м.url} for м in материал.media
		],
		"objectives": директива.get("objectives", []),
		# Продолженное занятие уже может нести отметки — агент видит их сразу.
		"objectives_progress": _прогресс(занятие, директива.get("objectives", [])),
		"directive": директива.get("directive"),
		# Зачин и обещание — верхним уровнем, а не внутри директивы с грифом
		# «только преподавателю»: их адресат — ученик (#238).
		"course_promise": frappe.db.get_value("LMS Course", курс, "course_promise") or None,
		"lesson_hook": frappe.db.get_value("Course Lesson", lesson, "lesson_hook") or None,
		"start": _состояние_старта(ученик, курс, lesson, занятие.name, сегмент, перенос),
		"course_objectives": курсовая.get("objectives", []),
		"course_directive": курсовая.get("directive"),
		"quiz": {
			"required": политика["quiz_required"],
			"pass_threshold": политика["pass_threshold"],
			"attempts_left": _осталось_попыток(ученик, lesson, политика),
		},
		# Отдельным полем, а не внутри директивы: заметки ведутся об ученике
		# и доступны ему, грифа «не показывать» на них нет. Смешать одно с
		# другим значило бы соврать агенту про режим обращения.
		"student_context": {
			**_заметки(ученик, курс),
			"carried_over": перенос,
			"recent_work": сделанное,
			"closed_reports": итоги,
		},
		# Подсказка «сегодня собираем резюме проекта», а не ограничение:
		# update_artifact принимает любой ключ, и ученик волен забежать вперёд.
		"artifact_blocks": _блоки_урока(ученик, курс, lesson, пространство),
		# Выводы сервера из истории ученика — коды, фразы складывает сервис
		# (learning-services#416).
		"signals": _сигналы_старта(ученик, курс, lesson, занятие, директива, сведения),
		# Домашка прошлого урока — с ответом и журналом, задание текущего —
		# целиком (learning-services#439).
		**домашка.для_старта(ученик, lesson, курс, пространство, полное=True),
	}
	if channel == "web":
		# Шапке веб-чата — место урока в курсе и остаток пробы
		# (learning-services#404). Своему агенту — нет: пробы у него не
		# считаются, программу он берёт `course_outline`, а порядок уроков стоит
		# запросов на каждую главу, и платить за них на каждом старте незачем.
		ответ["lesson"].update(_место_урока(lesson, курс))
		ответ["web_demo"] = пробные_уроки_ученика(ученик)
	# Отметка — после сборки ответа: упади она раньше, итог пропал бы для
	# ученика, так и не дойдя до агента.
	_отметить_показанные(итоги)
	return ответ


@frappe.whitelist(methods=["POST"])
@контракт
def remember(kind: str, key: str, text: str, session: str | None = None) -> dict:
	"""Записывает об ученике то, что пригодится на следующих занятиях.

	Ключ короткий и повторяемый: запись по существующему ключу замещает
	текст. Факт живёт у ученика целиком — роль и отрасль от предмета не
	зависят. Наблюдение и проект привязываются к курсу занятия: учебный
	сценарий одного курса не должен молча приходить в другой (#408).
	"""
	ученик = текущий_пользователь()
	вид = ВИДЫ_ЗАМЕТОК.get((kind or "").strip().lower())
	if not вид:
		raise Отказ(НЕИЗВЕСТНЫЙ_ВИД, "Вид заметки — fact, observation или project", kind=kind)

	# Пустая строка, а не None: ею Frappe хранит незаполненный Link, и фильтр
	# по None искал бы `course is null`, не находя ни одной записи.
	курс = ""
	занятие = None
	if вид in ЗАМЕТКИ_КУРСА:
		if not session:
			raise Отказ(
				ЧУЖОЕ_ЗАНЯТИЕ,
				"Наблюдение и проект записываются в рамках занятия: передайте session",
			)
		занятие = _своё_занятие(session)
		курс = занятие.course

	ключ = (key or "").strip().lower()
	if not ключ:
		# Свой код, а не «неизвестный вид»: вид к этому месту уже распознан,
		# и агент, ветвящийся по коду, стал бы подставлять другой вид вместо
		# того, чтобы дать ключ (lms-platform#209).
		raise Отказ(ПУСТОЙ_КЛЮЧ, "Ключ заметки обязателен", key=key)

	существующая = frappe.db.exists(
		"Agent Student Note", {"student": ученик, "course": курс, "note_key": ключ}
	)
	# Ключи профиля в предел не входят ни сами, ни в счёте прочих. `Why:`
	# ученик с полным набором прочих фактов иначе не смог бы заполнить профиль
	# (learning-services#463). Набор фиксирован, так что предел остаётся
	# конечным: прочие плюс ключи профиля.
	профильный = вид == ЗАМЕТКА_ФАКТ and ключ in КЛЮЧИ_ПРОФИЛЯ
	if not существующая and not профильный:
		отбор = {"student": ученик, "course": курс, "kind": вид}
		if вид == ЗАМЕТКА_ФАКТ:
			отбор["note_key"] = ("not in", tuple(КЛЮЧИ_ПРОФИЛЯ))
		сколько = frappe.db.count("Agent Student Note", отбор)
		предел = лимит_заметок()
		if сколько >= предел:
			raise Отказ(
				ПЕРЕПОЛНЕНО,
				"Заметок уже предельно много: замените запись по существующему ключу",
				limit=предел,
			)

	значения = {
		"text": text,
		"kind": вид,
		"source_session": занятие.name if занятие else None,
	}
	if существующая:
		запись = frappe.get_doc("Agent Student Note", существующая)
		запись.update(значения)
		запись.save(ignore_permissions=True)
	else:
		запись = frappe.get_doc(
			{
				"doctype": "Agent Student Note",
				"student": ученик,
				"course": курс,
				"note_key": ключ,
				**значения,
			}
		).insert(ignore_permissions=True)

	ответ = {"key": запись.note_key, "kind": kind}
	if занятие is not None and занятие.status not in ЗАВЕРШЁННЫЕ:
		# Запоминают посреди занятия — там же напоминание об отметках (#409).
		ответ["objectives_progress"] = _прогресс(занятие)
	return ответ


