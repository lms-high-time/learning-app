@frappe.whitelist(methods=["POST"])
@контракт
def update_artifact(
	course: str,
	artifact: str,
	key: str,
	content: str | None = None,
	clear: bool = False,
	url: str | None = None,
	table=None,
	file_name: str | None = None,
	rows=None,
	delete_rows=None,
	fields=None,
	space: str | None = None,
) -> dict:
	"""Записывает блок артефакта целиком — или очищает его.

	Замещение, а не дописывание: ученик уточняет уже сказанное, и склейка
	превратила бы документ в стенограмму разговора. Сервер проверяет только
	форму — документ и блок есть в схеме, текст непуст; отвечает ли текст
	подсказке автора, смотрит агент: артефакт на зачёт не влияет, и
	подыгрывать здесь нечему.

	`url` — адрес внешнего документа у блока-ссылки (`kind: link`); текст при
	нём необязателен, прежний остаётся.

	`table` — таблица, которую собрал агент, у блока-файла (`kind: file`):
	строки ячеек, формулы строками с `=`. Сервер собирает `xlsx` (или `csv`,
	если блок принимает только его) и кладёт файлом в блок, как загрузку
	ученика. `Why:` текст таблицы в десятки раз дешевле байтов base64 через
	параметры модели, и формулы в файле остаются формулами (#258, #319).
	`file_name` — имя файла, без него — по ключу блока.

	`clear` удаляет блок из документа ученика — текст, ссылку и файл; текст при
	этом не передаётся. `Why:` при смене проекта агенту нечем было убрать старый
	текст — он висел, пока не находилось, чем его заменить (репорт 8qse4ii3dc).
	Очистка — только явным флагом: пустой `content` без него по-прежнему отказ,
	иначе случайная пустая запись стирала бы блок.

	`rows`, `delete_rows`, `fields` — у блока с колонками и полями
	(learning-services#330): строки таблицы документа со своими колонками
	блока, ID строк на удаление, значения полей. Строки без `id` заводит и
	удаляет только блок, который таблицу заводит; остальные дописывают свои
	колонки существующим строкам. Это не замещение, а правка: названные
	клетки меняются, прочие остаются. `content` рядом — заметка к блоку.
	"""
	ученик = текущий_пользователь()
	_требовать_доступ_к_курсу(ученик, course)
	пространство = пространства.пространство_курса(ученик, course, space)
	схема, блок = _блок_схемы(course, artifact, key)
	ключ = блок.block_key
	# Флаг приходит и булевым из JSON, и строкой из формы.
	if clear in (True, 1, "1", "true"):
		if (content or "").strip() or (url or "").strip() or table or rows or delete_rows or fields:
			raise Отказ(
				ОЧИСТКА_С_ТЕКСТОМ,
				"Очистка блока не принимает текст: либо content, либо clear",
				artifact=схема.slug,
				key=ключ,
			)
		return _очистить_блок(ученик, course, пространство, схема, ключ)

	адрес = None
	if (url or "").strip():
		if artifact_files.вид(блок) != artifact_files.ССЫЛКА:
			raise Отказ(
				artifact_files.ВИД_НЕ_ТОТ,
				"Ссылку принимает только блок-ссылка",
				artifact=схема.slug,
				key=ключ,
				kind=artifact_files.вид(блок),
			)
		адрес = artifact_files.проверить_ссылку(url)
	if table:
		return _положить_таблицу(ученик, course, пространство, схема, блок, table, file_name, content)
	if rows or delete_rows or fields:
		return _записать_данные(ученик, course, пространство, схема, ключ, content, rows, delete_rows, fields)
	if not (content or "").strip() and not адрес:
		raise Отказ(ПУСТОЙ_БЛОК, "Блок записывается непустым", artifact=схема.slug, key=ключ)

	документ, строка = _строка_блока(ученик, course, пространство, схема, ключ)
	if (content or "").strip():
		строка.content = content
	if адрес:
		строка.url = адрес
	документ.schema_version = схема.name
	документ.save(ignore_permissions=True)
	return _ответ_записи(схема, ключ, документ)


def _ответ_записи(схема, ключ: str, документ, созданы: list[str] | None = None) -> dict:
	"""Ответ записи блока: заполненность документа и чего не хватает блоку.

	`empty_cells` — где блоку с полями и колонками не хватает обязательных
	значений: `{row, column}` или `{field}`; у прочих блоков пусто. `created` —
	ID строк, которые завела эта запись: по ним агент дописывает колонки.
	"""
	данные = _данные(документ)
	блок = next(б for б in схема.blocks if б.block_key == ключ)
	return {
		"artifact": схема.slug,
		"key": ключ,
		**_заполненность(схема, _содержимое(документ), _вложения(документ), данные),
		"empty_cells": artifact_tables.пустые_клетки(блок, данные, схема.blocks),
		"created": созданы or [],
	}


def _записать_данные(ученик: str, course: str, пространство: str | None, схема, ключ: str, content, rows, delete_rows, fields) -> dict:
	"""Строки и поля блока — в JSON документа; заметка — в текст блока."""
	if (content or "").strip():
		документ, строка = _строка_блока(ученик, course, пространство, схема, ключ)
		строка.content = content
	else:
		# Без заметки строка блока не нужна: данные таблиц общие для блоков
		# и живут в документе, а пустой текст блока doctype не примет.
		документ = _документ_ученика(ученик, course, пространство, схема)
	прежние = _данные(документ)
	было = {с["id"] for т in прежние["tables"].values() for с in т}
	новые = artifact_tables.записать(
		схема.blocks, ключ, прежние, rows=rows, delete_rows=delete_rows, fields=fields
	)
	документ.data = json.dumps(новые, ensure_ascii=False)
	документ.schema_version = схема.name
	документ.save(ignore_permissions=True)
	стало = [с["id"] for т in новые["tables"].values() for с in т]
	return _ответ_записи(схема, ключ, документ, [i for i in стало if i not in было])


@frappe.whitelist(methods=["POST"])
@контракт
def upload_artifact_file(
	course: str,
	artifact: str,
	key: str,
	file_name: str | None = None,
	content: str | None = None,
	space: str | None = None,
) -> dict:
	"""Кладёт файл ученика в блок-файл документа.

	Файл приходит полем `file` формы — так его шлёт страница «Мои документы»,
	или парой `file_name` + `content` (base64) — так его передаёт MCP-сервис из
	окна загрузки в чате (#317). Модель байтов не видит ни в одном случае: окно
	чата зовёт скрытый от неё инструмент. Файл приватный, привязан к документу
	ученика, и права на него Frappe берёт у документа: видит только ученик.
	Новый файл замещает прежний.
	"""
	ученик = текущий_пользователь()
	файл = frappe.request.files.get("file") if frappe.request and frappe.request.files else None
	if файл:
		имя, данные = файл.filename or "", файл.stream.read()
	else:
		имя, данные = file_name or "", artifact_files.из_base64(content)
	пространство = пространства.пространство_курса(ученик, course, space)
	return _положить_файл(ученик, course, пространство, artifact, key, имя, данные)


def _положить_файл(ученик: str, course: str, пространство: str | None, artifact: str, key: str, имя: str, данные: bytes) -> dict:
	_требовать_доступ_к_курсу(ученик, course)
	схема, блок = _блок_схемы(course, artifact, key)
	ключ = блок.block_key
	тип = artifact_files.проверить_файл(блок, имя, данные, artifact=схема.slug, key=ключ)

	документ, строка = _строка_блока(ученик, course, пространство, схема, ключ)
	if not документ.name:
		# Файл привязывается к документу по имени — оно появляется при записи.
		# `Why:` не `is_new()`: у документа, собранного `frappe.get_doc({...})`,
		# нет `__islocal`, и проверка отвечала «не новый» — файл вставлялся без
		# имени документа, и Frappe снимал привязку (#343).
		документ.schema_version = схема.name
		документ.insert(ignore_permissions=True)
		строка = next(с for с in документ.blocks if с.block_key == ключ)
	прежний = строка.file
	новый = artifact_files.сохранить_файл(документ, имя, данные)
	строка.file = новый.name
	строка.preview = artifact_files.срез(данные, тип)
	документ.schema_version = схема.name
	документ.save(ignore_permissions=True)
	artifact_files.удалить_файл(прежний)

	заполнено = _заполненность(схема, _содержимое(документ), _вложения(документ), _данные(документ))
	return {
		"artifact": схема.slug,
		"key": ключ,
		"file": artifact_files.сведения_о_файлах([новый.name])[новый.name],
		"preview": строка.preview or None,
		**заполнено,
	}


def _положить_таблицу(
	ученик: str,
	course: str,
	пространство: str | None,
	схема,
	блок,
	table,
	file_name: str | None,
	content: str | None,
) -> dict:
	"""Таблица агента — файлом в блок-файл; текст рядом, если передан."""
	ключ = блок.block_key
	if artifact_files.вид(блок) != artifact_files.ФАЙЛ:
		raise Отказ(
			artifact_files.ВИД_НЕ_ТОТ,
			"Таблицу файлом принимает только блок-файл",
			artifact=схема.slug,
			key=ключ,
			kind=artifact_files.вид(блок),
		)
	тип = artifact_files.тип_для_таблицы(блок)
	строки = artifact_files.строки_таблицы(table)
	имя = (file_name or "").strip() or ключ
	if artifact_files.расширение(имя) != тип:
		имя = f"{имя}.{тип}"
	_положить_файл(
		ученик, course, пространство, схема.slug, ключ, имя, artifact_files.собрать_таблицу(строки, тип)
	)
	документ, строка = _строка_блока(ученик, course, пространство, схема, ключ)
	if (content or "").strip():
		строка.content = content
		документ.schema_version = схема.name
		документ.save(ignore_permissions=True)
	return _ответ_записи(схема, ключ, документ)


def _блок_схемы(course: str, artifact: str, key: str):
	"""Действующая схема и её блок по ключу; нет блока — отказ."""
	схема = _действующая_схема(course, artifact)
	ключ = нормализовать_ключ(key)
	блок = next((б for б in схема.blocks if б.block_key == ключ), None)
	if блок is None:
		raise Отказ(
			БЛОК_НЕ_НАЙДЕН, "В этом документе нет такого блока", artifact=схема.slug, key=key
		)
	return схема, блок


def _строка_блока(ученик: str, course: str, пространство: str | None, схема, ключ: str):
	"""Документ ученика и строка блока в нём; чего нет — заводится, не записываясь."""
	документ = _документ_ученика(ученик, course, пространство, схема)
	строка = next((с for с in документ.blocks if с.block_key == ключ), None)
	if строка is None:
		строка = документ.append("blocks", {"block_key": ключ})
	return документ, строка


def _документ_ученика(ученик: str, course: str, пространство: str | None, схема):
	"""Документ ученика по схеме в его пространстве; нет — заводится, не записываясь."""
	return _экземпляр(ученик, course, схема.slug, пространство) or _новый_документ(
		ученик, course, схема, пространство
	)


def _новый_документ(ученик: str, course: str, схема, пространство: str | None):
	return frappe.get_doc(
		{
			"doctype": "Agent Student Artifact",
			"student": ученик,
			"course": course,
			"artifact": схема.slug,
			"organization": пространство,
		}
	)


def _очистить_блок(ученик: str, course: str, пространство: str | None, схема, ключ: str) -> dict:
	"""Удаляет строку блока из документа ученика — с файлом; ответ — как у записи.

	Блока нет или документ ещё не заводился — очищать нечего, и это не отказ:
	результат тот же, что после удаления.
	"""
	документ = _экземпляр(ученик, course, схема.slug, пространство)
	строка = next((с for с in документ.blocks if с.block_key == ключ), None) if документ else None
	блок = next(б for б in схема.blocks if б.block_key == ключ)
	файл = None
	if строка:
		файл = строка.file
		документ.remove(строка)
	if документ and artifact_tables.спек(блок):
		документ.data = json.dumps(
			artifact_tables.очистить(схема.blocks, ключ, документ.data), ensure_ascii=False
		)
	if документ and (строка or artifact_tables.спек(блок)):
		документ.schema_version = схема.name
		документ.save(ignore_permissions=True)
		artifact_files.удалить_файл(файл)
	if документ:
		return _ответ_записи(схема, ключ, документ)
	return {
		"artifact": схема.slug,
		"key": ключ,
		**_заполненность(схема, {}, {}),
		"empty_cells": [],
		"created": [],
	}


@frappe.whitelist(methods=["POST"])
@контракт
def report_outcomes(session: str, outcomes) -> dict:
	"""Отчёт о покрытии целей урока.

	Сдаётся до квиза и до закрытия урока: `request_quiz` и `complete_lesson`
	без него отказывают. Состав сверяется с целями действующей директивы —
	без сверки обязательный отчёт вырождается в пустой список.
	"""
	занятие = _своё_занятие(session)
	цели = _цели_урока(занятие.lesson)
	сданные = {}
	for пункт in список(outcomes):
		цель = (пункт.get("objective") or "").strip()
		статус = (пункт.get("status") or "").strip()
		if статус not in СТАТУСЫ_ЦЕЛЕЙ:
			raise Отказ(
				ЦЕЛИ_НЕ_СОВПАЛИ,
				"Статус цели должен быть covered, touched или skipped",
				objective=цель,
				status=статус,
			)
		продолжить = (пункт.get("resume_from") or "").strip()
		if len(продолжить) > ДЛИНА_ПРОДОЛЖЕНИЯ:
			raise Отказ(
				ЦЕЛИ_НЕ_СОВПАЛИ,
				f"«С чего продолжать» — одна фраза, не длиннее {ДЛИНА_ПРОДОЛЖЕНИЯ} знаков",
				objective=цель,
				field="resume_from",
			)
		сданные[цель] = (статус, продолжить or None)

	if set(сданные) != set(цели):
		raise Отказ(
			ЦЕЛИ_НЕ_СОВПАЛИ,
			"Отчёт должен покрывать ровно цели урока",
			missing=sorted(set(цели) - set(сданные)),
			unexpected=sorted(set(сданные) - set(цели)),
		)

	# Порядок целей — из директивы, а не из отчёта: строки таблицы читаются в
	# том же порядке, в каком автор задумывал урок.
	занятие.outcomes = []
	for цель in цели:
		статус, продолжить = сданные[цель]
		занятие.append("outcomes", {"objective": цель, "status": статус, "resume_from": продолжить})
	занятие.save(ignore_permissions=True)
	занятие.записать_событие(СОБЫТИЕ_ОТМЕТКА, "отчёт по целям урока")

	return {
		"session": session,
		"reported": len(цели),
		"empty_blocks": _пустые_блоки_урока(
			занятие.student, занятие.course, занятие.lesson, занятие.organization or None
		),
	}


