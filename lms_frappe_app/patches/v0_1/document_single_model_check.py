"""Проверка перед `document_single_model` (learning-services#515): действующие
схемы документов существующих курсов переводятся в разделы релиза.

Патч `pre_model_sync`: идёт раньше синхронизации схемы доктайпов. Не
переводится хоть одна — патч падает и перечисляет все, а `migrate` останавливается
до синхронизации: ни схема доктайпов, ни данные не тронуты, и сторож выкатки не
переключает релиз. Только чтение прямым SQL (`document_single_model.проверить`);
повторный запуск после перевода колонки `spec` не находит и проходит.

`Why:` проверка в самом `document_single_model` (`post_model_sync`) срабатывала
после синхронизации: при её отказе схема доктайпов уже новая, а код откаченной
выкатки — старый, и он ломался на ней.
"""

import frappe

from lms_frappe_app.patches.v0_1.document_single_model import проверить


def execute():
	беды = проверить()
	if беды:
		raise frappe.ValidationError(
			"document_single_model_check: действующие схемы существующих курсов не переводятся в "
			"разделы релиза, схема доктайпов и данные не тронуты:\n" + "\n".join(беды)
		)
	print("document_single_model_check: действующие схемы документов переводятся в разделы релиза")
