"""Требования к паролю поверх политики Frappe (learning-services#666).

Frappe оценивает пароль одним zxcvbn: семь символов с баллом 2 проходят, про
название платформы оценка не знает, утечек не проверяет (самооценка ASVS,
learning-services#664: 6.2.1, 6.2.11, 6.2.12). Здесь — длина, контекстные
слова и проверка по базе утёкших паролей. Пути, где задаётся пароль:

- ссылка из письма и смена пароля вошедшим — `access.update_password`: он
  пишет пароль мимо документа `User`, и хук документа его не видит;
- desk, REST и вставка пользователя с паролем — хук `before_validate`
  пользователя. До `validate`: там Frappe переносит пароль из `new_password` в
  приватное поле контроллера.

Регистрация формой пароля не принимает: Frappe и Learning заводят аккаунт со
случайным паролем и флагом `ignore_password_policy`, а свой пароль человек
задаёт по ссылке из письма — через `update_password`. Вход через Google
тоже ставит случайный пароль (56 шестнадцатеричных знаков), но без флага: он
проходит все проверки, а вход от проверки не зависит — см. `утёк`.
"""

import hashlib
from collections.abc import Iterable

import frappe
import requests
from frappe.utils import cint
from frappe.utils.password_strength import test_password_strength

#: Минимум длины. `Why:` ASVS 6.2.1 (L1) требует не меньше 8 и советует 15;
#: 12 — граница NIST SP 800-63B-4 для пароля как единственного фактора: у
#: учеников второго фактора нет. Длиннее — Frappe ограничивает 512 символами.
МИНИМУМ_ДЛИНЫ = 12

#: Контекстные слова (ASVS 6.2.11): то, с чего начнёт подбор тот, кто знает,
#: на какой сайт идёт, — название платформы, компании и движка. Все уходят в
#: оценку zxcvbn как «слова пользователя»: пароль из них и цифр получает
#: низкий балл, в том числе с заменой букв цифрами и задом наперёд.
КОНТЕКСТНЫЕ_СЛОВА = (
	"cenda",
	"ценда",
	"high time",
	"hightime",
	"хай тайм",
	"хайтайм",
	"lms",
	"learning",
	"agent learning",
	"frappe",
)

#: Названия, которые в пароле запрещены целиком, где бы ни стояли. `Why:`
#: zxcvbn снижает балл, но длинный пароль с названием внутри всё равно может
#: набрать порог. Только названия от пяти букв: короткое `lms` и обычные
#: слова вроде `learning` запрет вхождения ловил бы в посторонних словах
#: («realms»), их оценивает только zxcvbn.
ЗАПРЕЩЁННЫЕ_НАЗВАНИЯ = ("cenda", "ценда", "hightime", "хайтайм")

#: Цифры и знаки, которыми заменяют буквы, — для поиска названий.
_ЗАМЕНЫ = str.maketrans({"0": "o", "1": "i", "3": "e", "4": "a", "@": "a", "$": "s", "5": "s"})

#: Балл zxcvbn, если в System Settings порог не задан (политика выключена).
БАЛЛ_ПО_УМОЛЧАНИЮ = 2

#: Range API Have I Been Pwned: уходят только первые 5 знаков SHA-1 пароля
#: (k-anonymity), ответ — все хвосты хешей с этим началом.
АДРЕС_УТЕЧЕК = "https://api.pwnedpasswords.com/range/"
#: Секунды. `Why:` проверка стоит на пути смены пароля и входа через Google;
#: обычный ответ сервиса — десятки миллисекунд, ждать дольше трёх секунд —
#: держать человека у формы ради проверки, которую всё равно пропустим.
ТАЙМАУТ_УТЕЧЕК = 3

КОРОТКИЙ = f"Пароль должен быть не короче {МИНИМУМ_ДЛИНЫ} символов."
С_НАЗВАНИЕМ = "Пароль не должен содержать название платформы."
ПРОСТОЙ = "Пароль слишком простой: добавьте ещё слов, не связанных с вами и платформой."
УТЁК = "Этот пароль встречается в утечках данных — выберите другой."

#: Поля пользователя, которые Frappe передаёт в zxcvbn (`User.password_strength_test`).
ПОЛЯ_ПОЛЬЗОВАТЕЛЯ = ("first_name", "middle_name", "last_name", "email", "birth_date")


def проверить_пароль(пароль: str, сведения: Iterable = ()) -> None:
	"""Отказ `ValidationError`, если пароль не годится; `сведения` — имя,
	почта и прочее о самом пользователе, для оценки zxcvbn."""
	if причина := причина_отказа(пароль, сведения):
		frappe.throw(причина, title="Пароль не подходит")


def причина_отказа(пароль: str, сведения: Iterable = ()) -> str | None:
	"""Текст отказа или `None`. Проверки — от дешёвой к сетевой: до сервиса
	утечек доходит только пароль, прошедший остальные."""
	if len(пароль) < МИНИМУМ_ДЛИНЫ:
		return КОРОТКИЙ
	if есть_название(пароль):
		return С_НАЗВАНИЕМ
	слова = [*КОНТЕКСТНЫЕ_СЛОВА, *(str(с) for с in сведения if с)]
	порог = cint(frappe.get_system_settings("minimum_password_score")) or БАЛЛ_ПО_УМОЛЧАНИЮ
	if test_password_strength(пароль, user_inputs=слова).get("score", 0) < порог:
		return ПРОСТОЙ
	if утёк(пароль):
		return УТЁК
	return None


def есть_название(пароль: str) -> bool:
	"""Есть ли в пароле название платформы — без регистра, разделителей и
	замены букв цифрами: `C3nda-2026` и `High.Time` тоже считаются."""
	слитно = "".join(знак for знак in пароль.lower().translate(_ЗАМЕНЫ) if знак.isalnum())
	return any(название in слитно for название in ЗАПРЕЩЁННЫЕ_НАЗВАНИЯ)


def утёк(пароль: str) -> bool:
	"""Встречается ли пароль в базе утечек Have I Been Pwned.

	Сервису уходят первые 5 знаков SHA-1, а не пароль и не хеш целиком; с
	`Add-Padding` ответ дополнен фиктивными хвостами с числом 0, и по его
	размеру не понять, что искали.

	Сервис недоступен — пароль считается не утёкшим. `Why:` смена пароля по
	ссылке — единственный путь вернуть доступ, и закрывать его на время сбоя
	чужого сервиса хуже, чем пропустить пароль, уже прошедший длину и zxcvbn;
	отказ при сбое — ещё и способ заблокировать всем смену пароля. Сбой
	пишется в журнал приложения.
	"""
	# SHA-1 — формат базы HIBP, а не хеширование пароля для хранения.
	хеш = hashlib.sha1(пароль.encode(), usedforsecurity=False).hexdigest().upper()
	try:
		ответ = requests.get(
			АДРЕС_УТЕЧЕК + хеш[:5],
			headers={"Add-Padding": "true", "User-Agent": "Cenda password check"},
			timeout=ТАЙМАУТ_УТЕЧЕК,
		)
		ответ.raise_for_status()
	except requests.RequestException as ошибка:
		frappe.logger("lms_frappe_app.passwords").warning(f"Проверка пароля по утечкам пропущена: {ошибка!r}")
		return False
	return есть_в_диапазоне(ответ.text, хеш[5:])


def есть_в_диапазоне(ответ: str, хвост: str) -> bool:
	"""Есть ли хвост хеша в ответе range API: строки `ХВОСТ:ЧИСЛО`. Число 0 —
	у фиктивных строк дополнения, такая строка утечкой не считается."""
	for строка in ответ.splitlines():
		свой, _, число = строка.strip().partition(":")
		if свой.upper() == хвост and cint(число) > 0:
			return True
	return False


def сведения_пользователя(пользователь: str) -> tuple:
	return frappe.db.get_value("User", пользователь, ПОЛЯ_ПОЛЬЗОВАТЕЛЯ) or ()


def пароль_к_проверке(документ) -> str | None:
	"""Пароль, который задаётся документу пользователя, если его надо проверить.

	`ignore_password_policy` ставят регистрация Frappe и Learning: случайный
	пароль, которого человек не знает, — его задаст по ссылке из письма.
	"""
	if документ.flags.ignore_password_policy:
		return None
	return документ.get("new_password") or None


def проверить_пароль_пользователя(doc, method=None) -> None:
	"""`before_validate` пользователя: пароль из desk, REST или вставки.

	В тестах не проверяет — как и `User.password_strength_test` Frappe:
	тестовые записи Frappe и Learning заводят пользователей с простыми
	паролями, а сеть тестам не положена.
	"""
	if frappe.in_test:
		return
	if пароль := пароль_к_проверке(doc):
		проверить_пароль(пароль, [doc.get(поле) for поле in ПОЛЯ_ПОЛЬЗОВАТЕЛЯ])
