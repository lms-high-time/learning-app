"""Находки проверки карты и изменения против действующей версии — поля
запроса публикации (learning-services#560).

Публикатор передаёт их вместе с релизом: `findings` — замечания проверки
карты курса, `changes` — пути, которыми собранный релиз отличается от
действующей версии на платформе. В формат релиза они не входят и на дайджест
не влияют; сервер проверяет только форму и хранит их у записи новой версии как
есть. Что считать находкой и как сравнивать — дело конвейера курса.

Модуль к базе не ходит: проверка формы — чистые функции.
"""

import json

from lms_frappe_app.agent_learning.errors import Отказ

НЕВЕРНЫ = "release_findings_invalid"

#: Пределы формы — протокол запроса публикации: конвейер обрезает до них сам.
НАХОДОК_НЕ_БОЛЬШЕ = 500
СООБЩЕНИЕ_НЕ_ДЛИННЕЕ = 1000
ПУТЕЙ_НЕ_БОЛЬШЕ = 2000
#: Код, уровень, цель находки и путь отличия — ключи и коды, а не текст.
КЛЮЧ_НЕ_ДЛИННЕЕ = 200
ПУТЬ_НЕ_ДЛИННЕЕ = 1000

#: Поля находки: обязательно ли поле, и предел длины.
ПОЛЯ_НАХОДКИ = {
	"code": (True, КЛЮЧ_НЕ_ДЛИННЕЕ),
	"severity": (True, КЛЮЧ_НЕ_ДЛИННЕЕ),
	"target": (False, КЛЮЧ_НЕ_ДЛИННЕЕ),
	"message": (True, СООБЩЕНИЕ_НЕ_ДЛИННЕЕ),
}
#: Знаки отличия: появилось, исчезло, изменилось.
ЗНАКИ = ("+", "-", "~")


def находки(значение) -> list[dict] | None:
	"""Находки по форме — или отказ `release_findings_invalid`; не переданы — `None`.

	Находка — `{code, severity, target, message}`: `code`, `severity` и
	`message` — непустые строки, `target` — ключ узла карты или урока; пусто
	и `null` — находка без цели (хранится `null`). Других полей нет.
	"""
	if значение is None:
		return None
	значение = _json(значение, "findings")
	if not isinstance(значение, list):
		_отказ("findings", "список находок")
	if len(значение) > НАХОДОК_НЕ_БОЛЬШЕ:
		_отказ("findings", f"не больше {НАХОДОК_НЕ_БОЛЬШЕ} находок, передано {len(значение)}")
	собранное = []
	for номер, находка in enumerate(значение):
		где = f"findings[{номер}]"
		if not isinstance(находка, dict):
			_отказ(где, "находка — объект {code, severity, target, message}")
		if лишние := sorted(set(находка) - set(ПОЛЯ_НАХОДКИ)):
			_отказ(где, "лишние поля: " + ", ".join(map(str, лишние)))
		запись = {}
		for поле, (нужно, предел) in ПОЛЯ_НАХОДКИ.items():
			текст = находка.get(поле)
			if текст is None or (текст == "" and not нужно):
				if нужно:
					_отказ(f"{где}.{поле}", "обязательное поле")
				запись[поле] = None
				continue
			запись[поле] = _строка(текст, f"{где}.{поле}", предел)
		собранное.append(запись)
	return собранное


def изменения(значение) -> dict | None:
	"""Изменения по форме — или отказ `release_findings_invalid`; не переданы — `None`.

	`{against, paths, truncated}`: `against` — номер версии, с которой
	сравнивали, или `null` — сравнения не было, и тогда `paths` пуст; `paths`
	— `[{op, path}]`, `op` — `+`, `-` или `~`; `truncated` — путей было больше
	и список обрезан. Других полей нет.
	"""
	if значение is None:
		return None
	значение = _json(значение, "changes")
	if not isinstance(значение, dict):
		_отказ("changes", "объект {against, paths, truncated}")
	if лишние := sorted(set(значение) - {"against", "paths", "truncated"}):
		_отказ("changes", "лишние поля: " + ", ".join(map(str, лишние)))
	if "against" not in значение:
		_отказ("changes.against", "обязательное поле: номер версии или null")
	против = значение["against"]
	if против is not None and (isinstance(против, bool) or not isinstance(против, int) or против < 1):
		_отказ("changes.against", "номер версии — целое от 1 или null")
	пути = значение.get("paths", [])
	if not isinstance(пути, list):
		_отказ("changes.paths", "список отличий")
	if len(пути) > ПУТЕЙ_НЕ_БОЛЬШЕ:
		_отказ("changes.paths", f"не больше {ПУТЕЙ_НЕ_БОЛЬШЕ} путей, передано {len(пути)}: остальные отрезать и передать truncated")
	if против is None and пути:
		_отказ("changes.paths", "без against сравнения не было — путей быть не может")
	обрезано = значение.get("truncated", False)
	if not isinstance(обрезано, bool):
		_отказ("changes.truncated", "true или false")
	собранное = []
	for номер, отличие in enumerate(пути):
		где = f"changes.paths[{номер}]"
		if not isinstance(отличие, dict) or set(отличие) != {"op", "path"}:
			_отказ(где, "отличие — объект {op, path}")
		if отличие["op"] not in ЗНАКИ:
			_отказ(f"{где}.op", "знак отличия — +, - или ~")
		собранное.append({"op": отличие["op"], "path": _строка(отличие["path"], f"{где}.path", ПУТЬ_НЕ_ДЛИННЕЕ)})
	return {"against": против, "paths": собранное, "truncated": обрезано}


def _json(значение, где: str):
	"""Строка — JSON поля запроса: форма POST передаёт вложенное строкой."""
	if not isinstance(значение, str):
		return значение
	try:
		return json.loads(значение)
	except ValueError:
		_отказ(где, "не JSON")


def _строка(значение, где: str, предел: int) -> str:
	if not isinstance(значение, str) or not значение.strip():
		_отказ(где, "непустая строка")
	if len(значение) > предел:
		_отказ(где, f"не длиннее {предел} знаков, передано {len(значение)}")
	return значение


def _отказ(где: str, что: str):
	raise Отказ(НЕВЕРНЫ, f"{где}: {что}", where=где)
