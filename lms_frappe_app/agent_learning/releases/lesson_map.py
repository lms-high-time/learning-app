"""Карта урока для кабинета автора (learning-services#560).

Карта релиза (`map`) непрозрачна: её форму задаёт компилятор курса, приложение
её не проверяет и правил по ней не принуждает. Кабинет показывает автору срез
карты одного урока — ту же карту, оставленную узлами урока:

- `lesson` — урок карты (`map.lessons.<урок>`) как есть;
- `decisions` — решения урока (`decisions` урока карты);
- `results` — результаты его решений (`result` решения);
- `situations` — ситуации практики и зачёта урока (`situations`, `quiz`);
- `theses` — тезисы, на которые опираются решения и требования результатов
  (`relies_on`), и тезисы из причин ошибок и нарушений (`thesis`);
- `misconceptions` — заблуждения из причин ошибок и нарушений
  (`misconception`) и опровергнутые тезисами урока (`refutes`);
- `goals` — цели, которым служат решения урока (`serves`);
- `refs` — узлы, на которые ссылаются ситуации урока: решения и варианты
  наборов, ошибки и требования ловушек — у ситуации бывают наборы решений
  других уроков.

Узел, который не словарь, и ссылка не строкой пропускаются: срез строится и по
карте любой формы, а неизвестные поля узлов остаются в них как есть.

Срезы всех уроков читаются из снимка один раз на релиз и живут в
`frappe.cache` по имени и дайджесту релиза, как узлы карты (`places`): снимок
большой, а релиз неизменяем.
"""

import frappe

from lms_frappe_app.agent_learning.releases import index

#: Ключ кэша срезов карты по урокам: к нему дописываются имя и дайджест релиза.
КЭШ_СРЕЗОВ = "lms_frappe_app:release_lesson_maps"
#: Срезы живут в кэше сутки: релиз неизменяем, срок — против мусора удалённых.
КЭШ_СРЕЗОВ_ЖИВЁТ = 24 * 60 * 60

#: Коллекции карты, узлы которых входят в срез урока по своему ключу.
КОЛЛЕКЦИИ = ("decisions", "results", "situations", "theses", "misconceptions", "goals")


def срезы(релиз: str, дайджест: str) -> dict[str, dict]:
	"""Ключ урока карты → его срез; читается из снимка один раз на релиз."""
	ключ = ключ_кэша(релиз, дайджест)
	значение = frappe.cache.get_value(ключ)
	if значение is None:
		карта = index.снимок(релиз).get("map")
		уроки = _словарь(_словарь(карта).get("lessons"))
		значение = {урок: срез(карта, урок) for урок in уроки if isinstance(уроки[урок], dict)}
		frappe.cache.set_value(ключ, значение, expires_in_sec=КЭШ_СРЕЗОВ_ЖИВЁТ)
	return значение


def ключ_кэша(релиз: str, дайджест: str) -> str:
	"""Ключ кэша срезов релиза — с дайджестом, по той же причине, что `places.ключ_кэша`."""
	return f"{КЭШ_СРЕЗОВ}:{релиз}:{дайджест}"


def срез(карта, урок: str) -> dict | None:
	"""Срез карты урока `урок`; урока в карте нет — `None`."""
	карта = _словарь(карта)
	урок_карты = _словарь(карта.get("lessons")).get(урок)
	if not isinstance(урок_карты, dict):
		return None
	решения = _узлы(карта, "decisions", _ссылки(урок_карты.get("decisions")))
	результаты = _узлы(карта, "results", [р.get("result") for р in решения.values()])
	ситуации = _узлы(
		карта, "situations", _ссылки(урок_карты.get("situations")) + _ссылки(урок_карты.get("quiz"))
	)
	требования = [т for р in результаты.values() for т in _словари(р.get("requirements")).values()]
	ошибки = [о for р in решения.values() for в in _варианты(р).values() for о in _словари(в.get("errors")).values()]
	причины = [п for о in ошибки for п in _список(о.get("causes"))]
	причины += [п for т in требования for п in _список(_словарь(т.get("violation")).get("causes"))]
	причины = [п for п in причины if isinstance(п, dict)]
	тезисы = _узлы(
		карта,
		"theses",
		[т for у in [*решения.values(), *требования] for т in _ссылки(у.get("relies_on"))]
		+ [п.get("thesis") for п in причины],
	)
	заблуждения = _узлы(
		карта,
		"misconceptions",
		[п.get("misconception") for п in причины]
		+ [з for т in тезисы.values() for з in _ссылки(т.get("refutes"))],
	)
	return {
		"lesson": урок_карты,
		"decisions": решения,
		"results": результаты,
		"situations": ситуации,
		"theses": тезисы,
		"misconceptions": заблуждения,
		"goals": _узлы(карта, "goals", [р.get("serves") for р in решения.values()]),
		"refs": _ссылки_ситуаций(карта, ситуации.values()),
	}


def узлы(срез_урока: dict | None) -> set[str]:
	"""Ключи узлов среза урока: решения с вариантами и ошибками, результаты с
	требованиями, ситуации, тезисы и заблуждения. Цели и узлы `refs` — не
	урока: они общие для курса или других уроков."""
	ключи: set[str] = set()
	if not срез_урока:
		return ключи
	for коллекция in ("decisions", "results", "situations", "theses", "misconceptions"):
		ключи |= set(срез_урока[коллекция])
	for решение in срез_урока["decisions"].values():
		for вариант_ключ, вариант in _варианты(решение).items():
			ключи.add(вариант_ключ)
			ключи |= set(_словари(вариант.get("errors")))
	for результат in срез_урока["results"].values():
		ключи |= set(_словари(результат.get("requirements")))
	return ключи


def путь_урока(путь: str, урок: str, срез_урока: dict | None) -> bool:
	"""Относится ли путь отличий релиза (`changes.paths[].path`) к уроку.

	Пути — как их печатает сравнение релизов конвейера: ключи словарей через
	точку, элемент списка с ключом — в скобках. Урока — сам урок релиза
	(`lessons[<урок>]`), его срез пакета агента (`agent.lessons.<урок>`), урок
	карты (`map.lessons.<урок>`) и узлы его среза в коллекциях карты
	(`map.<коллекция>.<узел>`), кроме целей. Ключи узлов бывают с точкой,
	поэтому путь сверяется с ключами среза, а не режется по точкам.
	"""
	for начало in (f"lessons[{урок}]", f"agent.lessons.{урок}", f"map.lessons.{урок}"):
		if _под(путь, начало):
			return True
	if not срез_урока or not путь.startswith("map."):
		return False
	коллекция, _, хвост = путь[len("map.") :].partition(".")
	if коллекция == "goals" or коллекция not in КОЛЛЕКЦИИ:
		return False
	return any(_под(хвост, узел) for узел in срез_урока[коллекция])


def _под(путь: str, начало: str) -> bool:
	return путь == начало or путь.startswith(начало + ".") or путь.startswith(начало + "[")


def _ссылки_ситуаций(карта: dict, ситуации) -> dict[str, dict]:
	"""Узлы, на которые ссылаются ситуации: решения и варианты наборов, ошибки и
	требования ловушек — из всей карты. Решение — без вариантов, вариант — без
	ошибок: нужны их тексты, а вложенное лежит в срезе своего урока."""
	нужны = set()
	for ситуация in ситуации:
		for набор in _список(ситуация.get("sets")):
			if isinstance(набор, dict):
				нужны |= {набор.get("decision"), набор.get("expected")}
		нужны |= set(_ссылки(ситуация.get("traps")))
	if not нужны:
		return {}
	найдено = {}
	for ключ, решение in _словари(карта.get("decisions")).items():
		if ключ in нужны:
			найдено[ключ] = _без(решение, "variants")
		for вариант_ключ, вариант in _варианты(решение).items():
			if вариант_ключ in нужны:
				найдено[вариант_ключ] = _без(вариант, "errors")
			for ошибка_ключ, ошибка in _словари(вариант.get("errors")).items():
				if ошибка_ключ in нужны:
					найдено[ошибка_ключ] = ошибка
	for результат in _словари(карта.get("results")).values():
		for ключ, требование in _словари(результат.get("requirements")).items():
			if ключ in нужны:
				найдено[ключ] = требование
	return найдено


def _узлы(карта: dict, коллекция: str, ключи: list) -> dict[str, dict]:
	"""Узлы коллекции по ключам — по порядку ключей, без повторов и пропусков."""
	узлы_коллекции = _словари(карта.get(коллекция))
	return {к: узлы_коллекции[к] for к in dict.fromkeys(ключи) if isinstance(к, str) and к in узлы_коллекции}


def _без(узел: dict, поле: str) -> dict:
	return {к: в for к, в in узел.items() if к != поле}


def _варианты(решение: dict) -> dict[str, dict]:
	return _словари(решение.get("variants"))


def _словари(значение) -> dict[str, dict]:
	"""Словарь узлов: записи, значение которых — словарь."""
	return {str(к): в for к, в in _словарь(значение).items() if isinstance(в, dict)}


def _словарь(значение) -> dict:
	return значение if isinstance(значение, dict) else {}


def _список(значение) -> list:
	return значение if isinstance(значение, list) else []


def _ссылки(значение) -> list[str]:
	return [к for к in _список(значение) if isinstance(к, str)]
