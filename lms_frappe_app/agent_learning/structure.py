"""Порядок глав и уроков: чтение и запись.

Общий модуль для учебного потока и авторинга — обе стороны обязаны видеть
курс одинаково. Вторая копия этой логики разъехалась бы в первый же месяц:
ученик шёл бы по одному порядку, куратор правил другой.
"""

import frappe

from lms_frappe_app.agent_learning.errors import Отказ

ПОРЯДОК_НЕ_СОВПАЛ = "order_mismatch"

#: Дочерняя таблица, хранящая порядок, — своя у курса и у главы.
ТАБЛИЦА_ПОРЯДКА = {"LMS Course": ("chapters", "chapter"), "Course Chapter": ("lessons", "lesson")}


def главы_курса(курс: str) -> list[dict]:
	"""Главы курса по порядку — тем же правилом, что и уроки."""
	имена = _в_порядке(
		frappe.get_all("Chapter Reference", filters={"parent": курс}, pluck="chapter", order_by="idx asc"),
		frappe.get_all("Course Chapter", filters={"course": курс}, pluck="name"),
	)
	названия = (
		{
			глава.name: глава.title
			for глава in frappe.get_all(
				"Course Chapter", filters={"name": ("in", имена)}, fields=["name", "title"]
			)
		}
		if имена
		else {}
	)
	return [{"name": имя, "title": названия.get(имя)} for имя in имена]


def уроки_курса(курс: str) -> list[str]:
	"""Уроки курса в том порядке, в каком их показывает браузер.

	`Why:` порядок глав и уроков Frappe Learning хранит в дочерних таблицах
	`Chapter Reference` и `Lesson Reference`, а не в полях `course`/`chapter`:
	у самих записей `idx` всегда ноль. Сортировка по нему давала случайный
	порядок — а от него зависит, какой урок ученик получит следующим.

	Прямые ссылки остаются запасным путём: курс, собранный импортом или
	миграцией, может не иметь строк-ссылок, и терять его уроки нельзя.
	"""
	return [урок for глава in уроки_по_главам(курс) for урок in глава["lessons"]]


def уроки_по_главам(курс: str) -> list[dict]:
	"""Главы курса с их уроками — тем же порядком, что у `уроки_курса`.

	`Why:` кому нужна и структура, и плоский порядок, иначе спрашивал базу
	дважды и потом выяснял принадлежность урока главе запросом на урок. Здесь
	принадлежность известна по построению и ничего не стоит.
	"""
	return [
		{**глава, "lessons": уроки_главы(глава["name"])} for глава in главы_курса(курс)
	]


def уроков_в_курсах(курсы: list[str]) -> dict[str, int]:
	"""Сколько уроков в каждом курсе — четырьмя запросами на весь список.

	`Why:` перечень курсов собирал порядок глав и уроков заново для каждого
	курса, и полсотни курсов стоили больше двухсот обходов базы.
	"""
	return {курс: len(уроки) for курс, уроки in уроки_курсов(курсы).items()}


def уроки_курсов(курсы: list[str]) -> dict[str, list[str]]:
	"""Уроки каждого курса по порядку — четырьмя запросами на весь список.

	Порядок тот же, что у `уроки_курса`: тот же союз строк-ссылок и прямых полей.
	"""
	if not курсы:
		return {}

	ссылки_глав = _сгруппировать(
		frappe.get_all(
			"Chapter Reference",
			filters={"parent": ("in", курсы)},
			fields=["parent", "chapter"],
			order_by="idx asc",
		),
		"parent",
		"chapter",
	)
	прямые_главы = _сгруппировать(
		frappe.get_all(
			"Course Chapter", filters={"course": ("in", курсы)}, fields=["name", "course"]
		),
		"course",
		"name",
	)
	по_курсам = {
		курс: _в_порядке(ссылки_глав.get(курс, []), прямые_главы.get(курс, []))
		for курс in курсы
	}
	все_главы = [глава for список in по_курсам.values() for глава in список]
	if not все_главы:
		return {курс: [] for курс in курсы}

	ссылки_уроков = _сгруппировать(
		frappe.get_all(
			"Lesson Reference",
			filters={"parent": ("in", все_главы)},
			fields=["parent", "lesson"],
			order_by="idx asc",
		),
		"parent",
		"lesson",
	)
	прямые_уроки = _сгруппировать(
		frappe.get_all(
			"Course Lesson", filters={"chapter": ("in", все_главы)}, fields=["name", "chapter"]
		),
		"chapter",
		"name",
	)
	return {
		курс: [
			урок
			for глава in список_глав
			for урок in _в_порядке(ссылки_уроков.get(глава, []), прямые_уроки.get(глава, []))
		]
		for курс, список_глав in по_курсам.items()
	}


def _сгруппировать(записи, ключ: str, значение: str) -> dict[str, list[str]]:
	собранное: dict[str, list[str]] = {}
	for запись in записи:
		собранное.setdefault(запись.get(ключ), []).append(запись.get(значение))
	return собранное


def уроки_главы(глава: str) -> list[str]:
	"""Уроки одной главы по порядку."""
	return _в_порядке(
		frappe.get_all("Lesson Reference", filters={"parent": глава}, pluck="lesson", order_by="idx asc"),
		frappe.get_all("Course Lesson", filters={"chapter": глава}, pluck="name"),
	)


def _в_порядке(по_ссылкам: list[str], все: list[str]) -> list[str]:
	"""Известный порядок плюс всё, что в него не попало.

	`Why:` запасной путь, включавшийся только при полном отсутствии ссылок,
	терял записи в смешанном случае — а он обычный: часть глав заведена через
	интерфейс, часть приехала импортом. Терять урок хуже, чем показать его
	последним.
	"""
	порядок = list(по_ссылкам)
	известные = set(порядок)
	return порядок + [запись for запись in все if запись not in известные]


def привязать(родитель: str, doctype: str, значение: str) -> None:
	"""Добавляет главу или урок в конец порядка.

	Вызывается сразу при создании: запись без строки-ссылки для платформы
	не существует — курс получит случайную последовательность.
	"""
	таблица, поле = ТАБЛИЦА_ПОРЯДКА[doctype]
	документ = frappe.get_doc(doctype, родитель)
	документ.append(таблица, {поле: значение})
	документ.save()


def отвязать(родитель: str, doctype: str, значение: str) -> None:
	"""Убирает строку порядка, не трогая саму запись."""
	таблица, поле = ТАБЛИЦА_ПОРЯДКА[doctype]
	документ = frappe.get_doc(doctype, родитель)
	осталось = [строка.get(поле) for строка in документ.get(таблица) if строка.get(поле) != значение]
	документ.set(таблица, [])
	for оставшееся in осталось:
		документ.append(таблица, {поле: оставшееся})
	документ.save()


def переставить(родитель: str, doctype: str, порядок: list[str]) -> None:
	"""Пересобирает таблицу порядка в заданной последовательности.

	Принимает полный список, а не «переставить на позицию»: операция
	идемпотентна, и состав можно сверить с текущим. `Why:` агент, забывший
	один урок, иначе молча выкинул бы его из программы курса.
	"""
	таблица, поле = ТАБЛИЦА_ПОРЯДКА[doctype]
	документ = frappe.get_doc(doctype, родитель)
	текущий = [строка.get(поле) for строка in документ.get(таблица)]
	if sorted(текущий) != sorted(порядок):
		raise Отказ(
			ПОРЯДОК_НЕ_СОВПАЛ,
			"Список не совпадает с текущим составом: передайте все элементы целиком",
			expected=текущий,
			received=list(порядок),
		)
	документ.set(таблица, [])
	for значение in порядок:
		документ.append(таблица, {поле: значение})
	документ.save()
