НЕТ_КОЛОНКИ = "artifact_unknown_column"
НЕТ_ПОЛЯ = "artifact_unknown_field"
НЕТ_СТРОКИ = "artifact_unknown_row"
СТРОКИ_НЕ_ЗАВОДИТ = "artifact_rows_owner_only"
