def привести(описание: dict, значение, таблицы_данных: dict | None = None):
	"""Значение клетки или поля по его типу; пустое — `None`; неверное — отказ."""
	тип = описание["type"]
	где = {"column": описание["key"]}
	if тип == "formula":
		raise Отказ(НЕВЕРНОЕ_ЗНАЧЕНИЕ, "Колонку-формулу считает сервер", **где)
	if значение is None or (isinstance(значение, str) and not значение.strip()):
		return None
	if тип == "check":
		if isinstance(значение, str):
			return значение.strip().lower() in ("1", "true", "да", "yes", "x", "✓")
		return bool(значение)
	if тип in ("number", "scale"):
		число = значение
		if isinstance(значение, str):
			try:
				число = float(значение.strip().replace(",", ".").replace(" ", ""))
			except ValueError as ошибка:
				raise Отказ(НЕВЕРНОЕ_ЗНАЧЕНИЕ, "Нужно число", value=значение, **где) from ошибка
		if isinstance(число, bool) or not isinstance(число, (int, float)):
			raise Отказ(НЕВЕРНОЕ_ЗНАЧЕНИЕ, "Нужно число", value=значение, **где)
		число = _число(float(число))
		if тип == "scale":
			if not isinstance(число, int) or not описание["min"] <= число <= описание["max"]:
				raise Отказ(
					НЕВЕРНОЕ_ЗНАЧЕНИЕ,
					f"Балл по шкале — целое от {описание['min']} до {описание['max']}",
					value=значение,
					**где,
				)
		return число
	текст = str(значение).strip()
	if len(текст) > ДЛИНА_МАКС:
		raise Отказ(НЕВЕРНОЕ_ЗНАЧЕНИЕ, f"Не длиннее {ДЛИНА_МАКС} знаков", **где)
	if тип == "date":
		return _дата(текст, где)
	if тип == "select":
		for вариант in описание["options"]:
			if вариант.lower() == текст.lower():
				return вариант
		raise Отказ(НЕВЕРНОЕ_ЗНАЧЕНИЕ, "Выберите из списка", value=текст, options=описание["options"], **где)
	if тип == "ref":
		строки = (таблицы_данных or {}).get(описание["ref"]) or []
		for строка in строки:
			if строка.get("id", "").lower() == текст.lower():
				return строка["id"]
		raise Отказ(
			НЕВЕРНОЕ_ЗНАЧЕНИЕ, "Ссылка на строку, которой нет", value=текст, table=описание["ref"], **где
		)
	return текст


def _дата(текст: str, где: dict) -> str:
	"""ISO-дата; «31.12.2026» тоже принимается — так её пишут люди."""
	совпало = re.match(r"^(\d{1,2})\.(\d{1,2})\.(\d{4})$", текст)
	if совпало:
		день, месяц, год = (int(ч) for ч in совпало.groups())
	else:
		совпало = re.match(r"^(\d{4})-(\d{2})-(\d{2})$", текст)
		if not совпало:
			raise Отказ(НЕВЕРНОЕ_ЗНАЧЕНИЕ, "Дата — ГГГГ-ММ-ДД или ДД.ММ.ГГГГ", value=текст, **где)
		год, месяц, день = (int(ч) for ч in совпало.groups())
	try:
		return date(год, месяц, день).isoformat()
	except ValueError as ошибка:
		raise Отказ(НЕВЕРНОЕ_ЗНАЧЕНИЕ, "Такой даты нет", value=текст, **где) from ошибка


def пусто(значение) -> bool:
	return значение is None or значение == "" or значение is False


# ---------------------------------------------------------------- данные


def данные(сырые) -> dict:
	"""JSON документа ученика — в словарь с тремя разделами."""
	if isinstance(сырые, str):
		try:
			сырые = json.loads(сырые) if сырые.strip() else {}
		except ValueError:
			сырые = {}
	сырые = сырые if isinstance(сырые, dict) else {}
	return {
		"tables": dict(сырые.get("tables") or {}),
		"fields": dict(сырые.get("fields") or {}),
		"seq": dict(сырые.get("seq") or {}),
	}


def строки(таблица: dict, д: dict) -> list[dict]:
	"""Строки таблицы: сохранённые, а если таблицу ещё не трогали — заготовка."""
	if таблица["name"] in д["tables"]:
		return [dict(с) for с in д["tables"][таблица["name"]]]
	return [
		{"id": f"{таблица['prefix']}{номер}", **заготовка}
		for номер, заготовка in enumerate(таблица["rows"], start=1)
	]


def _следующий_id(таблица: dict, д: dict, занятые: list[dict]) -> str:
	# Номера не переиспользуются: удалённый R3 не вернётся другим риском,
	# иначе ссылки проблем и сверки поедут на чужую строку.
	номер = (
		max(
			int(д["seq"].get(таблица["name"]) or 0),
			*(int(re.sub(r"\D", "", с["id"]) or 0) for с in занятые),
			0,
		)
		+ 1
	)
	д["seq"][таблица["name"]] = номер
	return f"{таблица['prefix']}{номер}"


def записать(
	блоки: list,
	ключ: str,
	сырые,
	rows=None,
	delete_rows=None,
	fields=None,
) -> dict:
	"""Новые данные документа после записи блока `ключ`.

	`rows` — строки со своими колонками блока; без `id` строку заводит только
	хозяин таблицы. `delete_rows` — ID строк на удаление, тоже только хозяин.
	`fields` — значения полей блока. Всё проверяется до записи: либо данные
	меняются целиком, либо отказ и ничего.
	"""
	д = данные(сырые)
	блок = next(б for б in блоки if ключ_блока(б) == ключ)
	с = спек(блок)
	таблицы = таблицы_схемы(блоки)

	if fields:
		fields = _словарь(fields, "fields")
		свои = {п["key"]: п for п in с.get("fields", [])}
		for имя, значение in fields.items():
			if имя not in свои:
				raise Отказ(НЕТ_ПОЛЯ, "У блока нет такого поля", key=ключ, field=имя, fields=sorted(свои))
			д["fields"][имя] = привести(свои[имя], значение)

	if rows or delete_rows:
		if not с.get("columns"):
			raise Отказ(НЕТ_КОЛОНКИ, "У блока нет колонок таблицы", key=ключ)
		таблица = таблицы[с["table"]]
		хозяин = таблица["owner"] == ключ
		текущие = строки(таблица, д)
		данные_таблиц = {имя: строки(т, д) for имя, т in таблицы.items()}

		for id_строки in _список(delete_rows, "delete_rows"):
			if not хозяин:
				raise Отказ(
					СТРОКИ_НЕ_ЗАВОДИТ,
					"Удаляет строки блок, который их заводит",
					key=ключ,
					owner=таблица["owner"],
				)
			найдено = [с_ for с_ in текущие if с_["id"].lower() == str(id_строки).strip().lower()]
			if not найдено:
				raise Отказ(НЕТ_СТРОКИ, "Такой строки нет", key=ключ, row=id_строки)
			текущие.remove(найдено[0])

		свои = {к["key"]: к for к in с["columns"]}
		for строка in _список(rows, "rows"):
			строка = _словарь(строка, "rows")
			id_строки = str(строка.pop("id", "") or "").strip()
			for имя in строка:
				if имя not in свои:
					raise Отказ(
						НЕТ_КОЛОНКИ,
						"У блока нет такой колонки",
						key=ключ,
						column=имя,
						columns=sorted(к for к, о in свои.items() if о["type"] != "formula"),
					)
			if id_строки:
				найдено = [с_ for с_ in текущие if с_["id"].lower() == id_строки.lower()]
				if not найдено:
					raise Отказ(НЕТ_СТРОКИ, "Такой строки нет", key=ключ, row=id_строки)
				цель = найдено[0]
			else:
				if not хозяин:
					raise Отказ(
						СТРОКИ_НЕ_ЗАВОДИТ,
						"Строки заводит блок, который их заводит; здесь — только id существующих",
						key=ключ,
						owner=таблица["owner"],
					)
				if len(текущие) >= СТРОК_МАКС:
					raise Отказ(СТРОК_СЛИШКОМ_МНОГО, f"Не больше {СТРОК_МАКС} строк", key=ключ)
				цель = {"id": _следующий_id(таблица, д, текущие)}
				текущие.append(цель)
			данные_таблиц[таблица["name"]] = текущие
			for имя, значение in строка.items():
				цель[имя] = привести(свои[имя], значение, данные_таблиц)

		for колонка in с["columns"]:
			if колонка["type"] == "check" and колонка.get("max"):
				отмечено = sum(1 for с_ in текущие if с_.get(колонка["key"]))
				if отмечено > колонка["max"]:
					raise Отказ(
						ФЛАЖКОВ_СЛИШКОМ_МНОГО,
						f"Отметить можно не больше {колонка['max']}",
						key=ключ,
						column=колонка["key"],
						max=колонка["max"],
					)
		# Пустые клетки не хранятся: строка остаётся читаемой в JSON.
		д["tables"][таблица["name"]] = [{к: з for к, з in с_.items() if з is not None} for с_ in текущие]
	return д


def _список(значение, имя: str) -> list:
	if значение in (None, "", []):
		return []
	if isinstance(значение, str):
		try:
			значение = json.loads(значение)
		except ValueError as ошибка:
			raise Отказ(НЕВЕРНОЕ_ЗНАЧЕНИЕ, f"{имя} — список", param=имя) from ошибка
	if not isinstance(значение, list):
		raise Отказ(НЕВЕРНОЕ_ЗНАЧЕНИЕ, f"{имя} — список", param=имя)
	return значение


def _словарь(значение, имя: str) -> dict:
	if isinstance(значение, str):
		try:
			значение = json.loads(значение)
		except ValueError as ошибка:
			raise Отказ(НЕВЕРНОЕ_ЗНАЧЕНИЕ, f"{имя} — объект", param=имя) from ошибка
	if not isinstance(значение, dict):
		raise Отказ(НЕВЕРНОЕ_ЗНАЧЕНИЕ, f"{имя} — объект", param=имя)
	return dict(значение)


def вычисленные(таблица: dict, д: dict) -> list[dict]:
	"""Строки с посчитанными формулами — в порядке колонок схемы, так что
	формула может опираться на предыдущую (`in_work` на `rank`)."""
	формулы = [(к["key"], разобрать(к["formula"])) for к in таблица["columns"] if к["type"] == "formula"]
	итог = []
	for строка in строки(таблица, д):
		значения = {**д["fields"], **строка}
		for имя, дерево in формулы:
			значения[имя] = строка[имя] = _число(вычислить(дерево, значения))
		итог.append(строка)
	return итог


# ---------------------------------------------------------------- заполненность


def _обязательна(колонка: dict, строка: dict) -> bool:
	условие = колонка.get("required")
	if условие is True:
		return True
	return bool(условие) and not пусто(строка.get(условие))


def заполнен(блок, д: dict, блоки: list, текст: str = "") -> bool | None:
	"""Заполнен ли блок с полями или колонками; у прочих блоков — `None`.

	Поля: заполнены обязательные (нет обязательных — хоть одно). Колонки: есть
	строки, и у каждой обязательные колонки блока непусты (без обязательных —
	хоть одна клетка блока). `Why:` прежний текст блока, записанный до таблиц,
	считается, пока у блока нет ни одного значения: иначе прогресс учеников,
	начавших курс на markdown, упал бы в день выкладки.
	"""
	с = спек(блок)
	if not с.get("fields") and not с.get("columns"):
		return None
	поля = с.get("fields", [])
	колонки = [к for к in с.get("columns", []) if к["type"] != "formula"]
	таблица = таблицы_схемы(блоки)[с["table"]] if колонки else None
	ряды = вычисленные(таблица, д) if таблица else []

	# Заготовка — не заполненность: шкалы из урока приходят готовыми, но
	# блок готов, когда ученик подогнал их под свой проект.
	тронута = таблица is not None and таблица["name"] in д["tables"]
	есть_значения = any(not пусто(д["fields"].get(п["key"])) for п in поля) or (
		тронута and any(not пусто(р.get(к["key"])) for р in ряды for к in колонки)
	)
	if not есть_значения:
		return bool((текст or "").strip())

	if поля:
		обязательные = [п for п in поля if п.get("required")] or поля
		проверка = all if any(п.get("required") for п in поля) else any
		if not проверка(not пусто(д["fields"].get(п["key"])) for п in обязательные):
			return False
	if колонки:
		if not ряды:
			return False
		обязательные = [к for к in колонки if к.get("required")]
		if обязательные:
			return all(
				пусто(р.get(к["key"])) is False for р in ряды for к in обязательные if _обязательна(к, р)
			)
		return any(not пусто(р.get(к["key"])) for р in ряды for к in колонки)
	return True


def пустые_клетки(блок, д: dict, блоки: list) -> list[dict]:
	"""Где блоку не хватает значений: строка и колонка. Для агента и страницы."""
	с = спек(блок)
	пустые = [
		{"field": п["key"]}
		for п in с.get("fields", [])
		if п.get("required") and пусто(д["fields"].get(п["key"]))
	]
	колонки = [к for к in с.get("columns", []) if к.get("required")]
	if колонки:
		таблица = таблицы_схемы(блоки)[с["table"]]
		for р in вычисленные(таблица, д):
			for к in колонки:
				if _обязательна(к, р) and пусто(р.get(к["key"])):
					пустые.append({"row": р["id"], "column": к["key"]})
	return пустые


# ---------------------------------------------------------------- наружу


def таблицы_документа(блоки: list, д: dict) -> dict[str, dict]:
	"""Таблицы для страницы и агента: колонки всех блоков, строки с формулами."""
	итог = {}
	for имя, таблица in таблицы_схемы(блоки).items():
		ряды = вычисленные(таблица, д)
		итог[имя] = {
			"name": имя,
			"title": таблица["title"],
			"owner": таблица["owner"],
			"prefix": таблица["prefix"],
			"columns": таблица["columns"],
			"views": таблица["views"],
			"rows": ряды,
			# Строки — нетронутая заготовка автора: страница зовёт такую таблицу
			# «заготовкой», а не «готово» (learning-services#342).
			"preset": bool(таблица["rows"]) and имя not in д["tables"],
			"markdown": markdown_таблицы(таблица["columns"], ряды),
		}
	return итог


def поля_документа(блоки: list, д: dict) -> dict:
	return {имя: д["fields"].get(имя) for имя in поля_схемы(блоки)}


def ячейка_текстом(колонка: dict, значение) -> str:
	if значение is None or значение == "":
		return ""
	if колонка["type"] == "check" or isinstance(значение, bool):
		return "да" if значение else ""
	return str(_число(значение))


def markdown_таблицы(колонки: list[dict], ряды: list[dict]) -> str:
	if not ряды:
		return ""

	def клетка(текст: str) -> str:
		return текст.replace("|", "\\|").replace("\n", " ")

	шапка = ["ID", *(к["title"] for к in колонки)]
	линии = [
		"| " + " | ".join(клетка(ш) for ш in шапка) + " |",
		"|" + " --- |" * len(шапка),
	]
	for р in ряды:
		линии.append(
			"| "
			+ " | ".join([р["id"], *(клетка(ячейка_текстом(к, р.get(к["key"]))) for к in колонки)])
			+ " |"
		)
	return "\n".join(линии)


def markdown_полей(описания: list[dict], д: dict) -> str:
	линии = []
	for п in описания:
		значение = д["fields"].get(п["key"])
		if not пусто(значение):
			линии.append(f"- {п['title']}: {ячейка_текстом(п, значение)}")
	return "\n".join(линии)


def книга_xlsx(название: str, блоки: list, д: dict) -> bytes:
	"""Документ книгой Excel: лист «Шапка» с полями и лист на таблицу.

	Формулы колонок уходят формулами Excel — реестр продолжают вести с
	командой, и ранг считается сам. Формула с and/or/not уходит значением:
	у Excel другой синтаксис логики, и переводить его ради редкого случая
	незачем.
	"""
	import io

	from openpyxl import Workbook
	from openpyxl.styles import Alignment, Font, PatternFill
	from openpyxl.utils import get_column_letter

	книга = Workbook()
	шапка = книга.active
	шапка.title = "Шапка"
	шапка.append([название])
	шапка["A1"].font = Font(bold=True, size=14)
	адреса_полей: dict[str, str] = {}
	for имя, поле in поля_схемы(блоки).items():
		значение = д["fields"].get(имя)
		шапка.append([поле["title"], значение])
		адреса_полей[имя] = f"'Шапка'!$B${шапка.max_row}"
	шапка.column_dimensions["A"].width = 40
	шапка.column_dimensions["B"].width = 30

	заливка = PatternFill("solid", fgColor="EEF2F6")
	for имя, таблица in таблицы_схемы(блоки).items():
		лист = книга.create_sheet((таблица["title"] or имя)[:31])
		колонки = таблица["columns"]
		буквы = {"id": "A"}
		for номер, колонка in enumerate(колонки, start=2):
			буквы[колонка["key"]] = get_column_letter(номер)
		лист.append(["ID", *(к["title"] for к in колонки)])
		for клетка in лист[1]:
			клетка.font = Font(bold=True)
			клетка.fill = заливка
			клетка.alignment = Alignment(wrap_text=True, vertical="top")
		for номер_строки, р in enumerate(вычисленные(таблица, д), start=2):
			ряд = [р["id"]]
			for колонка in колонки:
				if колонка["type"] == "formula":
					ряд.append(
						_формула_excel(колонка["formula"], буквы, адреса_полей, номер_строки)
						or р.get(колонка["key"])
					)
				elif колонка["type"] == "check":
					ряд.append(bool(р.get(колонка["key"])))
				else:
					ряд.append(р.get(колонка["key"]))
			лист.append(ряд)
		лист.freeze_panes = "B2"
		for номер, колонка in enumerate(колонки, start=2):
			широкая = колонка["type"] in ("text", "longtext")
			лист.column_dimensions[get_column_letter(номер)].width = 36 if широкая else 14
		for ряд in лист.iter_rows(min_row=2):
			for клетка in ряд:
				клетка.alignment = Alignment(wrap_text=True, vertical="top")

	поток = io.BytesIO()
	книга.save(поток)
	return поток.getvalue()


def _формула_excel(формула: str, буквы: dict, поля: dict, строка: int) -> str | None:
	части = []
	for вид, значение in _лексемы(формула):
		if вид == "op" and значение in ("and", "or", "not"):
			return None
		if вид == "name":
			if значение in буквы:
				части.append(f"{буквы[значение]}{строка}")
			elif значение in поля:
				части.append(поля[значение])
			else:
				return None
		elif значение == "==":
			части.append("=")
		elif значение == "!=":
			части.append("<>")
		else:
			части.append(значение)
	return "=" + "".join(части)


def очистить(блоки: list, ключ: str, сырые) -> dict:
	"""Данные документа без значений блока `ключ`.

	Поля блока стираются, его колонки — во всех строках. Блок, который
	заводит таблицу, уносит и строки: без него их не завести заново, а чужие
	колонки у пустого реестра ничего не значат. `Why:` очистка нужна, когда
	ученик сменил проект, — старый реестр тогда неправда целиком.
	"""
	д = данные(сырые)
	блок = next(б for б in блоки if ключ_блока(б) == ключ)
	с = спек(блок)
	for поле in с.get("fields", []):
		д["fields"].pop(поле["key"], None)
	if с.get("columns"):
		таблица = таблицы_схемы(блоки)[с["table"]]
		if таблица["owner"] == ключ:
			д["tables"].pop(таблица["name"], None)
		elif таблица["name"] in д["tables"]:
			свои = {к["key"] for к in с["columns"]}
			д["tables"][таблица["name"]] = [
				{к: з for к, з in строка.items() if к not in свои} for строка in д["tables"][таблица["name"]]
			]
	return д
