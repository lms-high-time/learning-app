"""Блокировки, показанный уровень и очередь агента по карте компетенций (learning-services#810).

Дизайн карты компетенций, §4 и §8:

- **Открытый уровень** компетенции — наивысшая цель по ней среди начатых
  уроков; нет её ни в одном начатом — заблокирована целиком (0). Блокировка
  действует на агента и на отображение, а не на данные: свидетельство выше
  открытого уровня записывается с настоящим уровнем.
- **Показанный уровень** — меньшее из подтверждённого и открытого.
- **Очередь агента** — то, что стоит посмотреть при естественном поводе:
  компетенции пройденных уроков без подтверждения (`unconfirmed`) и
  затруднение после подтверждения (`difficulty_after_confirmation`).
  Подтверждённое ниже цели в очередь не идёт: цели не условие закрытия.
  Первыми — компетенции текущего урока и составляющие его интеграционных.

Выход из очереди — по журналу: у `unconfirmed` — любое действующее
подтверждение; у затруднения — подтверждение не ниже уровня затруднения или
пересмотр уровня. Пропуск выход не даёт. Состав очереди считает только
приложение: MCP его не пересчитывает.
"""

import frappe

from lms_frappe_app.agent_learning.competencies import evidence
from lms_frappe_app.agent_learning.releases import index

НЕ_ПОДТВЕРЖДЕНА = "unconfirmed"
ЗАТРУДНЕНИЕ_ПОСЛЕ = "difficulty_after_confirmation"
ПРОЙДЕН = "passed"


def открытые_уровни(цели_уроков: dict[str, list[dict]], начатые: set[str]) -> dict[str, int]:
	"""Компетенция → открытый уровень: наивысшая цель среди начатых уроков. Нет в начатых — нет ключа."""
	итог: dict[str, int] = {}
	for урок, цели in цели_уроков.items():
		if урок in начатые:
			for ц in цели:
				итог[ц["competency"]] = max(итог.get(ц["competency"], 0), ц["target"])
	return итог


def затруднения_после(записи: list) -> dict[str, int]:
	"""Компетенция → уровень открытого затруднения после подтверждения, по журналу по порядку.

	Затруднение на уровне не выше уже действующего подтверждения открывает пункт; подтверждение
	не ниже его уровня или пересмотр — закрывают. Без базы.
	"""
	выведено = evidence._выведенные(записи)
	подтверждено: dict[str, int] = {}
	открыто: dict[str, int] = {}
	for з in записи:
		к = з.competency
		if з.kind == evidence.ПЕРЕСМОТР:
			# Выведенные пересмотром подтверждения не считаются нигде (`выведено`), так что уровень
			# здесь уже без них; пересмотр закрывает пункт — затруднение отработано снижением.
			открыто.pop(к, None)
			continue
		if з.outcome == evidence.ПОДТВЕРЖДЕНО and з.name not in выведено:
			подтверждено[к] = max(подтверждено.get(к, 0), з.level)
			if к in открыто and з.level >= открыто[к]:
				del открыто[к]
		elif з.outcome == evidence.ЗАТРУДНЕНИЕ and 0 < (з.level or 0) <= подтверждено.get(к, 0):
			открыто[к] = з.level
	return открыто


def очередь_по_данным(
	карта: list[dict],
	цели_уроков: dict[str, list[dict]],
	статусы: dict[str, str],
	записи: list,
	текущий_урок: str | None = None,
) -> list[dict]:
	"""Очередь агента: `{competency, title, reason, level, last_outcome}` по порядку — сначала
	связанные с текущим уроком, затем по порядку карты. Без базы.

	`статусы` — ключ урока → статус прохождения ученика; `level` у затруднения — его уровень,
	у неподтверждённой — `None`.
	"""
	состояние = evidence.состояние_по_записям(записи)
	затруднения = затруднения_после(записи)
	пройденные = {
		к for урок, статус in статусы.items() if статус == ПРОЙДЕН for к in _ключи(цели_уроков.get(урок))
	}
	названия = {к["key"]: к["title"] for к in карта}
	пункты = []
	for к in названия:
		с = состояние.get(к, evidence.ПУСТО)
		if к in затруднения:
			пункты.append({"competency": к, "reason": ЗАТРУДНЕНИЕ_ПОСЛЕ, "level": затруднения[к]})
		elif к in пройденные and с["level"] is None:
			пункты.append({"competency": к, "reason": НЕ_ПОДТВЕРЖДЕНА, "level": None})
	связанные = _связанные(карта, цели_уроков.get(текущий_урок) or [])
	пункты.sort(key=lambda п: п["competency"] not in связанные)
	return [
		{
			**п,
			"title": названия[п["competency"]],
			"last_outcome": состояние.get(п["competency"], evidence.ПУСТО)["last_outcome"],
		}
		for п in пункты
	]


def _ключи(цели: list[dict] | None) -> set[str]:
	return {ц["competency"] for ц in цели or []}


def _связанные(карта: list[dict], цели: list[dict]) -> set[str]:
	"""Компетенции урока и составляющие его интеграционных."""
	свои = _ключи(цели)
	части = {ч["competency"] for к in карта if к["key"] in свои for ч in к.get("parts") or []}
	return свои | части


def статусы_уроков(ученик: str, курс: str) -> dict[str, str]:
	"""Ключ урока → статус прохождения ученика по курсу; урок без прохождения не начат."""
	return {
		р.lesson_key: р.status
		for р in frappe.get_all(
			"Agent Lesson Run", filters={"student": ученик, "course": курс}, fields=["lesson_key", "status"]
		)
	}


def карта_ученика(ученик: str, курс: str, релиз: str, текущий_урок: str | None = None) -> dict | None:
	"""Карта компетенций ученика по курсу: `{open_levels, state, queue, lesson_status}`; курс без
	карты — `None` одним запросом.

	Начатый урок — тот, у которого есть прохождение: его заводит первый старт урока.
	"""
	карта = index.карта_компетенций(релиз)
	if not карта:
		return None
	цели = index.цели_уроков(релиз)
	статусы = статусы_уроков(ученик, курс)
	записи = evidence._записи(ученик, курс)
	return {
		"open_levels": открытые_уровни(цели, set(статусы)),
		"state": evidence.состояние_по_записям(записи),
		"queue": очередь_по_данным(карта, цели, статусы, записи, текущий_урок),
		"lesson_status": статусы,
	}


def показанный_уровень(уровень: int | None, открытый: int) -> int | None:
	"""Меньшее из подтверждённого и открытого; нет подтверждения или всё закрыто — `None`."""
	if not уровень or not открытый:
		return None
	return min(уровень, открытый)
