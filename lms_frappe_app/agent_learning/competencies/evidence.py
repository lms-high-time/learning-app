"""Свидетельства об освоении компетенций и пересмотр уровня (learning-services#808).

Уровень ставит агент ученика, и только свидетельством: компактной записью
того, что ученик сделал и в каких условиях. Сервер не судит о смысле текста —
он держит форму записи и формальные правила, которые должны устоять против
недобросовестного агента (ученик может вызвать метод своим токеном мимо MCP,
CLAUDE.md §10):

- компетенция — из карты действующего релиза курса;
- у каждого исхода свои обязательные поля (`ОБЯЗАТЕЛЬНО`);
- только для «подтверждено»: форма «выбор из вариантов» — не выше уровня 1,
  подсказки или исправление после обратной связи — не выше 2, уровень 4 — с
  полями переноса;
- повтор с тем же ключом запроса записи не создаёт.

Журнал (`Agent Competency Event`) не переписывается. Пересмотр — отдельная
запись: только вниз, и выводит из расчёта подтверждения выше нового уровня
сам сервер — агенту не нужно помнить прежние свидетельства. Состояние
компетенции у ученика — наивысший уровень действующих подтверждений и
последний исход; выводится из журнала (`состояние_по_записям`).

**Компетенции каталога** (learning-services#826) — общие для всех курсов:
запись несёт версию компетенции на момент записи (`competency_version`), и
журнал по ним читается во всех курсах ученика (`_записи`, `сквозные`) —
подтверждение из одного курса засчитывается в другом, пересмотр и отмена
аудитом действуют везде. Ключи карты внутри релиза локальны для курса: у их
записей версии нет (0), и журнал по ним — только по курсу.
"""

import json

import frappe
from frappe.query_builder import Order

from lms_frappe_app.agent_learning.constants import СОБЫТИЕ_ЗАКРЫТИЕ_ОТКАЗАНО
from lms_frappe_app.agent_learning.errors import Отказ
from lms_frappe_app.agent_learning.releases import index

ЖУРНАЛ = "Agent Competency Event"
СВИДЕТЕЛЬСТВО, ПЕРЕСМОТР, АУДИТ = "Evidence", "Revision", "Audit"

ПОДТВЕРЖДЕНО, ЗАТРУДНЕНИЕ, НЕДОСТАТОЧНО, ПРОПУЩЕНО = "confirmed", "difficulty", "insufficient", "skipped"
ИСХОДЫ = (ПОДТВЕРЖДЕНО, ЗАТРУДНЕНИЕ, НЕДОСТАТОЧНО, ПРОПУЩЕНО)
ВЫБОР, СВОБОДНЫЙ, РАБОТА = "choice", "free", "work"
ФОРМЫ = (ВЫБОР, СВОБОДНЫЙ, РАБОТА)
УРОВНИ = (1, 2, 3, 4)

ТЕКСТЫ = (
	"task",
	"student_action",
	"assessment",
	"uncertainties",
	"transfer_difference",
	"transfer_adaptation",
)
#: Обязательное у исхода (дизайн карты компетенций, §5): уровень, тексты, отметки. Отметки — только у
#: «подтверждено» и «затруднения»: у «недостаточно» и пропуска проверки не было, и их отметки не
#: пишутся (в журнале — 0); аналитика по отметкам считает только эти два исхода.
ОБЯЗАТЕЛЬНО = {
	ПОДТВЕРЖДЕНО: (
		"level",
		"task",
		"student_action",
		"assessment",
		"task_form",
		"hints",
		"corrected",
		"indirect",
	),
	ЗАТРУДНЕНИЕ: (
		"level",
		"task",
		"student_action",
		"assessment",
		"task_form",
		"hints",
		"corrected",
		"indirect",
	),
	НЕДОСТАТОЧНО: ("task", "assessment"),
	ПРОПУЩЕНО: ("task",),
}
#: Предел текста свидетельства: запись — компактная, не стенограмма.
ПРЕДЕЛ_ТЕКСТА = 1000
ПРЕДЕЛ_КЛЮЧА = 80

КОМПЕТЕНЦИЯ_НЕИЗВЕСТНА = "competency_unknown"
ИСХОД_НЕИЗВЕСТЕН = "outcome_unknown"
ПОЛЕ_ОБЯЗАТЕЛЬНО = "evidence_field_required"
ПОЛЕ_ЛИШНЕЕ = "evidence_field_not_allowed"
УРОВЕНЬ_НЕВЕРНЫЙ = "level_invalid"
УРОВЕНЬ_ВЫШЕ_ДОПУСТИМОГО = "level_capped"
ФОРМА_НЕИЗВЕСТНА = "task_form_unknown"
ТЕКСТ_ДЛИННЫЙ = "evidence_too_long"
КЛЮЧ_НЕВЕРНЫЙ = "request_key_invalid"
ПЕРЕСМОТР_НЕ_ВНИЗ = "revision_not_lower"


def сквозные(карта: list[dict]) -> list[str]:
	"""Компетенции карты курса, журнал по которым читается во всех курсах ученика, — компетенции
	каталога: у них есть версия (`catalog.read.карты_по_целям`). У карты внутри релиза версии нет,
	её ключи локальны для курса — их здесь нет. Без базы."""
	return [к["key"] for к in карта if isinstance(к, dict) and к.get("version")]


def _текст(значение) -> str:
	return str(значение).strip() if значение is not None else ""


def _уровень(значение) -> int | None:
	"""Уровень из параметра метода: целое 1–4 (строкой тоже) — число; пусто — `None`; иначе отказ."""
	if значение in (None, ""):
		return None
	if isinstance(значение, bool):
		raise Отказ(УРОВЕНЬ_НЕВЕРНЫЙ, "Уровень — целое число от 1 до 4", level=значение)
	try:
		уровень = int(str(значение).strip())
	except ValueError:
		raise Отказ(УРОВЕНЬ_НЕВЕРНЫЙ, "Уровень — целое число от 1 до 4", level=значение) from None
	if уровень not in УРОВНИ or str(значение).strip() != str(уровень):
		raise Отказ(УРОВЕНЬ_НЕВЕРНЫЙ, "Уровень — целое число от 1 до 4", level=значение)
	return уровень


def _да_нет(значение) -> bool | None:
	"""Отметка «да/нет» из параметра метода; не передана — `None`."""
	if значение in (None, ""):
		return None
	return значение not in (False, 0, "0", "false", "False", "no")


def _ключ_запроса(ключ) -> str:
	"""Ключ запроса — непустая строка до `ПРЕДЕЛ_КЛЮЧА` знаков без `<` и `>`.

	`Why:` текстовые поля хранятся очищенными от HTML (`html_text.очистить`):
	ключ со скобкой лёг бы в журнал другим, и повтор его не нашёл бы.
	"""
	ключ = _текст(ключ)
	if not ключ or len(ключ) > ПРЕДЕЛ_КЛЮЧА or "<" in ключ or ">" in ключ:
		raise Отказ(
			КЛЮЧ_НЕВЕРНЫЙ,
			f"Нужен ключ запроса — непустая строка до {ПРЕДЕЛ_КЛЮЧА} знаков без < и >: повтор с тем же ключом записи не создаёт",
			limit=ПРЕДЕЛ_КЛЮЧА,
		)
	return ключ


def форма_свидетельства(
	исход: str, уровень, тексты: dict, форма_задания, отметки: dict
) -> tuple[int | None, dict, str | None, dict]:
	"""Свидетельство по правилам сервера — (уровень, тексты, форма задания, отметки) — или отказ.

	Без базы: компетенцию и ключ запроса проверяет `записать`.
	"""
	if исход not in ИСХОДЫ:
		raise Отказ(
			ИСХОД_НЕИЗВЕСТЕН, "Исход — одно из: " + ", ".join(ИСХОДЫ), outcome=исход, allowed=list(ИСХОДЫ)
		)
	уровень = _уровень(уровень)
	тексты = {поле: _текст(тексты.get(поле)) for поле in ТЕКСТЫ}
	for поле, текст in тексты.items():
		if len(текст) > ПРЕДЕЛ_ТЕКСТА:
			raise Отказ(
				ТЕКСТ_ДЛИННЫЙ,
				f"Свидетельство — компактная запись: {поле} не длиннее {ПРЕДЕЛ_ТЕКСТА} знаков",
				field=поле,
				limit=ПРЕДЕЛ_ТЕКСТА,
				length=len(текст),
			)
	форма_задания = _текст(форма_задания) or None
	if форма_задания is not None and форма_задания not in ФОРМЫ:
		raise Отказ(
			ФОРМА_НЕИЗВЕСТНА,
			"Форма задания — одно из: " + ", ".join(ФОРМЫ),
			task_form=форма_задания,
			allowed=list(ФОРМЫ),
		)
	отметки = {
		"hints": _да_нет(отметки.get("hints")),
		"corrected": _да_нет(отметки.get("corrected")),
		"indirect": _да_нет(отметки.get("indirect")),
	}
	есть = {"level": уровень, "task_form": форма_задания, **тексты, **отметки}
	for поле in ОБЯЗАТЕЛЬНО[исход]:
		if есть[поле] in (None, ""):
			raise Отказ(
				ПОЛЕ_ОБЯЗАТЕЛЬНО,
				f"У исхода {исход} обязательно поле {поле}",
				field=поле,
				outcome=исход,
				required=list(ОБЯЗАТЕЛЬНО[исход]),
			)
	if исход == ПРОПУЩЕНО and уровень is not None:
		raise Отказ(
			ПОЛЕ_ЛИШНЕЕ, "У пропуска уровня нет: ученик отказался от проверки", field="level", outcome=исход
		)
	if исход == ПОДТВЕРЖДЕНО:
		_потолок(уровень, форма_задания, отметки)
		if уровень == 4:
			for поле in ("transfer_difference", "transfer_adaptation"):
				if not тексты[поле]:
					raise Отказ(
						ПОЛЕ_ОБЯЗАТЕЛЬНО,
						f"Уровень 4 подтверждается переносом: обязательно поле {поле}",
						field=поле,
						outcome=исход,
						level=уровень,
					)
	return уровень, тексты, форма_задания, отметки


def _потолок(уровень: int, форма_задания: str, отметки: dict) -> None:
	"""Отметки ограничивают подтверждённый уровень (дизайн, §6): выбор — 1, подсказки и исправление — 2."""
	for потолок, причина, есть in (
		(1, "task_form", форма_задания == ВЫБОР),
		(2, "hints", отметки["hints"]),
		(2, "corrected", отметки["corrected"]),
	):
		if есть and уровень > потолок:
			raise Отказ(
				УРОВЕНЬ_ВЫШЕ_ДОПУСТИМОГО,
				f"С отметкой {причина} подтверждается уровень не выше {потолок}; для выше — новая задача без неё",
				level=уровень,
				cap=потолок,
				reason=причина,
			)


def _компетенция(релиз: str, компетенция: str) -> tuple[str, int]:
	"""Компетенция карты курса и её версия в каталоге — или отказ `competency_unknown`.

	Карта курса на каталоге — цели уроков и их составляющие по каталогу: компетенция каталога
	вне карты курса — тоже отказ. У карты внутри релиза версия — 0.
	"""
	компетенция = _текст(компетенция)
	найдено = next(
		(к for к in index.карта_компетенций(релиз) if isinstance(к, dict) and к.get("key") == компетенция),
		None,
	)
	if not найдено:
		raise Отказ(
			КОМПЕТЕНЦИЯ_НЕИЗВЕСТНА,
			"Такой компетенции нет в карте курса — ключи компетенций урока отдаёт start_lesson",
			competency=компетенция,
		)
	return компетенция, int(найдено.get("version") or 0)


def _уже(ученик: str, ключ: str, for_update: bool = False) -> str | None:
	return frappe.db.get_value(
		ЖУРНАЛ, {"student": ученик, "request_key": ключ}, "name", for_update=for_update
	)


def повтор(ученик: str, ключ_запроса) -> dict | None:
	"""Ответ на прежнюю запись ученика с этим ключом запроса — или `None`, записи нет.

	Метод зовёт до проверок занятия: запись прошла, ответ потерялся, занятие закрылось —
	повтор всё равно узнаёт, что запись есть. Ключ уникален в пределах ученика, чужого
	не выдаёт.
	"""
	имя = _уже(ученик, _ключ_запроса(ключ_запроса))
	return _ответ(имя, True) if имя else None


def _ответ(имя: str, повтор: bool) -> dict:
	запись = frappe.db.get_value(
		ЖУРНАЛ,
		имя,
		["name", "kind", "competency", "competency_version", "student", "course"],
		as_dict=True,
	)
	return {
		"event": запись.name,
		"kind": "evidence" if запись.kind == СВИДЕТЕЛЬСТВО else "revision",
		"competency": запись.competency,
		"duplicate": повтор,
		"state": состояние_компетенции(
			запись.student, запись.course, запись.competency, bool(запись.competency_version)
		),
	}


def _вставить(запись: dict) -> str:
	"""Вставить запись журнала — или взять ту, что с тем же ключом вставил параллельный вызов.

	Дубль ловит уникальный индекс (`install.обеспечить_индекс_компетенций`);
	откат к точке снимает только эту вставку — как `runs.service._вставить`.
	"""
	frappe.db.savepoint("competency_event")
	try:
		return frappe.get_doc({"doctype": ЖУРНАЛ, **запись}).insert(ignore_permissions=True).name
	except (frappe.UniqueValidationError, frappe.DuplicateEntryError):
		frappe.db.rollback(save_point="competency_event")
		frappe.clear_last_message()
		# Блокирующее чтение видит строку, зафиксированную параллельным вызовом после
		# начала транзакции; на стенде гонка приходит взаимоблокировкой — метод отвечает `busy`.
		имя = _уже(запись["student"], запись["request_key"], for_update=True)
		if not имя:
			raise
		return имя


def _общее(занятие, релиз: str, ключ_урока: str, компетенция: str, версия: int, ключ: str) -> dict:
	return {
		"student": занятие.student,
		"course": занятие.course,
		"lesson": занятие.lesson,
		"lesson_key": ключ_урока,
		"session": занятие.name,
		"release": релиз,
		"competency": компетенция,
		"competency_version": версия,
		"request_key": ключ,
	}


def записать(
	занятие,
	релиз: str,
	ключ_урока: str,
	компетенция: str,
	исход: str,
	уровень,
	тексты: dict,
	форма_задания,
	отметки: dict,
	ключ_запроса,
) -> dict:
	"""Свидетельство агента по занятию — или ответ на прежнюю запись с тем же ключом запроса.

	Отказы — до записи. Повтор ключа отвечает прежней записью (`duplicate: true`), даже
	если поля другие: ключ — обещание агента, что это тот же вызов.
	"""
	ключ = _ключ_запроса(ключ_запроса)
	if имя := _уже(занятие.student, ключ):
		return _ответ(имя, True)
	компетенция, версия = _компетенция(релиз, компетенция)
	уровень, тексты, форма_задания, отметки = форма_свидетельства(
		исход, уровень, тексты, форма_задания, отметки
	)
	имя = _вставить(
		{
			**_общее(занятие, релиз, ключ_урока, компетенция, версия, ключ),
			"kind": СВИДЕТЕЛЬСТВО,
			"outcome": исход,
			"level": уровень or 0,
			**тексты,
			"task_form": форма_задания or "",
			"hints": int(bool(отметки["hints"])),
			"corrected": int(bool(отметки["corrected"])),
			"indirect": int(bool(отметки["indirect"])),
			# Сигнал аудиту (дизайн §7): свидетельство дописано после отказа в закрытии урока.
			"after_refusal": int(
				bool(
					frappe.db.exists(
						"Agent Session Event", {"session": занятие.name, "kind": СОБЫТИЕ_ЗАКРЫТИЕ_ОТКАЗАНО}
					)
				)
			),
		}
	)
	return _ответ(имя, False)


def пересмотреть(
	занятие, релиз: str, ключ_урока: str, компетенция: str, уровень, причина, ключ_запроса
) -> dict:
	"""Пересмотр уровня компетенции вниз (дизайн, §6, §10): новый уровень (0 — нет уровня) ниже
	текущего, причина обязательна. Подтверждения выше нового уровня выходят из расчёта — их
	перечисляет сама запись пересмотра (`withdrawn`). У компетенции каталога текущий уровень и
	выводимые подтверждения — по всем курсам ученика."""
	ключ = _ключ_запроса(ключ_запроса)
	if имя := _уже(занятие.student, ключ):
		return _ответ(имя, True)
	компетенция, версия = _компетенция(релиз, компетенция)
	новый = 0 if (уровень == 0 and not isinstance(уровень, bool)) or уровень == "0" else _уровень(уровень)
	if новый is None:
		raise Отказ(ПОЛЕ_ОБЯЗАТЕЛЬНО, "Нужен новый уровень: 0–3, ниже текущего", field="level")
	причина = _текст(причина)
	if not причина:
		raise Отказ(ПОЛЕ_ОБЯЗАТЕЛЬНО, "Нужна причина пересмотра: какие затруднения", field="reason")
	if len(причина) > ПРЕДЕЛ_ТЕКСТА:
		raise Отказ(
			ТЕКСТ_ДЛИННЫЙ, f"Причина не длиннее {ПРЕДЕЛ_ТЕКСТА} знаков", field="reason", limit=ПРЕДЕЛ_ТЕКСТА
		)
	действующие = _действующие_подтверждения(занятие.student, занятие.course, компетенция, bool(версия))
	текущий = max(действующие.values(), default=0)
	if новый >= текущий:
		raise Отказ(
			ПЕРЕСМОТР_НЕ_ВНИЗ,
			"Пересмотр только снижает уровень; поднять — новым свидетельством confirmed",
			level=новый,
			current_level=текущий or None,
		)
	имя = _вставить(
		{
			**_общее(занятие, релиз, ключ_урока, компетенция, версия, ключ),
			"kind": ПЕРЕСМОТР,
			"level": новый,
			"assessment": причина,
			"withdrawn": json.dumps(sorted(и for и, у in действующие.items() if у > новый)),
		}
	)
	return _ответ(имя, False)


ПУСТО = {"level": None, "last_outcome": None, "last_level": None}


