"""Закрытие урока по компетенциям (learning-services#809, дизайн §7).

Урок с картой компетенций закрывается, когда каждую его компетенцию
проверили или ученик отказался: освоения не требуется — это не
сертификация. Засчитывается:

- свидетельство «подтверждено», «найдено затруднение» или «пропущено» из
  занятий этого урока — этого курса: ключ урока локален для курса;
- «подтверждено» не ниже цели урока из любого урока любого курса ученика:
  ученик, показавший «применяет» в уроке 2, не проверяется заново в уроке 5
  с целью «объясняет» (learning-services#826) — журнал по компетенции
  читается во всех курсах (`evidence._записи`). Подтверждение, выведенное
  пересмотром, здесь не считается.

«Данных недостаточно» не засчитывается: этот исход значит, что проверки не
было. Квиз в уроке с картой не обязателен и не открывается: сданный квиз
закрыл бы урок мимо этого правила.

Цель, которую закрывает только подтверждение из другого курса, — засчёт
(`засчёты_по_записям`): закрытие урока пишет его в журнал занятия.
"""

from lms_frappe_app.agent_learning.competencies import evidence

#: Исходы, которые закрывают компетенцию урока, если записаны в его занятиях.
ЗАСЧИТЫВАЮТСЯ_В_УРОКЕ = frozenset({evidence.ПОДТВЕРЖДЕНО, evidence.ЗАТРУДНЕНИЕ, evidence.ПРОПУЩЕНО})


def _закрывающие(записи: list, выведено: set[str], курс: str, ключ_урока: str, цель: dict) -> list:
	"""Свидетельства, которые закрывают цель урока `{competency, target}`, по порядку журнала;
	`выведено` — выведенные из расчёта (`evidence._выведенные`)."""
	return [
		з
		for з in записи
		if з.kind == evidence.СВИДЕТЕЛЬСТВО
		and з.competency == цель["competency"]
		and (
			(з.course == курс and з.lesson_key == ключ_урока and з.outcome in ЗАСЧИТЫВАЮТСЯ_В_УРОКЕ)
			or (з.outcome == evidence.ПОДТВЕРЖДЕНО and з.name not in выведено and з.level >= цель["target"])
		)
	]


def непроверенные_по_записям(записи: list, курс: str, ключ_урока: str, цели: list[dict]) -> list[dict]:
	"""Цели урока `{competency, target}`, по которым свидетельства для закрытия нет — по порядку целей.

	`записи` — журнал ученика по курсу и по компетенциям целей — по всем курсам
	(`evidence._записи`). Без базы.
	"""
	выведено = evidence._выведенные(записи)
	return [ц for ц in цели if not _закрывающие(записи, выведено, курс, ключ_урока, ц)]


def засчёты_по_записям(записи: list, курс: str, ключ_урока: str, цели: list[dict]) -> list[dict]:
	"""Цели урока, закрытые засчётом из другого курса: `{competency, target, evidence, course, level}`.

	Засчёт — когда цель закрывают только подтверждения других курсов; закрывает её и запись этого
	курса — засчёта нет. `evidence`, `course`, `level` — последнее из закрывающих подтверждений.
	Без базы.
	"""
	выведено = evidence._выведенные(записи)
	итог = []
	for ц in цели:
		закрывающие = _закрывающие(записи, выведено, курс, ключ_урока, ц)
		if закрывающие and all(з.course != курс for з in закрывающие):
			з = закрывающие[-1]
			итог.append({**ц, "evidence": з.name, "course": з.course, "level": з.level})
	return итог


def _записи_для_целей(ученик: str, курс: str, цели: list[dict]) -> list:
	"""Журнал ученика для закрытия урока — одной выборкой: по курсу и по компетенциям целей —
	по всем курсам. Карта курса не читается."""
	return evidence._записи(ученик, курс, по_всем_курсам=list(dict.fromkeys(ц["competency"] for ц in цели)))


def непроверенные(ученик: str, курс: str, ключ_урока: str, цели: list[dict]) -> list[dict]:
	"""Цели урока без свидетельства для закрытия; у урока без целей — `[]` без запроса."""
	if not цели:
		return []
	return непроверенные_по_записям(_записи_для_целей(ученик, курс, цели), курс, ключ_урока, цели)


def проверка(ученик: str, курс: str, ключ_урока: str, цели: list[dict]) -> tuple[list[dict], list[dict]]:
	"""Для закрытия урока — (цели без свидетельства, засчёты из других курсов) одной выборкой
	журнала; у урока без целей — `([], [])` без запроса."""
	if not цели:
		return [], []
	записи = _записи_для_целей(ученик, курс, цели)
	return (
		непроверенные_по_записям(записи, курс, ключ_урока, цели),
		засчёты_по_записям(записи, курс, ключ_урока, цели),
	)
