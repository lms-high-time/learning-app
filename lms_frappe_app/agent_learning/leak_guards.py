"""Что не имеет права появиться в ответе наружу.

Один дом для списков, которые проверяют тесты. `Why:` копий было три, и ни
одна не была надмножеством другой: `owner` заявлен в контракте, но самой
широкой проверкой не проверялся. Разъехавшиеся списки означают, что часть
проверок слабее, чем выглядит.
"""

#: Поля эталона квиза в релизе (`lessons[].quiz.answers`): ответы вопросов,
#: верный вариант, пояснение. Ищутся ключами JSON, а не подстрокой: `correct`
#: и `explanation` законно приходят в ответах квиза — где именно, решают
#: `_законный_счёт` и `_законное_пояснение`.
ПОЛЯ_ЭТАЛОНА = (
	"answers",
	"correct",
	"explanation",
)

#: Ключи варианта и вопроса — в релизе (`key`) и наружу (`id`): `correct`
#: рядом с ними — метка верного варианта.
КЛЮЧИ_ВАРИАНТА = frozenset({"id", "key", "text", "options"})

#: Внутренние структуры Frappe. Контракт обязан оставаться интерфейсом общего
#: назначения — тем, который мог бы реализовать другой backend.
ВНУТРЕННОСТИ_FRAPPE = (
	"doctype",
	"docstatus",
	"modified_by",
	"owner",
	"idx",
	"parenttype",
)


def проверить_ответ(
	тест, ответ, что: str, запрещённые_тексты: tuple[str, ...] = (), кроме: tuple[str, ...] = ()
) -> str:
	"""Утверждает, что в ответе нет ни эталонов, ни внутренностей Frappe.

	`запрещённые_тексты` — конкретные значения из базы: проверка по именам
	полей пропустит утечку вида ``{"hint": <текст пояснения>}``, а проверка по
	тексту — нет. `кроме` — имена из списков, которые у этого ответа законны:
	`owner` у таблицы документа — блок, который её заводит (CONTRACT.md,
	«Зачем контракт именно такой»). `explanation` в `кроме` разрешает
	пояснение только там, где его отдаёт квиз (`_законное_пояснение`), а не во
	всём ответе.
	"""
	import json

	выдано = json.dumps(ответ, ensure_ascii=False, default=str)

	for поле, значение, словарь, ключ_выше, выше in _поля(json.loads(выдано)):
		if поле not in ПОЛЯ_ЭТАЛОНА:
			continue
		if поле == "correct" and _законный_счёт(значение, словарь, ключ_выше):
			continue
		if поле == "explanation" and поле in кроме and _законное_пояснение(словарь, ключ_выше, выше):
			continue
		тест.fail(f"{что}: поле эталона «{поле}»: {значение!r}")
	for поле in ВНУТРЕННОСТИ_FRAPPE:
		if поле in кроме:
			continue
		тест.assertNotIn(поле, выдано, f"{что}: структура Frappe «{поле}»")
	for текст in запрещённые_тексты:
		тест.assertNotIn(текст, выдано, f"{что}: утёк текст «{текст}»")
	return выдано


def _законный_счёт(значение, словарь: dict, ключ_выше) -> bool:
	"""`correct` — вердикт ответа (`verdict.correct`, `true`/`false`) или счёт
	верных рядом с `total` (итог попытки, `objective_results`).

	Рядом с ключом, идентификатором, текстом или вариантами — метка верного
	варианта, утечка при любом значении: `{"options": [{"key": "V2", "correct": true}]}`.
	"""
	if словарь.keys() & КЛЮЧИ_ВАРИАНТА:
		return False
	if isinstance(значение, bool):
		return ключ_выше == "verdict"
	return isinstance(значение, int | float) and "total" in словарь


def _законное_пояснение(словарь: dict, ключ_выше, выше) -> bool:
	"""Пояснение — к верному ответу в его вердикте или к вопросу в
	`explanations` итога сданной попытки (CONTRACT.md, «Квиз урока из релиза»)."""
	if ключ_выше == "verdict":
		return словарь.get("correct") is True
	return ключ_выше == "explanations" and isinstance(выше, dict) and выше.get("passed") is True


def _поля(данные, ключ_выше=None, выше=None):
	"""Все ключи словарей ответа на любой глубине: `(ключ, значение, словарь,
	ключ_выше, выше)` — словарь, где лежит ключ, ключ, под которым лежит сам
	словарь (список прозрачен), и словарь, где лежит тот ключ.

	Строка, которая сама разбирается как JSON (снимок вопросов попытки в
	базе), проверяется изнутри — и закодированная дважды тоже: разбор идёт,
	пока строка снова оказывается JSON.
	"""
	import json

	while isinstance(данные, str):
		try:
			данные = json.loads(данные)
		except ValueError:
			return
	if isinstance(данные, dict):
		for ключ, значение in данные.items():
			yield ключ, значение, данные, ключ_выше, выше
			yield from _поля(значение, ключ, данные)
	elif isinstance(данные, list):
		for элемент in данные:
			yield from _поля(элемент, ключ_выше, выше)
