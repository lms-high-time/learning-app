"""Что не имеет права появиться в ответе наружу.

Один дом для списков, которые проверяют тесты. `Why:` копий было три, и ни
одна не была надмножеством другой: `owner` заявлен в контракте, но самой
широкой проверкой не проверялся. Разъехавшиеся списки означают, что часть
проверок слабее, чем выглядит.
"""

#: Поля эталона квиза в релизе (`lessons[].quiz.answers`): ответы вопросов,
#: верный вариант, пояснение. Ищутся ключами JSON, а не подстрокой: `correct`
#: законно приходит вердиктом (`true`/`false`) и счётом верных в итоге, а
#: верный вариант эталона — ключ варианта, строка.
ПОЛЯ_ЭТАЛОНА = (
	"answers",
	"correct",
	"explanation",
)

#: Внутренние структуры Frappe. Контракт обязан оставаться интерфейсом общего
#: назначения — тем, который мог бы реализовать другой backend.
ВНУТРЕННОСТИ_FRAPPE = (
	"doctype",
	"docstatus",
	"modified_by",
	"owner",
	"idx",
	"parenttype",
)


def проверить_ответ(
	тест, ответ, что: str, запрещённые_тексты: tuple[str, ...] = (), кроме: tuple[str, ...] = ()
) -> str:
	"""Утверждает, что в ответе нет ни эталонов, ни внутренностей Frappe.

	`запрещённые_тексты` — конкретные значения из базы: проверка по именам
	полей пропустит утечку вида ``{"hint": <текст пояснения>}``, а проверка по
	тексту — нет. `кроме` — имена из списков, которые у этого ответа законны:
	`owner` у таблицы документа — блок, который её заводит (CONTRACT.md,
	«Зачем контракт именно такой»); `explanation` в итоге сданной попытки.
	"""
	import json

	выдано = json.dumps(ответ, ensure_ascii=False, default=str)

	for поле, значение in _поля(json.loads(выдано)):
		if поле not in ПОЛЯ_ЭТАЛОНА or поле in кроме:
			continue
		if поле == "correct" and isinstance(значение, int | float):
			continue
		тест.fail(f"{что}: поле эталона «{поле}»: {значение!r}")
	for поле in ВНУТРЕННОСТИ_FRAPPE:
		if поле in кроме:
			continue
		тест.assertNotIn(поле, выдано, f"{что}: структура Frappe «{поле}»")
	for текст in запрещённые_тексты:
		тест.assertNotIn(текст, выдано, f"{что}: утёк текст «{текст}»")
	return выдано


def _поля(данные):
	"""Пары «ключ — значение» всех словарей ответа на любой глубине.

	Строка, которая сама разбирается как JSON (снимок вопросов попытки в
	базе), проверяется изнутри.
	"""
	import json

	if isinstance(данные, str):
		try:
			данные = json.loads(данные)
		except ValueError:
			return
		if isinstance(данные, str):
			return
	if isinstance(данные, dict):
		for ключ, значение in данные.items():
			yield ключ, значение
			yield from _поля(значение)
	elif isinstance(данные, list):
		for элемент in данные:
			yield from _поля(элемент)
