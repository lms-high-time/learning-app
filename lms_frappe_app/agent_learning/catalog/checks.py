"""Проверка каталога компетенций и вид правки компетенции (learning-services#825).

Схема — `catalog.public.schema.json` рядом, проверяет её та же проверка, что
релиз курса (`releases.schema`). Сверх схемы — ключи уникальны, класс
компетенции — из списка своей схемы, класс в каждой обязательной схеме есть,
ссылки составляющих и похожих сходятся, у базовой нет составляющих, у
интегративной — не меньше двух различных и не она сама, связи «часть» без
кругов, компетенция не похожа сама на себя. Коды — как у проверки релиза.
Содержание текстов не проверяется. Формат — `CONTRACT.md`, раздел «Каталог
компетенций». Всё здесь — без базы.
"""

import json
from functools import cache
from pathlib import Path

from lms_frappe_app.agent_learning.releases import checks as проверки_релиза
from lms_frappe_app.agent_learning.releases import schema as проверка_схемы

СХЕМА = Path(__file__).with_name("catalog.public.schema.json")
ФОРМАТ = "lms-competency-catalog/1"
УРОВНИ = ("1", "2", "3", "4")

ДОБАВЛЕНА, ПО_СУЩЕСТВУ, РЕДАКТОРСКАЯ = "added", "substantive", "editorial"


@cache
def схема() -> dict:
	return json.loads(СХЕМА.read_text(encoding="utf-8"))


def ошибки_схемы(каталог) -> list[dict]:
	"""Расхождения каталога со схемой — `[{path, message}]`; пусто — подходит."""
	return проверка_схемы.ошибки(каталог, корень=схема())


def проблемы(каталог: dict) -> list[dict]:
	"""Расхождения сверх схемы — `[{code, where, …}]`. Каталог уже прошёл схему."""
	найдено: list[dict] = []
	схемы = {с["key"]: с for с in каталог["classifications"]}
	проверки_релиза._повторы([с["key"] for с in каталог["classifications"]], "classifications", найдено)
	for ключ, с in схемы.items():
		проверки_релиза._повторы(с["source"], f"classifications[{ключ}].source", найдено)
		проверки_релиза._повторы(
			[к["key"] for к in с["classes"]], f"classifications[{ключ}].classes", найдено
		)
	классы = {ключ: {к["key"] for к in с["classes"]} for ключ, с in схемы.items()}
	обязательные = [ключ for ключ, с in схемы.items() if с["required"]]
	проверки_релиза._повторы([к["key"] for к in каталог["competencies"]], "competencies", найдено)
	компетенции = {к["key"]: к for к in каталог["competencies"]}
	for ключ, комп in компетенции.items():
		свои = комп.get("classes") or {}
		for схема_, класс in свои.items():
			if схема_ not in классы:
				проверки_релиза._ссылка(найдено, f"competencies[{ключ}].classes", схема_)
			elif класс not in классы[схема_]:
				проверки_релиза._ссылка(найдено, f"competencies[{ключ}].classes.{схема_}", класс)
		for схема_ in обязательные:
			if схема_ not in свои:
				найдено.append(
					{
						"code": "class_required",
						"where": f"competencies[{ключ}].classes",
						"classification": схема_,
						"message": "нет класса в обязательной схеме",
					}
				)
		где = f"competencies[{ключ}].similar"
		похожие = комп.get("similar") or []
		проверки_релиза._повторы(похожие, где, найдено)
		for похожая in похожие:
			if похожая == ключ:
				найдено.append(
					{
						"code": "competency_similar",
						"where": где,
						"message": "компетенция не похожа сама на себя",
					}
				)
			elif похожая not in компетенции:
				проверки_релиза._ссылка(найдено, где, похожая)
	проверки_релиза.связи_компетенций(компетенции, найдено)
	return найдено


def канон(каталог: dict) -> dict:
	"""Канонический вид каталога, прошедшего проверки: схемы классификации, их классы и
	компетенции — по ключу, первоисточники схемы — по алфавиту, составляющие — по ключу
	с целым уровнем (`3.0` — то же, что `3`), похожие — по алфавиту, пустых `classes`,
	`parts` и `similar` нет. Дайджест, снимок выпуска и вид правки считаются по нему.

	`Why:` перестановка компетенций в источнике или пустой список связей вместо
	отсутствующего иначе давали бы новый выпуск без единой правки.
	"""

	def компетенция(к: dict) -> dict:
		итог = {поле: к[поле] for поле in ("key", "title", "description", "kind")}
		if классы := к.get("classes"):
			итог["classes"] = dict(sorted(классы.items()))
		итог["levels"] = {уровень: к["levels"][уровень] for уровень in УРОВНИ}
		части = sorted(
			(
				{"competency": ч["competency"], "from_level": int(ч["from_level"])}
				for ч in к.get("parts") or []
			),
			key=lambda ч: ч["competency"],
		)
		if части:
			итог["parts"] = части
		if похожие := sorted(к.get("similar") or []):
			итог["similar"] = похожие
		return итог

	return {
		"format": каталог["format"],
		"classifications": sorted(
			map(схема_классификации, каталог["classifications"]), key=lambda с: с["key"]
		),
		"competencies": sorted(map(компетенция, каталог["competencies"]), key=lambda к: к["key"]),
	}


def схема_классификации(с: dict) -> dict:
	"""Схема классификации в каноническом виде: классы — по ключу, первоисточники — по
	алфавиту: их порядок ничего не значит."""
	return {
		"key": с["key"],
		"title": с["title"],
		"source": sorted(с["source"]),
		"required": с["required"],
		"classes": sorted(
			({"key": к["key"], "title": к["title"]} for к in с["classes"]), key=lambda к: к["key"]
		),
	}


def признаки(компетенция: dict) -> dict:
	"""Признаки уровней `{"1": текст, …, "4": текст}` для сравнения по существу: пробелы
	схлопнуты, края обрезаны — правка одних пробелов не поднимает версию."""
	return {уровень: " ".join(компетенция["levels"][уровень].split()) for уровень in УРОВНИ}


#: Поля, правка которых редакторская, — в порядке, в каком их называет `правки`.
#: `levels` — признаки, изменённые только пробелами.
РЕДАКТОРСКИЕ_ПОЛЯ = ("title", "description", "kind", "classes", "parts", "similar", "levels")
#: Поля схемы классификации, правку которых называет `правки` (`classifications.changed`).
ПОЛЯ_СХЕМЫ = ("title", "source", "required")


def правки(прежний: dict | None, новый: dict, версии: dict[str, int], схемы: dict[str, dict]) -> dict:
	"""Правки нового каталога против опубликованного; оба — в каноническом виде (`канон`).

	`{added: [ключ], substantive: [{key, version}], editorial: [{key, fields}],
	classifications: {added: [ключ], changed: [{key, fields}], classes: {added: {схема:
	[класс]}, renamed: {схема: [класс]}}}}` — по порядку нового каталога; неизменённых
	нет ни в одном списке.

	Новая компетенция, схема или класс — те, которых нет в базе (`версии` — текущая
	версия каждой опубликованной компетенции, `схемы` — каждая опубликованная схема в
	каноническом виде, `схема_классификации`), а не в прежнем снимке: запись решает
	база. Классы новой схемы — тоже новые. `changed` — схемы с изменёнными полями
	(`ПОЛЯ_СХЕМЫ`), `renamed` — классы с новым названием. По существу — изменился
	признак хотя бы одного уровня (`признаки`): версия растёт на один. Остальное —
	редакторская правка, версия та же; `fields` — изменённые поля
	(`РЕДАКТОРСКИЕ_ПОЛЯ`): тип и состав составляющих меняют карты курсов, и
	публикатор должен это видеть. Компетенция в базе, но не в прежнем снимке —
	по существу: сравнить её не с чем.
	"""
	было = {к["key"]: к for к in (прежний or {}).get("competencies", [])}
	итог: dict = {ДОБАВЛЕНА: [], ПО_СУЩЕСТВУ: [], РЕДАКТОРСКАЯ: []}
	for комп in новый["competencies"]:
		ключ = комп["key"]
		прежняя = было.get(ключ)
		if ключ not in версии:
			итог[ДОБАВЛЕНА].append(ключ)
		elif прежняя is None or признаки(прежняя) != признаки(комп):
			итог[ПО_СУЩЕСТВУ].append({"key": ключ, "version": версии[ключ] + 1})
		elif поля := [п for п in РЕДАКТОРСКИЕ_ПОЛЯ if прежняя.get(п) != комп.get(п)]:
			итог[РЕДАКТОРСКАЯ].append({"key": ключ, "fields": поля})
	итог["classifications"] = правки_схем(новый["classifications"], схемы)
	return итог


def правки_схем(новые: list[dict], схемы: dict[str, dict]) -> dict:
	"""Раздел `classifications` правок (`правки`): `новые` — схемы нового каталога,
	`схемы` — опубликованные, обе в каноническом виде."""
	итог = пустые_правки()["classifications"]
	for схема_ in новые:
		ключ = схема_["key"]
		была = схемы.get(ключ)
		if была is None:
			итог[ДОБАВЛЕНА].append(ключ)
		elif поля := [п for п in ПОЛЯ_СХЕМЫ if была[п] != схема_[п]]:
			итог["changed"].append({"key": ключ, "fields": поля})
		названия = {к["key"]: к["title"] for к in (была or {}).get("classes", [])}
		if новые_классы := [к["key"] for к in схема_["classes"] if к["key"] not in названия]:
			итог["classes"][ДОБАВЛЕНА][ключ] = новые_классы
		if другие := [
			к["key"] for к in схема_["classes"] if к["key"] in названия and названия[к["key"]] != к["title"]
		]:
			итог["classes"]["renamed"][ключ] = другие
	return итог


def пустые_правки() -> dict:
	"""Правки публикации, которая ничего не изменила."""
	return {
		ДОБАВЛЕНА: [],
		ПО_СУЩЕСТВУ: [],
		РЕДАКТОРСКАЯ: [],
		"classifications": {ДОБАВЛЕНА: [], "changed": [], "classes": {ДОБАВЛЕНА: {}, "renamed": {}}},
	}
