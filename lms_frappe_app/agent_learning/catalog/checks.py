"""Проверка каталога компетенций и вид правки компетенции (learning-services#825).

Схема — `catalog.public.schema.json` рядом, проверяет её та же проверка, что
релиз курса (`releases.schema`). Сверх схемы — ключи уникальны, ссылки
области, составляющих и похожих сходятся, у базовой нет составляющих, у
интегративной — не меньше двух различных и не она сама, связи «часть» без
кругов, компетенция не похожа сама на себя. Коды — как у проверки релиза.
Содержание текстов не проверяется. Формат — `CONTRACT.md`, раздел «Каталог
компетенций». Всё здесь — без базы.
"""

import json
from functools import cache
from pathlib import Path

from lms_frappe_app.agent_learning.releases import checks as проверки_релиза
from lms_frappe_app.agent_learning.releases import schema as проверка_схемы

СХЕМА = Path(__file__).with_name("catalog.public.schema.json")
ФОРМАТ = "lms-competency-catalog/1"
УРОВНИ = ("1", "2", "3", "4")

ДОБАВЛЕНА, ПО_СУЩЕСТВУ, РЕДАКТОРСКАЯ = "added", "substantive", "editorial"


@cache
def схема() -> dict:
	return json.loads(СХЕМА.read_text(encoding="utf-8"))


def ошибки_схемы(каталог) -> list[dict]:
	"""Расхождения каталога со схемой — `[{path, message}]`; пусто — подходит."""
	return проверка_схемы.ошибки(каталог, корень=схема())


def проблемы(каталог: dict) -> list[dict]:
	"""Расхождения сверх схемы — `[{code, where, …}]`. Каталог уже прошёл схему."""
	найдено: list[dict] = []
	области = {о["key"] for о in каталог["areas"]}
	проверки_релиза._повторы([о["key"] for о in каталог["areas"]], "areas", найдено)
	проверки_релиза._повторы([к["key"] for к in каталог["competencies"]], "competencies", найдено)
	компетенции = {к["key"]: к for к in каталог["competencies"]}
	for ключ, комп in компетенции.items():
		if комп["area"] not in области:
			проверки_релиза._ссылка(найдено, f"competencies[{ключ}].area", комп["area"])
		где = f"competencies[{ключ}].similar"
		похожие = комп.get("similar") or []
		проверки_релиза._повторы(похожие, где, найдено)
		for похожая in похожие:
			if похожая == ключ:
				найдено.append(
					{
						"code": "competency_similar",
						"where": где,
						"message": "компетенция не похожа сама на себя",
					}
				)
			elif похожая not in компетенции:
				проверки_релиза._ссылка(найдено, где, похожая)
	проверки_релиза.связи_компетенций(компетенции, найдено)
	return найдено


def канон(каталог: dict) -> dict:
	"""Канонический вид каталога, прошедшего проверки: области и компетенции — по ключу,
	составляющие — по ключу с целым уровнем (`3.0` — то же, что `3`), похожие — по
	алфавиту, пустых `parts` и `similar` нет. Дайджест, снимок выпуска и вид правки
	считаются по нему.

	`Why:` перестановка компетенций в источнике или пустой список связей вместо
	отсутствующего иначе давали бы новый выпуск без единой правки.
	"""

	def компетенция(к: dict) -> dict:
		итог = {поле: к[поле] for поле in ("key", "title", "description", "kind", "area")}
		итог["levels"] = {уровень: к["levels"][уровень] for уровень in УРОВНИ}
		части = sorted(
			(
				{"competency": ч["competency"], "from_level": int(ч["from_level"])}
				for ч in к.get("parts") or []
			),
			key=lambda ч: ч["competency"],
		)
		if части:
			итог["parts"] = части
		if похожие := sorted(к.get("similar") or []):
			итог["similar"] = похожие
		return итог

	return {
		"format": каталог["format"],
		"areas": sorted(
			({"key": о["key"], "title": о["title"]} for о in каталог["areas"]), key=lambda о: о["key"]
		),
		"competencies": sorted(map(компетенция, каталог["competencies"]), key=lambda к: к["key"]),
	}


def признаки(компетенция: dict) -> dict:
	"""Признаки уровней `{"1": текст, …, "4": текст}` для сравнения по существу: пробелы
	схлопнуты, края обрезаны — правка одних пробелов не поднимает версию."""
	return {уровень: " ".join(компетенция["levels"][уровень].split()) for уровень in УРОВНИ}


#: Поля, правка которых редакторская, — в порядке, в каком их называет `правки`.
#: `levels` — признаки, изменённые только пробелами.
РЕДАКТОРСКИЕ_ПОЛЯ = ("title", "description", "kind", "area", "parts", "similar", "levels")


def правки(прежний: dict | None, новый: dict, версии: dict[str, int], области: dict[str, str]) -> dict:
	"""Правки нового каталога против опубликованного; оба — в каноническом виде (`канон`).

	`{added: [ключ], substantive: [{key, version}], editorial: [{key, fields}],
	areas: {added: [ключ], renamed: [ключ]}}` — по порядку нового каталога;
	неизменённых нет ни в одном списке.

	Новая компетенция или область — та, которой нет в базе (`версии` — текущая версия
	каждой опубликованной компетенции, `области` — название каждой опубликованной
	области), а не в прежнем снимке: запись решает база. По существу — изменился
	признак хотя бы одного уровня (`признаки`): версия растёт на один. Остальное —
	редакторская правка, версия та же; `fields` — изменённые поля
	(`РЕДАКТОРСКИЕ_ПОЛЯ`): тип и состав составляющих меняют карты курсов, и
	публикатор должен это видеть. Компетенция в базе, но не в прежнем снимке —
	по существу: сравнить её не с чем.
	"""
	было = {к["key"]: к for к in (прежний or {}).get("competencies", [])}
	итог: dict = {ДОБАВЛЕНА: [], ПО_СУЩЕСТВУ: [], РЕДАКТОРСКАЯ: []}
	for комп in новый["competencies"]:
		ключ = комп["key"]
		прежняя = было.get(ключ)
		if ключ not in версии:
			итог[ДОБАВЛЕНА].append(ключ)
		elif прежняя is None or признаки(прежняя) != признаки(комп):
			итог[ПО_СУЩЕСТВУ].append({"key": ключ, "version": версии[ключ] + 1})
		elif поля := [п for п in РЕДАКТОРСКИЕ_ПОЛЯ if прежняя.get(п) != комп.get(п)]:
			итог[РЕДАКТОРСКАЯ].append({"key": ключ, "fields": поля})
	итог["areas"] = {
		ДОБАВЛЕНА: [о["key"] for о in новый["areas"] if о["key"] not in области],
		"renamed": [
			о["key"] for о in новый["areas"] if о["key"] in области and области[о["key"]] != о["title"]
		],
	}
	return итог


def пустые_правки() -> dict:
	"""Правки публикации, которая ничего не изменила."""
	return {ДОБАВЛЕНА: [], ПО_СУЩЕСТВУ: [], РЕДАКТОРСКАЯ: [], "areas": {ДОБАВЛЕНА: [], "renamed": []}}
