import frappe
from frappe.model.document import Document

#: Флаг документа: запись пишет публикация каталога (`catalog.service`).
ИЗ_КАТАЛОГА = "from_competency_catalog"


def только_из_каталога(документ: Document, что: str) -> None:
	"""Отказ, если запись сохраняют мимо публикации каталога; удаление — всегда отказ.

	`Why:` у каталога один дом — источник курсов, выпуск переносит его сюда
	целиком. Правка в Desk завела бы вторую копию, которую следующий выпуск
	молча перепишет; удаление оставило бы свидетельства с ключом в никуда.
	"""
	if not документ.flags.get(ИЗ_КАТАЛОГА):
		frappe.throw(
			frappe._("{0} правится только выпуском каталога").format(что),
			title=frappe._("Каталог компетенций"),
		)


class AgentCompetency(Document):
	"""Компетенция опубликованного каталога: слаг — имя записи (learning-services#825).

	Текущее состояние по последнему выпуску каталога; прежние состояния — в
	снимках выпусков. Версия растёт, только когда меняется признак хотя бы
	одного уровня; её вычисляет публикация.
	"""

	def validate(self):
		только_из_каталога(self, frappe._("Компетенция"))

	def on_trash(self):
		frappe.throw(
			frappe._("Компетенция каталога не удаляется: ключ — имя компетенции в журнале свидетельств"),
			title=frappe._("Каталог компетенций"),
		)
