import frappe
from frappe.model.document import Document

#: Флаг запроса: курс с этим именем удаляется целиком, и его релизы — с ним.
УДАЛЯЕТСЯ_КУРС = "release_course_deleting"


class AgentCourseRelease(Document):
	"""Опубликованный релиз курса: снимок и индекс по ключам (learning-services#500).

	Неизменяем. `Why:` на релиз будут ссылаться прохождения учеников (этап 2):
	правка снимка задним числом переписала бы, по чему ученик занимался.
	Исправление — новый релиз. Отказ — на любом сохранении существующей
	записи: дочерние строки индекса тоже часть релиза, и поштучная сверка
	полей была бы дырявой.
	"""

	def validate(self):
		if self.is_new():
			return
		frappe.throw(frappe._("Релиз не правится: опубликуйте новый"), title=frappe._("Релиз неизменяем"))

	def on_trash(self):
		"""Релиз не удаляется. `Why:` прохождения, заметки, репорты и попытки
		ссылаются на релиз как на версию, по которой они сделаны, а записи
		релизов курса — его история версий.

		Исключение — курс удаляется целиком (`releases.service.удалить_курс`):
		истории больше не к чему относиться."""
		if frappe.flags.get(УДАЛЯЕТСЯ_КУРС) == self.course:
			return
		frappe.throw(
			frappe._("Релиз не удаляется: записи релизов — история версий курса"),
			title=frappe._("Релиз неизменяем"),
		)
