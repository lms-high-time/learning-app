"""OAuth-клиенты агентов: роли, чей это агент и когда их токены отзываются.

Агент ученика или куратора регистрирует OAuth-клиента во Frappe сам
(динамическая регистрация) и авторизуется им от имени пользователя. Frappe
при этом разрешает клиент только `Desk User`, и ученик без desk-доступа
получал на странице авторизации «Invalid client_id parameter value» —
то есть не мог подключить агента вообще. Роли платформы добавляются каждому
клиенту; `Desk User` не отнимается.
"""

from urllib.parse import urlparse

import frappe

from lms_frappe_app.agent_learning import cimd
from lms_frappe_app.install import КЛЮЧ_ЧАТА_ID

РОЛИ_ПЛАТФОРМЫ = ("LMS Student", "Course Creator")


def разрешить_роли_платформы(doc, method=None) -> None:
	"""Хук `validate` OAuth Client: идёт после `add_default_role` Frappe."""
	есть = {р.role for р in doc.allowed_roles}
	for роль in РОЛИ_ПЛАТФОРМЫ:
		if роль not in есть:
			doc.append("allowed_roles", {"role": роль})


#: Агент — по домену адресов возврата клиента. `Why:` `app_name` клиент пишет
#: о себе сам при динамической регистрации, а адрес возврата — то, куда Frappe
#: отдаёт код авторизации. Агент назван, только когда все адреса клиента — из
#: его домена: клиент, добавивший к своему адресу `claude.ai`, вошёл бы через
#: свой и в отчёте числился бы Claude.
АГЕНТЫ_ПО_ДОМЕНУ = {"claude.ai": "Claude", "chatgpt.com": "ChatGPT"}
ВЕБ_ЧАТ = "Веб-чат"
ДРУГОЙ_АГЕНТ = "Другой"


def агент_клиента(клиент: str, redirect_uris: str | None, клиент_чата: str | None) -> str:
	"""Чей OAuth-клиент: Claude, ChatGPT, веб-чат платформы или другой агент.

	`клиент_чата` — имя клиента веб-чата из конфигурации сайта. Незнакомый
	клиент — «Другой», а не ошибка: подключить коннектор может любой агент.
	"""
	if клиент_чата and клиент == клиент_чата:
		return ВЕБ_ЧАТ
	# Клиент по адресу документа назван сайтом, который этот документ публикует
	# (learning-services#661): у Claude Code адреса возврата локальные.
	if cimd.это_адрес_клиента(клиент):
		return _агент_адреса(клиент) or ДРУГОЙ_АГЕНТ
	агенты = {_агент_адреса(адрес) for адрес in (redirect_uris or "").split()}
	if len(агенты) == 1 and None not in агенты:
		return агенты.pop()
	return ДРУГОЙ_АГЕНТ


def _агент_адреса(адрес: str) -> str | None:
	хост = (urlparse(адрес).hostname or "").lower()
	for домен, агент in АГЕНТЫ_ПО_ДОМЕНУ.items():
		if хост == домен or хост.endswith("." + домен):
			return агент
	return None


def отозвать_чат_при_выходе(login_manager=None) -> None:
	"""Хук `on_logout`: выход из Cenda закрывает и веб-чат.

	`Why:` у чата свой вход — кука и OAuth-токен ученика в памяти сервиса, — и
	выход из Cenda их не трогал: после «Выйти» «Начать бесплатно» открывала
	чат прежнего ученика, на общем компьютере — чужие уроки и документы
	(learning-services#656). Отозванный токен чат на следующем ходе получает
	отказом и уводит на вход. Токены других агентов — подключения, которые
	ученик сделал сам, — выход не трогает: агент работает и без открытого
	браузера.

	Хук идёт до удаления сессии, поэтому выходящий — `frappe.session.user`.
	Пути выхода без этого хука — сброс сессий при смене пароля, истечение
	сессии, а у выхода «за другого» (админ отключает пользователя) хук видит
	админа — закрывает сверка входа в самом чате: при открытии он спрашивает
	Frappe, кто вошёл.

	Сбой отзыва выход не останавливает: выйти из Cenda должно получаться
	всегда, а чат подстрахует та же сверка.
	"""
	клиент = frappe.conf.get(КЛЮЧ_ЧАТА_ID)
	пользователь = frappe.session.user
	if not клиент or not пользователь or пользователь == "Guest":
		return
	try:
		frappe.db.set_value(
			"OAuth Bearer Token",
			{"client": клиент, "user": пользователь, "status": "Active"},
			"status",
			"Revoked",
			update_modified=False,
		)
	except Exception:
		frappe.log_error(title="Токены веб-чата не отозваны при выходе")


def отозвать_токены_пользователя(пользователь: str) -> None:
	"""Все действующие токены и неиспользованные коды пользователя — у всех
	агентов и веб-чата.

	`Why:` токен обновления не смотрел ни на пароль, ни на `enabled`: агент
	закрытого аккаунта получал новые токены, а интроспекция Frappe называла их
	действующими (learning-services#631). Смена пароля — признак, что прежний
	мог утечь, и подключения, сделанные с ним, тоже под подозрением. Код,
	выданный до смены, обменялся бы на новый токен уже после неё.
	"""
	# Коды — первыми: обмен кода держит его строку до выдачи токена, и
	# обновление ждёт его, а токен, выданный этим обменом, гасится следом.
	# По первичному ключу: у `user` кода нет индекса, и обновление по нему
	# заблокировало бы всю таблицу кодов.
	коды = frappe.get_all(
		"OAuth Authorization Code", filters={"user": пользователь, "validity": "Valid"}, pluck="name"
	)
	if коды:
		frappe.db.set_value(
			"OAuth Authorization Code", {"name": ("in", коды)}, "validity", "Invalid", update_modified=False
		)
	frappe.db.set_value(
		"OAuth Bearer Token",
		{"user": пользователь, "status": "Active"},
		"status",
		"Revoked",
		update_modified=False,
	)


def заметить_смену_пароля(doc, method=None) -> None:
	"""Хук `before_validate` User: новый пароль виден только до `validate`.

	`Why:` `User.validate` переносит `new_password` в закрытый атрибут и
	очищает поле, а сам пароль пишет в `on_update` — там его уже не видно.
	"""
	doc.flags.lms_пароль_сменён = bool(doc.new_password) and not doc.is_new()


def отозвать_при_смене_доступа(doc, method=None) -> None:
	"""Хук `on_update` User: пароль сменён в desk или аккаунт отключён."""
	отключён = not doc.enabled and doc.has_value_changed("enabled")
	if doc.flags.lms_пароль_сменён or отключён:
		отозвать_токены_пользователя(doc.name)


def удалить_токены(doc, method=None) -> None:
	"""Хук `on_trash` User: токены удаляются вместе с пользователем.

	Удаляются, а не отзываются: отозванный токен по-прежнему ссылается на
	пользователя, и Frappe не дал бы его удалить. Проверка ссылок идёт после
	`on_trash`, а отказ в ней откатывает и это удаление.
	"""
	frappe.db.delete("OAuth Bearer Token", {"user": doc.name})
