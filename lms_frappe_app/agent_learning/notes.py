"""Заметки автора: адрес места, переходы статуса и чей ход.

Заметка — не содержание курса: её пишет человек в кабинете или агент
куратора, чтобы петля «увидел → агент поправил → принял» не шла через
пересказ в чате. Место — адрес по ключам релиза курса (learning-services#512);
заметка помнит релиз, к которому написана. Модуль к базе не ходит: разбор
адреса, правила переходов и очередь проверяются без курса в базе; есть ли
место в релизе, проверяет `releases.places`.

Статусы: `open` → `done` (агент, с тем, что поменял) → `accepted` (автор) или
назад в `open` с ответом автора. `via` — кто пишет: `author` или `agent`.
Агент ходит в MCP с токеном куратора, и по пользователю его запись от записи
автора не отличить; признак передаёт вызывающий. Это признак для очереди, а не
защита: писать могут только авторские роли.
"""

from lms_frappe_app.agent_learning.errors import Отказ

НЕВЕРНЫЙ_АДРЕС = "invalid_target"
НЕДОПУСТИМЫЙ_ПЕРЕХОД = "invalid_transition"

СТАТУСЫ = ("open", "done", "accepted")
ИСТОЧНИКИ = ("author", "agent")

#: Виды мест без ключа.
БЕЗ_КЛЮЧА = ("course", "agent.frame")
#: Виды мест с ключом: `<вид>.<ключ>`. Сначала составные: ключ сам может
#: содержать точку, и `agent.lesson.x` не должен разобраться как `agent`.
С_КЛЮЧОМ = (
	"agent.lesson",
	"agent.item",
	"chapter",
	"lesson",
	"objective",
	"goal",
	"question",
	"section",
	"map",
)
#: Виды, ключ которых — `<урок>/<пункт>`.
С_ПУНКТОМ = frozenset({"goal", "agent.item"})

ФОРМЫ_АДРЕСА = (
	"course, chapter.<ключ>, lesson.<ключ>, objective.<ключ>, goal.<урок>/<пункт>, "
	"question.<ключ>, section.<ключ>, agent.frame, agent.lesson.<ключ>, "
	"agent.item.<урок>/<пункт>, map.<узел>"
)

#: Допустимые переходы: (было, стало) → кто вправе и нужен ли текст.
ПЕРЕХОДЫ = {
	("open", "done"): ("agent", True),
	("done", "accepted"): ("author", False),
	("open", "accepted"): ("author", False),
	("done", "open"): ("author", True),
	("accepted", "open"): ("author", True),
}


def разобрать_адрес(target: str | None) -> dict:
	"""Адрес места заметки: `{kind, key}` — или `Отказ(invalid_target)`.

	Разбирается только форма. `key` у `goal` и `agent.item` — `<урок>/<пункт>`
	целиком: ключи релиза сами бывают с `/`, и разрезать их можно только по
	ключам уроков релиза.
	"""
	адрес = (target or "").strip()
	if адрес in БЕЗ_КЛЮЧА:
		return {"kind": адрес, "key": None}
	for вид in С_КЛЮЧОМ:
		if адрес.startswith(вид + "."):
			ключ = адрес[len(вид) + 1 :]
			if not ключ or ключ != ключ.strip():
				break
			if вид in С_ПУНКТОМ and not _с_пунктом(ключ):
				raise Отказ(НЕВЕРНЫЙ_АДРЕС, f"Пункт пишется как {вид}.<урок>/<пункт>", where="target")
			return {"kind": вид, "key": ключ}
	raise Отказ(НЕВЕРНЫЙ_АДРЕС, "Адрес не распознан: " + ФОРМЫ_АДРЕСА, where="target")


def адрес(разобранный: dict) -> str:
	"""Строка адреса по `{kind, key}` — обратное к `разобрать_адрес`."""
	return разобранный["kind"] + (f".{разобранный['key']}" if разобранный["key"] else "")


def _с_пунктом(ключ: str) -> bool:
	урок, _, пункт = ключ.partition("/")
	return bool(урок) and bool(пункт)


def проверить_переход(было: str, стало: str, via: str, текст: str | None) -> None:
	"""Отказ `invalid_transition`, если переход недопустим.

	Агент отмечает «сделано» и пишет, что поменял; принимает и возвращает
	автор, а возвращая — отвечает, что не так.
	"""
	правило = ПЕРЕХОДЫ.get((было, стало))
	if via not in ИСТОЧНИКИ or not правило:
		raise Отказ(НЕДОПУСТИМЫЙ_ПЕРЕХОД, f"Из «{было}» в «{стало}» перейти нельзя", status=было)
	кто, нужен_текст = правило
	if via != кто:
		raise Отказ(
			НЕДОПУСТИМЫЙ_ПЕРЕХОД,
			"Отметить «сделано» может агент" if стало == "done" else "Принять или вернуть может автор",
			status=было,
		)
	if нужен_текст and not (текст or "").strip():
		raise Отказ(
			НЕДОПУСТИМЫЙ_ПЕРЕХОД,
			"Напишите, что поменяли" if стало == "done" else "Напишите, что не так",
			status=было,
		)


def ждёт(статус: str, via: str, ответы: list[dict]) -> str | None:
	"""Чей ход: `author`, `agent` или `None`, если заметка принята.

	«Сделано» ждёт проверки автора. Открытое ждёт того, кто не сказал
	последнего слова: вопрос агента — автора, заметка автора — агента.
	"""
	if статус == "accepted":
		return None
	if статус == "done":
		return "author"
	последний = ответы[-1]["via"] if ответы else via
	return "author" if последний == "agent" else "agent"


def группа(статус: str, ход: str | None) -> str:
	"""Группа очереди кабинета: `check`, `question`, `agent`, `accepted`."""
	if статус == "accepted":
		return "accepted"
	if статус == "done":
		return "check"
	return "question" if ход == "author" else "agent"
