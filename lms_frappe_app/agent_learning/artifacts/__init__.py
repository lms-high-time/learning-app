"""Документ курса: поля, таблицы, холст, файлы (learning-services#329, #330, #351).

Блок документа, кроме текста, может нести **поля** — одиночные значения
(порог внимания, дата пересмотра) — и **колонки** — свой вклад в таблицу
документа. Таблица называется по ключу; блоки с одной таблицей вносят в неё
свои колонки, а строки у неё общие. Первый такой блок в схеме — хозяин
таблицы: только он заводит и удаляет строки, остальные заполняют свои колонки
у существующих. Так реестр рисков растёт по урокам, как задуман в курсе:
урок 2 заводит риски, урок 3 дописывает им оценку.

`Why:` десять markdown-текстов, сшитых ID в тексте, нельзя ни отсортировать,
ни проверить: ранг ученик считал руками, «ответ у каждого риска выше порога»
проверял на глаз агент. Здесь то же самое — данные, и проверка их формы —
дело сервера.

Модуль на каждую часть движка. Зависимости идут снизу вверх, круга нет:

- `codes` — коды отказов; ни от кого не зависит;
- `formulas` — язык формул: разбор и счёт;
- `schema` — схема блока и документа; опирается на `formulas`;
- `canvas` — холст документа; опирается на `schema`;
- `values` — значение клетки или поля по типу; опирается на `formulas`;
- `data` — данные документа ученика: запись, очистка, формулы посчитанными;
  опирается на `schema` и `values`;
- `fill` — заполненность блока и пустые клетки; опирается на `data`;
- `export` — таблицы для страницы и агента, markdown, книга Excel;
  опирается на `data`;
- `files` — блок как файл или ссылка; опирается только на `codes`;
- `course` — схемы документов курса: действующие версии и новая от автора;
  опирается на `schema`, `canvas` и `files`;
- `document` — документ ученика: содержимое, заполненность, блоки наружу,
  выгрузка файлом; опирается на `course`, `fill` и `export`;
- `write` — запись в документ ученика; опирается на `document`.

От `formulas` до `export` модули не ходят в базу: схема и данные приходят
словарями, наружу уходят словари, и проверяются они без сайта. `course`,
`document` и `write` ходят в базу, но права не проверяют: роль автора, доступ
ученика к курсу и пространство проверяют методы API, которые их зовут
(`api.student`, `api.authoring`, `api.team`). Путь метода — часть контракта,
поэтому методы живут там, а здесь — то, что они делают.
"""
