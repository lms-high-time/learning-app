"""Документ курса: разделы релиза и данные ученика по ним.

Документ описывается релизом целиком: раздел документа релиза — блок схемы с
теми же ключом, названием, описанием, `rows` (`one` или `many`) и текстовыми
колонками с `required` (`true`, `false` или `{"if_column": …}`). Ученик
заполняет раздел `many` строками, раздел `one` — полями; сервер проверяет
форму записи, обязательность и заполненность, по ним работают сигналы и
выгрузка.

Модуль на каждую часть движка. Зависимости идут снизу вверх, круга нет:

- `codes` — коды отказов; ни от кого не зависит;
- `schema` — раздел и схема документа: форма и проверка;
- `values` — значение клетки или поля: текст;
- `data` — данные документа ученика: чтение, запись раздела, очистка;
  опирается на `schema` и `values`;
- `fill` — заполненность раздела и пустые клетки; опирается на `data`;
- `export` — markdown раздела и документа, книга Excel; опирается на `data`;
- `course` — схемы документов курса: действующие версии и запись новой;
  опирается на `schema`;
- `document` — документ ученика: данные, заполненность, блоки наружу,
  выгрузка файлом; опирается на `course`, `fill` и `export`;
- `write` — запись в документ ученика; опирается на `document`.

От `schema` до `export` модули не ходят в базу: схема и данные приходят
словарями, наружу уходят словари, и проверяются они без сайта. `course`,
`document` и `write` ходят в базу, но права не проверяют: доступ ученика к
курсу и пространство проверяют методы API, которые их зовут (`api.student`,
`api.team`). Путь метода — часть контракта, поэтому методы живут там, а
здесь — то, что они делают.
"""
