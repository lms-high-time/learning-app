ФАЙЛ = {"kind": "file", "accept": "xlsx,csv"}
ГДЕ = {"artifact": "plan", "key": "money"}


def xlsx(*ряды, пустая_колонка: int | None = None) -> bytes:
	"""Книга, собранная программой: у формул нет посчитанных значений."""
	from openpyxl import Workbook
	from openpyxl.styles import Font

	книга = Workbook()
	лист = книга.active
	for ряд in ряды:
		лист.append(ряд)
	if пустая_колонка:
		# Отформатированная, но пустая колонка далеко справа — как в живом файле.
		лист.cell(row=1, column=пустая_колонка).font = Font(bold=True)
	поток = io.BytesIO()
	книга.save(поток)
	return поток.getvalue()


class TestИзBase64(UnitTestCase):
	def test_байты_из_base64(self):
		"""Пустое и битое — пустые байты: дальше `годность_файла` откажет `artifact_file_missing`."""
		abc = base64.b64encode(b"abc").decode()
		случаи = (
			("base64", abc, b"abc"),
			("пробелы и перевод строки по краям", f"  {abc}\n", b"abc"),
			("data-адрес браузера", f"data:text/csv;base64,{abc}", b"abc"),
			("data без запятой — не адрес", f"data:{abc}", b""),
			("None", None, b""),
			("пустая строка", "", b""),
			("только пробелы", "   ", b""),
			("битый base64", "не base64!", b""),
			("без выравнивания", abc[:-1], b""),
			("перевод строки внутри", f"{abc[:2]}\n{abc[2:]}", b""),
		)
		for что, вход, ожидание in случаи:
			with self.subTest(что):
				self.assertEqual(files.из_base64(вход), ожидание)


class TestГодностьФайла(UnitTestCase):
	def test_годный_файл_отдаёт_расширение(self):
		случаи = (
			("csv из accept", ФАЙЛ, "plan.csv", b"x", 10, "csv"),
			("расширение в верхнем регистре", ФАЙЛ, "PLAN.XLSX", b"x", 10, "xlsx"),
			("accept с точками, пробелами и регистром", {"kind": "file", "accept": " .CSV , xlsx"}, "a.csv", b"x", 10, "csv"),
			("accept списком, как отдаёт блок_наружу", {"kind": "file", "accept": ["csv"]}, "a.csv", b"x", 10, "csv"),
			("пустой accept — любое расширение", {"kind": "file", "accept": ""}, "photo.png", b"x", 10, "png"),
			("пустой accept — и без расширения", {"kind": "file"}, "README", b"x", 10, ""),
			("размер ровно в предел", ФАЙЛ, "plan.csv", b"x" * 10, 10, "csv"),
		)
		for что, блок, имя, данные, предел, ожидание in случаи:
			with self.subTest(что):
				self.assertEqual(files.годность_файла(блок, имя, данные, предел, **ГДЕ), ожидание)

	def test_отказы(self):
		"""Проверки по очереди: вид, пустота, расширение, размер; `где` — в подробностях."""
		случаи = (
			("файл в текстовый блок", {}, "plan.csv", b"x", 10, codes.ВИД_НЕ_ТОТ, {"kind": "text"}),
			("файл в блок-ссылку", {"kind": "link"}, "plan.csv", b"x", 10, codes.ВИД_НЕ_ТОТ, {"kind": "link"}),
			("вид раньше пустоты", {"kind": "text"}, "plan.csv", b"", 10, codes.ВИД_НЕ_ТОТ, {"kind": "text"}),
			("пустой файл", ФАЙЛ, "plan.csv", b"", 10, codes.ФАЙЛА_НЕТ, {}),
			("пустота раньше расширения", ФАЙЛ, "photo.png", b"", 10, codes.ФАЙЛА_НЕТ, {}),
			(
				"файл не того типа",
				ФАЙЛ,
				"photo.png",
				b"\x89PNG",
				10,
				codes.ФАЙЛ_НЕ_ТОГО_ТИПА,
				{"accept": ["xlsx", "csv"], "received": "png"},
			),
			(
				"файл без расширения",
				ФАЙЛ,
				"plan",
				b"x",
				10,
				codes.ФАЙЛ_НЕ_ТОГО_ТИПА,
				{"accept": ["xlsx", "csv"], "received": ""},
			),
			(
				"расширение раньше размера",
				ФАЙЛ,
				"photo.png",
				b"x" * 11,
				10,
				codes.ФАЙЛ_НЕ_ТОГО_ТИПА,
				{"received": "png"},
			),
			(
				"на байт больше предела",
				ФАЙЛ,
				"plan.csv",
				b"x" * 11,
				10,
				codes.ФАЙЛ_СЛИШКОМ_БОЛЬШОЙ,
				{"max_bytes": 10, "size": 11},
			),
		)
		for что, блок, имя, данные, предел, код, подробности in случаи:
			with self.subTest(что):
				with self.assertRaises(Отказ) as пойман:
					files.годность_файла(блок, имя, данные, предел, **ГДЕ)
				self.assertEqual(пойман.exception.код, код)
				self.assertEqual(
					{к: пойман.exception.подробности.get(к) for к in {**подробности, **ГДЕ}},
					{**подробности, **ГДЕ},
				)


class TestСрезТаблицы(UnitTestCase):
	def test_срез(self):
		длинная = "я" * 61
		случаи = (
			("не таблица", b"a;b\n1;2\n", "pdf", 20, None),
			(
				"csv через точку с запятой",
				"Месяц;Выручка;Расходы\nЯнварь;100;80\nФевраль;120;90\n".encode(),
				"csv",
				20,
				"| Месяц | Выручка | Расходы |\n| --- | --- | --- |\n| Январь | 100 | 80 |\n| Февраль | 120 | 90 |",
			),
			("csv через запятую", b"a,b\n1,2\n", "csv", 20, "| a | b |\n| --- | --- |\n| 1 | 2 |"),
			("csv через табуляцию", b"a\tb\n1\t2\n", "csv", 20, "| a | b |\n| --- | --- |\n| 1 | 2 |"),
			("BOM в начале csv", "﻿a;b\n1;2\n".encode(), "csv", 20, "| a | b |\n| --- | --- |\n| 1 | 2 |"),
			("шапка и не больше строк предела", b"a;b\n1;2\n3;4\n5;6\n", "csv", 1, "| a | b |\n| --- | --- |\n| 1 | 2 |"),
			("пустые строки выпадают", b"a;b\n;\n1;2\n", "csv", 20, "| a | b |\n| --- | --- |\n| 1 | 2 |"),
			("пустой файл", b"", "csv", 20, None),
			("только пустые ячейки", b";\n;\n", "csv", 20, None),
			(
				"пустые колонки справа не в срезе",
				b"a;b;;\n1;2;;\n",
				"csv",
				20,
				"| a | b |\n| --- | --- |\n| 1 | 2 |",
			),
			(
				"разделитель не угадан — запятая; короткая строка дополняется до ширины",
				b"a,b,c\n1,2,3\n4\n",
				"csv",
				20,
				"| a | b | c |\n| --- | --- | --- |\n| 1 | 2 | 3 |\n| 4 |  |  |",
			),
			(
				"черта экранируется, пробелы схлопываются",
				'a;b\n"x|y";"раз\n  два"\n'.encode(),
				"csv",
				20,
				"| a | b |\n| --- | --- |\n| x\\|y | раз два |",
			),
			(
				"длинная ячейка режется",
				f"a;b\n{'я' * 60};{длинная}\n".encode(),
				"csv",
				20,
				f"| a | b |\n| --- | --- |\n| {'я' * 60} | {'я' * 59}… |",
			),
			(
				"xlsx: без значения видна формула",
				xlsx(["Месяц", "Прибыль"], ["Январь", "=B2-C2"]),
				"xlsx",
				20,
				"| Месяц | Прибыль |\n| --- | --- |\n| Январь | =B2-C2 |",
			),
			(
				"xlsx: число — значением",
				xlsx(["Месяц", "Выручка"], ["Январь", 100]),
				"xlsx",
				20,
				"| Месяц | Выручка |\n| --- | --- |\n| Январь | 100 |",
			),
			(
				"#315 xlsx: отформатированная пустая колонка справа не в срезе",
				xlsx(["Гипотеза", "Охват"], ["Кофейня", 100], пустая_колонка=25),
				"xlsx",
				20,
				"| Гипотеза | Охват |\n| --- | --- |\n| Кофейня | 100 |",
			),
			(
				"xlsx: шапка и не больше строк предела",
				xlsx(["a"], [1], [2]),
				"xlsx",
				1,
				"| a |\n| --- |\n| 1 |",
			),
		)
		for что, данные, тип, строк, ожидание in случаи:
			with self.subTest(что):
				self.assertEqual(files.срез_таблицы(данные, тип, строк), ожидание)

	def test_нечитаемый_xlsx_исключение(self):
		"""Исключение ловит `срез` и отдаёт `None` с записью в лог."""
		with self.assertRaises(Exception):
			files.срез_таблицы(b"not a zip", "xlsx", 20)
