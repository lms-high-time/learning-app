"""Переход документа курса на новую версию шаблона (learning-services#376).

Версия шаблона может переименовать ключи прошлой версии — `renamed`:

    {"blocks": {"risks": "threats"},
     "fields": {"limit": "threshold"},
     "tables": {"register": "threats"},
     "columns": {"threats": {"event": "what"}}}

Старое имя — ключ прошлой версии, новое — этой; колонки — по таблице под её
новым именем. При переходе курса через несколько версий их переименования
складываются в одно (`сложить`), и им переименовываются правки курса, данные
учеников и старая схема — для разницы, которую увидит автор.

`Why:` без переименований новое имя колонки для курса — удалённая колонка и
новая пустая: ученик потерял бы заполненное, правки курса ссылались бы на
ключ, которого больше нет.

Модуль не ходит в базу: правки, схемы и данные приходят словарями.
"""

from __future__ import annotations

import copy
import json

from lms_frappe_app.agent_learning.artifacts.codes import НЕВЕРНЫЙ_ШАБЛОН
from lms_frappe_app.agent_learning.artifacts.schema import ключ_блока, поля_схемы, спек, таблицы_схемы
from lms_frappe_app.agent_learning.errors import Отказ

#: Что переименовывается. Колонки — словарь по таблицам, прочее — «старое →
#: новое».
ВИДЫ = ("blocks", "fields", "tables", "columns")


def разобрать(сырые, **где) -> dict:
	"""Переименования в каноническом виде: без пустых разделов; не та форма — отказ.

	Ключи блоков — в нижнем регистре, как их хранит схема.
	"""
	if сырые in (None, "", {}):
		return {}
	if isinstance(сырые, str):
		try:
			сырые = json.loads(сырые)
		except ValueError as ошибка:
			raise Отказ(НЕВЕРНЫЙ_ШАБЛОН, "Переименования — JSON", path="renamed", **где) from ошибка
	if not isinstance(сырые, dict):
		raise Отказ(НЕВЕРНЫЙ_ШАБЛОН, "Переименования — объект", path="renamed", **где)
	итог: dict = {}
	for вид, имена in сырые.items():
		if вид not in ВИДЫ:
			raise Отказ(НЕВЕРНЫЙ_ШАБЛОН, "Переименовываются " + ", ".join(ВИДЫ), path=f"renamed.{вид}", **где)
		if вид == "columns":
			if not isinstance(имена, dict):
				raise Отказ(НЕВЕРНЫЙ_ШАБЛОН, "Колонки — по таблицам", path="renamed.columns", **где)
			колонки = {
				str(таблица).strip(): _имена(кол, f"renamed.columns.{таблица}", str.strip, где)
				for таблица, кол in имена.items()
			}
			колонки = {таблица: кол for таблица, кол in колонки.items() if кол}
			if колонки:
				итог["columns"] = колонки
			continue
		нормализовать = _ключ if вид == "blocks" else str.strip
		имена = _имена(имена, f"renamed.{вид}", нормализовать, где)
		if имена:
			итог[вид] = имена
	return итог


def _ключ(значение: str) -> str:
	return значение.strip().lower()


def _имена(имена, путь: str, нормализовать, где: dict) -> dict[str, str]:
	if not isinstance(имена, dict):
		raise Отказ(НЕВЕРНЫЙ_ШАБЛОН, "Переименование — объект «старое: новое»", path=путь, **где)
	итог = {}
	for старое, новое in имена.items():
		if not isinstance(новое, str) or not новое.strip():
			raise Отказ(НЕВЕРНЫЙ_ШАБЛОН, "Новое имя — непустая строка", path=f"{путь}.{старое}", **где)
		итог[нормализовать(str(старое))] = нормализовать(новое)
	return итог


def проверить(переименования: dict, прежние: list | None, новые: list, **где) -> None:
	"""Переименования версии против прошлой версии и этой; не сходится — отказ с `path`.

	Старое имя было в прошлой версии, новое есть в этой. Новое имя не занято в
	прошлой версии — разве что само переименовано: обмен двух ключей законен.
	`Why:` иначе у ученика под одним ключом встретились бы данные двух разных
	колонок, и одни затёрли бы другие.
	"""
	if not переименования:
		return
	if прежние is None:
		raise Отказ(НЕВЕРНЫЙ_ШАБЛОН, "У первой версии переименовывать нечего", path="renamed", **где)
	было = _ключи(прежние)
	стало = _ключи(новые)
	for вид in ("blocks", "fields", "tables"):
		_проверить_имена(переименования.get(вид) or {}, было[вид], стало[вид], f"renamed.{вид}", где)
	таблицы = переименования.get("tables") or {}
	for таблица, колонки in (переименования.get("columns") or {}).items():
		путь = f"renamed.columns.{таблица}"
		if таблица not in стало["tables"]:
			raise Отказ(НЕВЕРНЫЙ_ШАБЛОН, "В этой версии нет такой таблицы", path=путь, **где)
		прежняя = _прежнее_имя(таблица, таблицы)
		if прежняя not in было["tables"]:
			raise Отказ(НЕВЕРНЫЙ_ШАБЛОН, "У таблицы нет прошлой версии", path=путь, **где)
		_проверить_имена(колонки, было["columns"][прежняя], стало["columns"][таблица], путь, где)


def _ключи(блоки: list) -> dict:
	таблицы = таблицы_схемы(блоки)
	return {
		"blocks": {_ключ(ключ_блока(б) or "") for б in блоки},
		"fields": set(поля_схемы(блоки)),
		"tables": set(таблицы),
		"columns": {имя: {к["key"] for к in т["columns"]} for имя, т in таблицы.items()},
	}


def _проверить_имена(имена: dict, было: set, стало: set, путь: str, где: dict) -> None:
	новые = list(имена.values())
	for старое, новое in имена.items():
		место = f"{путь}.{старое}"
		if старое not in было:
			raise Отказ(НЕВЕРНЫЙ_ШАБЛОН, "Старого имени нет в прошлой версии", path=место, **где)
		if новое not in стало:
			raise Отказ(НЕВЕРНЫЙ_ШАБЛОН, "Нового имени нет в этой версии", path=место, **где)
		if новое == старое:
			raise Отказ(НЕВЕРНЫЙ_ШАБЛОН, "Имя переименовано само в себя", path=место, **где)
		if новые.count(новое) > 1:
			raise Отказ(НЕВЕРНЫЙ_ШАБЛОН, "Два старых имени получили одно новое", path=место, **где)
		if новое in было and новое not in имена:
			raise Отказ(
				НЕВЕРНЫЙ_ШАБЛОН, "Новое имя занято в прошлой версии и не переименовано", path=место, **где
			)


def сложить(переименования: list[dict | None]) -> dict:
	"""Переименования версий по порядку — одним: от первой прошлой к последней.

	Ключ, который одна версия завела, а следующая переименовала, в данных
	курса ещё не встречался — в сумму он не входит. Переименование туда и
	обратно не оставляет ничего.
	"""
	итог: dict = {}
	for следующее in переименования:
		следующее = следующее or {}
		сумма = {
			вид: _сложить_имена(итог.get(вид) or {}, следующее.get(вид) or {})
			for вид in ("blocks", "fields", "tables")
		}
		сумма["columns"] = _сложить_колонки(итог, следующее)
		итог = {вид: имена for вид, имена in сумма.items() if имена}
	return итог


def _сложить_имена(первое: dict, второе: dict) -> dict:
	итог = {старое: второе.get(новое, новое) for старое, новое in первое.items()}
	for старое, новое in второе.items():
		# Имя, которое первое переименовало прочь, во втором — уже другой ключ,
		# заведённый заново: данных под ним у курса нет.
		if старое not in первое.values() and старое not in первое:
			итог[старое] = новое
	return {старое: новое for старое, новое in итог.items() if старое != новое}


def _сложить_колонки(первое: dict, второе: dict) -> dict:
	"""Колонки двух переименований — по таблицам под именем после второго."""
	таблицы_первого = первое.get("tables") or {}
	таблицы_второго = второе.get("tables") or {}
	итог = {
		таблицы_второго.get(таблица, таблица): dict(к) for таблица, к in (первое.get("columns") or {}).items()
	}
	for таблица, колонки in (второе.get("columns") or {}).items():
		середина = _прежнее_имя(таблица, таблицы_второго)
		if середина is None or _прежнее_имя(середина, таблицы_первого) is None:
			# Таблица заведена заново после прежней, переименованной прочь:
			# данных под ней у курса нет.
			continue
		итог[таблица] = _сложить_имена(итог.get(таблица) or {}, колонки)
	return {таблица: к for таблица, к in итог.items() if к}


def _прежнее_имя(имя: str, переименования: dict) -> str | None:
	"""Имя до переименования; `None` — имя заведено заново: прежнее ушло прочь."""
	for старое, новое in переименования.items():
		if новое == имя:
			return старое
	return None if имя in переименования else имя


def переименовать_правки(правки: dict, переименования: dict, таблицы_блоков: dict[str, str]) -> dict:
	"""Правки курса под ключи новой версии шаблона.

	`таблицы_блоков` — таблица каждого блока прошлой версии шаблона: колонки в
	правке блока — его колонки, и искать их переименование надо по его таблице.
	Добавленное курсом (ключи `add_*`) остаётся со своими ключами: курс их
	завёл, шаблон их не знает; переименовывается только `after` и таблица.
	"""
	if not переименования or not isinstance(правки, dict):
		return copy.deepcopy(правки)
	блоки = переименования.get("blocks") or {}
	поля = переименования.get("fields") or {}
	таблицы = переименования.get("tables") or {}
	колонки = переименования.get("columns") or {}

	def колонки_блока(ключ: str) -> dict:
		таблица = таблицы_блоков.get(ключ)
		if not таблица:
			return {}
		return колонки.get(таблицы.get(таблица, таблица)) or {}

	итог = copy.deepcopy(правки)
	if isinstance(итог.get("blocks"), dict):
		правленые = {}
		for сырой, правка in итог["blocks"].items():
			ключ = _ключ(str(сырой))
			if isinstance(правка, dict) and isinstance(правка.get("spec"), dict):
				_переименовать_схему_правки(правка["spec"], поля, таблицы, колонки_блока(ключ))
			правленые[блоки.get(ключ, сырой)] = правка
		итог["blocks"] = правленые
	if isinstance(итог.get("add_blocks"), list):
		for добавка in итог["add_blocks"]:
			if not isinstance(добавка, dict):
				continue
			_после(добавка, блоки, _ключ)
			if isinstance(добавка.get("spec"), dict):
				_таблица(добавка["spec"], таблицы)
	if isinstance(итог.get("canvas"), dict):
		итог["canvas"] = _переименовать_холст(итог["canvas"], блоки, поля, колонки_блока)
	return итог


def _переименовать_схему_правки(правка: dict, поля: dict, таблицы: dict, колонки: dict) -> None:
	for имя, имена in (("fields", поля), ("columns", колонки)):
		if isinstance(правка.get(имя), dict):
			правка[имя] = {имена.get(str(ключ).strip(), ключ): з for ключ, з in правка[имя].items()}
	for имя, имена in (("add_fields", поля), ("add_columns", колонки)):
		добавки = правка.get(имя)
		for добавка in добавки if isinstance(добавки, list) else ():
			if isinstance(добавка, dict):
				_после(добавка, имена, str.strip)
	_таблица(правка, таблицы)


def _после(добавка: dict, имена: dict, нормализовать) -> None:
	после = добавка.get("after")
	if isinstance(после, str) and нормализовать(после) in имена:
		добавка["after"] = имена[нормализовать(после)]


def _таблица(правка: dict, таблицы: dict) -> None:
	таблица = правка.get("table")
	if isinstance(таблица, str) and таблица.strip() in таблицы:
		правка["table"] = таблицы[таблица.strip()]


def _переименовать_холст(холст: dict, блоки: dict, поля: dict, колонки_блока) -> dict:
	"""Холст правки: ячейки сетки, подписи, сводка и набросок — ключи блоков;
	в сводке ещё поля и колонки таблицы блока."""
	if isinstance(холст.get("grid"), list):
		холст["grid"] = [
			" ".join(блоки.get(_ключ(к), к) for к in ряд.split()) if isinstance(ряд, str) else ряд
			for ряд in холст["grid"]
		]
	if isinstance(холст.get("labels"), dict):
		холст["labels"] = {блоки.get(_ключ(str(к)), к): п for к, п in холст["labels"].items()}
	if isinstance(холст.get("summary"), dict):
		сводка = {}
		for сырой, показать in холст["summary"].items():
			ключ = _ключ(str(сырой))
			if isinstance(показать, list):
				имена = {**поля, **колонки_блока(ключ)}
				показать = [имена.get(str(и).strip(), и) for и in показать]
			сводка[блоки.get(ключ, сырой)] = показать
		холст["summary"] = сводка
	if isinstance(холст.get("sketch"), str):
		холст["sketch"] = блоки.get(_ключ(холст["sketch"]), холст["sketch"])
	return холст


def переименовать_схему(блоки: list[dict], переименования: dict) -> list[dict]:
	"""Блоки схемы под ключами новой версии: ключ блока, таблица, поля, колонки.

	Для разницы: старая схема, переименованная так, сравнивается с новой, и
	переименование не выглядит удалённым и добавленным.
	"""
	имена_блоков = переименования.get("blocks") or {}
	поля = переименования.get("fields") or {}
	таблицы = переименования.get("tables") or {}
	колонки = переименования.get("columns") or {}
	итог = []
	for блок in блоки:
		блок = copy.deepcopy(блок)
		блок["key"] = имена_блоков.get(блок["key"], блок["key"])
		с = блок.get("spec")
		if isinstance(с, dict):
			for поле in с.get("fields") or []:
				поле["key"] = поля.get(поле["key"], поле["key"])
			if с.get("table"):
				с["table"] = таблицы.get(с["table"], с["table"])
				свои = колонки.get(с["table"]) or {}
				for колонка in с.get("columns") or []:
					колонка["key"] = свои.get(колонка["key"], колонка["key"])
		итог.append(блок)
	return итог


def переименовать_данные(данные: dict, переименования: dict) -> dict:
	"""Данные документа ученика — `{tables, fields, seq}` — под ключами новой версии.

	Под новым именем могли лежать данные блока, давно убранного из схемы:
	ученик их не видит. Переименованное их заменяет — это данные того, что
	ученик видит и заполнял.
	"""
	поля = переименования.get("fields") or {}
	таблицы = переименования.get("tables") or {}
	колонки = переименования.get("columns") or {}
	новые_таблицы = {}
	for таблица, строки in (данные.get("tables") or {}).items():
		свои = колонки.get(таблицы.get(таблица, таблица)) or {}
		новые_таблицы[таблица] = [
			_переименовать(строка, свои) if isinstance(строка, dict) else строка for строка in строки
		]
	return {
		**данные,
		"tables": _переименовать(новые_таблицы, таблицы),
		"fields": _переименовать(данные.get("fields") or {}, поля),
		"seq": _переименовать(данные.get("seq") or {}, таблицы),
	}


def _переименовать(словарь: dict, имена: dict) -> dict:
	"""Ключи словаря по переименованию; переименованное вытесняет прежнее под тем же ключом."""
	итог = {ключ: значение for ключ, значение in словарь.items() if ключ not in имена}
	for ключ, значение in словарь.items():
		if ключ in имена:
			итог[имена[ключ]] = значение
	return итог


def разница(было: list[dict], стало: list[dict]) -> dict:
	"""Что поменялось в схеме документа: блоки, поля, колонки таблиц.

	`было` — старая схема, уже переименованная (`переименовать_схему`).
	Колонки — «таблица.колонка». Изменённый блок — тот, что есть в обеих, но
	отличается чем угодно: подсказкой, уроком, схемой.
	"""
	прежние = {б["key"]: б for б in было}
	новые = {б["key"]: б for б in стало}
	поля_было, поля_стало = поля_схемы(было), поля_схемы(стало)
	колонки_было, колонки_стало = _колонки(было), _колонки(стало)
	return {
		"blocks": {
			"added": [к for к in новые if к not in прежние],
			"removed": [к for к in прежние if к not in новые],
			"changed": [к for к, б in новые.items() if к in прежние and прежние[к] != б],
		},
		"fields": {
			"added": [к for к in поля_стало if к not in поля_было],
			"removed": [к for к in поля_было if к not in поля_стало],
		},
		"columns": {
			"added": [к for к in колонки_стало if к not in колонки_было],
			"removed": [к for к in колонки_было if к not in колонки_стало],
		},
	}


def _колонки(блоки: list[dict]) -> list[str]:
	return [f"{имя}.{к['key']}" for имя, т in таблицы_схемы(блоки).items() for к in т["columns"]]


def таблицы_блоков(блоки: list[dict]) -> dict[str, str]:
	"""Таблица каждого блока с колонками — для `переименовать_правки`."""
	return {_ключ(ключ_блока(б) or ""): спек(б)["table"] for б in блоки if спек(б).get("columns")}
