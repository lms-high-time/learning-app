"""Итоговая схема документа курса: шаблон и правки курса (learning-services#370).

Шаблон — схема документа без уроков, общая для курсов. Правки — то, чем
документ курса отличается от шаблона: уроки блоков, подсказки, варианты
выбора, лишний блок, подписи холста.

    {"title": "…",
     "blocks": {"risks": {"lesson": "…", "hint": "…",
                          "spec": {"columns": {"source": {"options": ["…"]}},
                                   "add_columns": [{"key": "permit", "after": "source"}]}},
                "issues": null},
     "add_blocks": [{"key": "site_log", "title": "…", "after": "status"}],
     "canvas": {"labels": {"uvp": "…"}}}

Блок правится по ключу блока, поле и колонка — по своему ключу: в схеме они
списком, в правках — словарём. Объект сливается с объектом, `null` удаляет,
список заменяет список целиком. Новое — в `add_blocks`, `add_fields`,
`add_columns` с местом `after`.

`Why:` правка по позиции ломается от любого нового блока шаблона, а по ключу
переживает его. Ключ, которого в шаблоне нет, — отказ: опечатка в правке
иначе молча превратилась бы в «ничего не поменялось».

Модуль не ходит в базу: схему собранного документа проверяет тот же код, что
и схему от автора, — при записи.
"""

from __future__ import annotations

import copy

from lms_frappe_app.agent_learning.artifacts.codes import НЕВЕРНАЯ_СХЕМА, НЕВЕРНЫЕ_ПРАВКИ
from lms_frappe_app.agent_learning.errors import Отказ

#: Что правка может сказать о документе, блоке, схеме блока и холсте. Прочее
#: имя — отказ по той же причине, что и чужой ключ: опечатка.
СВОЙСТВА_ПРАВОК = ("title", "layout", "blocks", "add_blocks", "canvas")
СВОЙСТВА_БЛОКА = ("title", "hint", "lesson", "span", "kind", "accept", "spec")
СВОЙСТВА_СХЕМЫ = (
	"fields",
	"columns",
	"add_fields",
	"add_columns",
	"table",
	"prefix",
	"title",
	"rows",
	"views",
)
СВОЙСТВА_ХОЛСТА = ("grid", "labels", "sketch", "summary")

#: Правка схемы блока по ключам и то, куда ложатся добавленные: поле — в
#: `fields`, колонка — в `columns`.
СПИСКИ_СХЕМЫ = {"fields": "field", "columns": "column"}
ДОБАВКИ_СХЕМЫ = {"add_fields": "fields", "add_columns": "columns"}


def собрать(шаблон: dict, правки: dict | None) -> dict:
	"""Итоговая схема: шаблон с правками курса — `{title, layout, blocks, canvas}`.

	Шаблон не меняется. Блоки собранного — в той форме, в какой их принимает
	`set_course_artifact`: проверять их и писать дальше — тем же путём.
	"""
	правки = {} if правки is None else правки
	if not isinstance(правки, dict):
		raise Отказ(НЕВЕРНЫЕ_ПРАВКИ, "Правки курса — объект")
	_только_известные(правки, СВОЙСТВА_ПРАВОК)
	без_уроков(шаблон.get("blocks") or [])

	блоки = _править_блоки(copy.deepcopy(шаблон.get("blocks") or []), правки.get("blocks"))
	блоки = _добавить(блоки, правки.get("add_blocks"), _ключ_блока, "key", свойства=СВОЙСТВА_БЛОКА)

	холст = copy.deepcopy(шаблон.get("canvas"))
	if "canvas" in правки:
		холст = _править_холст(холст, правки["canvas"])

	return {
		"title": правки.get("title") or шаблон.get("title"),
		"layout": правки.get("layout") or шаблон.get("layout"),
		"blocks": блоки,
		"canvas": холст or None,
	}


def без_уроков(блоки: list) -> None:
	"""Урок в блоке шаблона — отказ: урок принадлежит курсу, а не шаблону.

	`Why:` шаблон общий для курсов, и урок одного курса в нём оказался бы
	чужим уроком у каждого следующего.
	"""
	for блок in блоки:
		if isinstance(блок, dict) and блок.get("lesson"):
			raise Отказ(
				НЕВЕРНАЯ_СХЕМА,
				"Урок блока задаётся в правках курса, а не в шаблоне",
				key=блок.get("key"),
			)


def без_уроков_в_правках(правки: dict) -> None:
	"""Урок в правках наследника шаблона — отказ: правки наследника — тоже шаблон.

	Урок блока задаётся правками курса и только ими. `Why:` наследник общий
	для курсов, как и родитель, и урок одного курса в нём оказался бы у
	каждого курса, собранного из наследника.
	"""
	# Форму правок проверяет `собрать`; здесь — только уроки в ней.
	if not isinstance(правки, dict):
		return
	блоки = правки.get("blocks")
	for ключ, правка in блоки.items() if isinstance(блоки, dict) else ():
		if isinstance(правка, dict) and "lesson" in правка:
			raise Отказ(НЕВЕРНЫЕ_ПРАВКИ, "Урок блока задаётся в правках курса, а не шаблона", key=ключ)
	добавки = правки.get("add_blocks")
	for добавка in добавки if isinstance(добавки, list) else ():
		if isinstance(добавка, dict) and "lesson" in добавка:
			raise Отказ(
				НЕВЕРНЫЕ_ПРАВКИ, "Урок блока задаётся в правках курса, а не шаблона", key=добавка.get("key")
			)


def _ключ_блока(значение) -> str:
	return str(значение or "").strip().lower()


def _ключ_элемента(значение) -> str:
	return str(значение or "").strip()


def _только_известные(правка: dict, известные: tuple[str, ...], **где) -> None:
	for имя in правка:
		if имя not in известные:
			raise Отказ(
				НЕВЕРНЫЕ_ПРАВКИ,
				"Правка называет то, чего правки не знают: " + ", ".join(известные),
				name=имя,
				**где,
			)


def _слить(база, правка):
	"""Объект сливается с объектом, `null` удаляет, прочее заменяет целиком."""
	if not isinstance(правка, dict):
		return copy.deepcopy(правка)
	итог = copy.deepcopy(база) if isinstance(база, dict) else {}
	for имя, значение in правка.items():
		if значение is None:
			итог.pop(имя, None)
		else:
			итог[имя] = _слить(итог.get(имя), значение)
	return итог


def _править_блоки(блоки: list[dict], правка) -> list[dict]:
	if правка is None:
		return блоки
	if not isinstance(правка, dict):
		raise Отказ(НЕВЕРНЫЕ_ПРАВКИ, "blocks в правках — объект по ключам блоков")
	по_ключам = {_ключ_блока(б.get("key")): б for б in блоки}
	убрать = set()
	for сырой, что in правка.items():
		ключ = _ключ_блока(сырой)
		if ключ not in по_ключам:
			raise Отказ(НЕВЕРНЫЕ_ПРАВКИ, "В шаблоне нет такого блока", key=сырой)
		if что is None:
			убрать.add(ключ)
			continue
		if not isinstance(что, dict):
			raise Отказ(НЕВЕРНЫЕ_ПРАВКИ, "Правка блока — объект или null", key=ключ)
		_только_известные(что, СВОЙСТВА_БЛОКА, key=ключ)
		блок = по_ключам[ключ]
		for имя, значение in что.items():
			if имя == "spec":
				блок["spec"] = _править_схему(блок.get("spec"), значение, ключ)
			elif значение is None:
				блок.pop(имя, None)
			else:
				блок[имя] = _слить(блок.get(имя), значение)
	return [б for б in блоки if _ключ_блока(б.get("key")) not in убрать]


def _править_схему(схема, правка, ключ: str) -> dict | None:
	"""Схема блока с правкой: поля и колонки — по ключам, прочее — слиянием."""
	if правка is None:
		return None
	if not isinstance(правка, dict):
		raise Отказ(НЕВЕРНЫЕ_ПРАВКИ, "Правка схемы блока — объект", key=ключ)
	_только_известные(правка, СВОЙСТВА_СХЕМЫ, key=ключ)
	итог = copy.deepcopy(схема) if isinstance(схема, dict) else {}
	for имя, значение in правка.items():
		if имя in ДОБАВКИ_СХЕМЫ:
			continue
		if значение is None:
			итог.pop(имя, None)
		elif имя in СПИСКИ_СХЕМЫ:
			итог[имя] = _править_элементы(итог.get(имя) or [], значение, ключ, СПИСКИ_СХЕМЫ[имя])
		else:
			итог[имя] = _слить(итог.get(имя), значение)
	# Добавки — после правок: новое поле встаёт после поля, которое правка
	# оставила, а не после убранного ею же.
	for имя, куда in ДОБАВКИ_СХЕМЫ.items():
		if правка.get(имя) is not None:
			итог[куда] = _добавить(
				list(итог.get(куда) or []), правка[имя], _ключ_элемента, СПИСКИ_СХЕМЫ[куда], key=ключ
			)
	return итог


def _править_элементы(элементы: list, правка, ключ: str, что: str) -> list:
	"""Поля или колонки блока с правкой по их ключам."""
	if not isinstance(правка, dict):
		raise Отказ(
			НЕВЕРНЫЕ_ПРАВКИ,
			"Поля и колонки в правках — объект по их ключам; новые — в add_fields и add_columns",
			key=ключ,
		)
	по_ключам = {_ключ_элемента(э.get("key")): э for э in элементы if isinstance(э, dict)}
	правленые: dict[str, dict | None] = {}
	for сырой, значение in правка.items():
		имя = _ключ_элемента(сырой)
		if имя not in по_ключам:
			raise Отказ(НЕВЕРНЫЕ_ПРАВКИ, "В блоке шаблона нет такого ключа", key=ключ, **{что: сырой})
		if значение is not None and not isinstance(значение, dict):
			raise Отказ(НЕВЕРНЫЕ_ПРАВКИ, "Правка — объект или null", key=ключ, **{что: имя})
		if значение and _ключ_элемента(значение.get("key") or имя) != имя:
			raise Отказ(НЕВЕРНЫЕ_ПРАВКИ, "Ключ правкой не меняется", key=ключ, **{что: имя})
		правленые[имя] = None if значение is None else _слить(по_ключам[имя], значение)
	итог = []
	for элемент in элементы:
		имя = _ключ_элемента(элемент.get("key")) if isinstance(элемент, dict) else None
		if имя not in правленые:
			итог.append(copy.deepcopy(элемент))
		elif правленые[имя] is not None:
			итог.append(правленые[имя])
	return итог


def _добавить(
	элементы: list, добавки, ключ_из, что: str, свойства: tuple[str, ...] | None = None, **где
) -> list:
	"""Новые блоки, поля или колонки — после названного `after`, иначе в конец.

	Несколько добавок после одного места встают в том порядке, в каком
	перечислены. `что` — как зовётся ключ добавки в отказе; `свойства` — что
	добавка может нести, кроме ключа; `None` — что угодно: свойства поля и
	колонки проверяет схема.
	"""
	if добавки is None:
		return элементы
	if not isinstance(добавки, list):
		raise Отказ(НЕВЕРНЫЕ_ПРАВКИ, "Добавки — список", **где)
	последняя_после: dict[str, str] = {}
	for добавка in добавки:
		if not isinstance(добавка, dict):
			raise Отказ(НЕВЕРНЫЕ_ПРАВКИ, "Добавка — объект с ключом", **где)
		новое = copy.deepcopy(добавка)
		после = новое.pop("after", None)
		имя = ключ_из(новое.get("key"))
		if not имя:
			raise Отказ(НЕВЕРНЫЕ_ПРАВКИ, "У добавки нужен ключ", **где)
		if свойства is not None:
			_только_известные({к: в for к, в in новое.items() if к != "key"}, свойства, key=имя)
		новое["key"] = имя
		ключи = [ключ_из(э.get("key")) for э in элементы]
		if имя in ключи:
			raise Отказ(
				НЕВЕРНЫЕ_ПРАВКИ, "Такой ключ уже есть — правьте его, а не добавляйте", **где, **{что: имя}
			)
		if после is None:
			элементы.append(новое)
			continue
		место = ключ_из(после)
		if место not in ключи:
			raise Отказ(
				НЕВЕРНЫЕ_ПРАВКИ, "after называет ключ, которого нет", **где, **{что: имя}, after=после
			)
		опора = последняя_после.get(место, место)
		элементы.insert(ключи.index(опора) + 1, новое)
		последняя_после[место] = имя
	return элементы


def _править_холст(холст, правка) -> dict | None:
	"""Холст с правкой: подписи и сводка сливаются, сетка заменяется, `null` убирает холст."""
	if правка is None:
		return None
	if not isinstance(правка, dict):
		raise Отказ(НЕВЕРНЫЕ_ПРАВКИ, "Правка холста — объект или null", key="canvas")
	_только_известные(правка, СВОЙСТВА_ХОЛСТА, key="canvas")
	return _слить(холст, правка)
