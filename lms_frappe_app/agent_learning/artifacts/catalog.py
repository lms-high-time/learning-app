"""Проверка каталога документов: каждая действующая схема курса из базы —
через проверку движка (learning-services#377).

Схему пишет публикация релиза и проверяет при записи, но движок меняется и
после неё: новое правило проверки, другой разбор формулы. Схему, записанную
старым движком, новый может не принять — и увидел бы это ученик, открыв
документ. Здесь это видно сразу: блоки и холст действующей схемы проходят ту
же проверку, что и запись.

Проверку зовут команда `bench --site <сайт> check-artifact-catalog` и
`after_migrate`: упавший `bench migrate` останавливает выкатку до
переключения релиза. `Why:` снимок каталога в фикстурах тестов был бы проще,
но схемы — закрытое содержание курсов, а его в открытом приложении не держат.
"""

from __future__ import annotations

import json

import frappe

from lms_frappe_app.agent_learning.artifacts.canvas import проверить_холст
from lms_frappe_app.agent_learning.artifacts.course import _блоки_схем, блок_наружу, строки_схемы
from lms_frappe_app.agent_learning.errors import Отказ

ДОКУМЕНТ = "Agent Course Artifact"
#: Код беды, когда проверка упала не отказом движка, — отказ беда несёт как есть.
СБОЙ = "catalog_error"


def проверить_каталог() -> list[dict]:
	"""Беды действующих схем курсов.

	Беда — `{doctype, name, course, artifact, version, code, message,
	details}`. Пустой список — каталог в порядке.
	"""
	действующие = frappe.get_all(
		ДОКУМЕНТ,
		filters={"is_active": 1},
		fields=["name", "course", "slug", "version", "canvas"],
		order_by="course asc, slug asc",
	)
	if not действующие:
		return []
	блоки = _блоки_схем([д.name for д in действующие])
	беды = []
	for запись in действующие:
		беды += _проверить(запись, блоки.get(запись.name, []))
	return беды


def отчёт(вывести) -> int:
	"""Беды каталога — строками через `вывести`; код выхода команды: 1, если беды есть."""
	беды = проверить_каталог()
	for беда in беды:
		вывести(описать(беда))
	if беды:
		вывести(f"Каталог документов: бед — {len(беды)}")
		return 1
	вывести("Каталог документов в порядке")
	return 0


def после_миграции() -> None:
	"""Сломанный каталог валит `bench migrate`, а с ним и выкатку.

	`Why:` сторож выкатки уже не переключает релиз, если `migrate` упал, —
	проверка каталога встаёт туда же без правки сторожа. На сайте без
	документов бед нет: свежая установка и тестовый сайт мигрируют как прежде.
	"""
	беды = проверить_каталог()
	if беды:
		raise frappe.ValidationError(
			"Каталог документов не проходит проверку движка:\n" + "\n".join(описать(б) for б in беды)
		)
	print("Каталог документов в порядке")


def описать(беда: dict) -> str:
	где = f"документ {беда['artifact']} курса {беда['course']} v{беда['version']}"
	подробности = json.dumps(беда["details"], ensure_ascii=False, default=str) if беда["details"] else ""
	return f"{где} ({беда['name']}): {беда['code']} — {беда['message']} {подробности}".rstrip()


def _проверить(запись, строки: list) -> list[dict]:
	"""Одна схема: блоки и холст — через проверку записи; отказ движка или сбой —
	бедой, а не исключением.

	`Why:` сбой на одном документе не должен прятать беды остальных: автору
	нужен весь список, а не первая строка трассировки.
	"""
	try:
		блоки = строки_схемы([блок_наружу(с) for с in строки])
		проверить_холст(запись.canvas, блоки)
		return []
	except Отказ as отказ:
		return [_беда(запись, отказ.код, отказ.сообщение, **отказ.подробности)]
	except Exception as сбой:
		return [_беда(запись, СБОЙ, f"{type(сбой).__name__}: {сбой}")]


def _беда(запись, код: str, сообщение: str, **подробности) -> dict:
	return {
		"doctype": ДОКУМЕНТ,
		"name": запись.name,
		"course": запись.course,
		"artifact": запись.slug,
		"version": запись.version,
		"code": код,
		"message": сообщение,
		"details": подробности,
	}
