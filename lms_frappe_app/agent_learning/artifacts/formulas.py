"""Формулы колонок и полей документа.

Маленький язык без eval: числа, имена колонок и полей, + - * /, сравнения,
and, or, not, скобки. Пустое значение делает пустым и результат: ранг без
вероятности — не ноль, а «ещё не оценено».
"""

from __future__ import annotations

import re

from lms_frappe_app.agent_learning.artifacts.codes import НЕВЕРНАЯ_СХЕМА
from lms_frappe_app.agent_learning.errors import Отказ

_ЛЕКСЕМЫ = re.compile(r"\s*(?:(\d+(?:\.\d+)?)|([a-z_][a-z0-9_]*)|(>=|<=|==|!=|[-+*/()<>]))")


def _лексемы(текст: str) -> list[tuple[str, str]]:
	итог, позиция = [], 0
	текст = текст.strip()
	while позиция < len(текст):
		совпало = _ЛЕКСЕМЫ.match(текст, позиция)
		if not совпало or совпало.end() == позиция:
			raise Отказ(НЕВЕРНАЯ_СХЕМА, "Формула не разбирается", formula=текст)
		число, имя, знак = совпало.groups()
		if число:
			итог.append(("num", число))
		elif имя:
			итог.append(("op", имя) if имя in ("and", "or", "not") else ("name", имя))
		else:
			итог.append(("op", знак))
		позиция = совпало.end()
	return итог


def разобрать(текст: str):
	"""Формула — в дерево; пустая или неверная — отказ."""
	лексемы = _лексемы(текст or "")
	if not лексемы:
		raise Отказ(НЕВЕРНАЯ_СХЕМА, "Формула пустая")
	позиция = 0

	def смотреть():
		return лексемы[позиция] if позиция < len(лексемы) else (None, None)

	def взять():
		nonlocal позиция
		позиция += 1
		return лексемы[позиция - 1]

	def уровень(операции, следующий):
		def разбор():
			левое = следующий()
			while смотреть()[0] == "op" and смотреть()[1] in операции:
				знак = взять()[1]
				левое = ("bin", знак, левое, следующий())
			return левое

		return разбор

	def атом():
		вид, значение = смотреть()
		if вид == "num":
			взять()
			return ("num", float(значение))
		if вид == "name":
			взять()
			return ("name", значение)
		if (вид, значение) == ("op", "("):
			взять()
			узел = выражение()
			if смотреть() != ("op", ")"):
				raise Отказ(НЕВЕРНАЯ_СХЕМА, "В формуле не закрыта скобка", formula=текст)
			взять()
			return узел
		if (вид, значение) in (("op", "-"), ("op", "not")):
			взять()
			return ("un", значение, атом())
		raise Отказ(НЕВЕРНАЯ_СХЕМА, "Формула не разбирается", formula=текст)

	умножение = уровень(("*", "/"), атом)
	сложение = уровень(("+", "-"), умножение)
	сравнение = уровень((">=", "<=", ">", "<", "==", "!="), сложение)
	и = уровень(("and",), сравнение)
	выражение = уровень(("or",), и)

	дерево = выражение()
	if позиция != len(лексемы):
		raise Отказ(НЕВЕРНАЯ_СХЕМА, "Формула не разбирается", formula=текст)
	return дерево


def имена(дерево) -> set[str]:
	if дерево[0] == "name":
		return {дерево[1]}
	if дерево[0] == "un":
		return имена(дерево[2])
	if дерево[0] == "bin":
		return имена(дерево[2]) | имена(дерево[3])
	return set()


def вычислить(дерево, значения: dict):
	"""Значение формулы; пустой операнд — пустой результат, деление на ноль тоже."""
	вид = дерево[0]
	if вид == "num":
		return дерево[1]
	if вид == "name":
		значение = значения.get(дерево[1])
		if значение in (None, ""):
			return None
		if isinstance(значение, bool):
			return значение
		try:
			return float(значение)
		except (TypeError, ValueError):
			return None
	if вид == "un":
		операнд = вычислить(дерево[2], значения)
		if операнд is None:
			return None
		return (not операнд) if дерево[1] == "not" else -операнд
	знак, левое, правое = дерево[1], вычислить(дерево[2], значения), вычислить(дерево[3], значения)
	if знак == "and":
		return None if левое is None or правое is None else bool(левое) and bool(правое)
	if знак == "or":
		if левое is None and правое is None:
			return None
		return bool(левое) or bool(правое)
	if левое is None or правое is None:
		return None
	if знак == "/" and правое == 0:
		return None
	return {
		"+": lambda: левое + правое,
		"-": lambda: левое - правое,
		"*": lambda: левое * правое,
		"/": lambda: левое / правое,
		">=": lambda: левое >= правое,
		"<=": lambda: левое <= правое,
		">": lambda: левое > правое,
		"<": lambda: левое < правое,
		"==": lambda: левое == правое,
		"!=": lambda: левое != правое,
	}[знак]()


def _число(значение):
	"""12.0 → 12: целый ранг не должен выглядеть дробью."""
	if isinstance(значение, float) and значение.is_integer():
		return int(значение)
	return значение
