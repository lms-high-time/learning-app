КВИЗА_НЕТ = "quiz_not_configured"
НЕЧЕГО_ПРОВЕРЯТЬ = "quiz_not_checkable"
ПОПЫТКИ_ИСЧЕРПАНЫ = "quiz_attempts_exhausted"
СЛИШКОМ_РАНО = "retry_too_soon"
ПОПЫТКА_ЗАВЕРШЕНА = "attempt_finished"
ЧУЖОЙ_ВОПРОС = "question_mismatch"
НУЖНЫ_СЛОВА = "student_words_required"

#: Сколько слов ученика ложится в журнал. Обрезка, а не отказ: слова только
#: для разбора и на вердикт не влияют, а отказ из-за длины стоил бы ученику
#: ответа. Предел — про читателя журнала: две тысячи знаков хватает на
#: развёрнутый ответ и не хватает на пересказ всего разговора.
ДЛИНА_СЛОВ = 2000


# --- начало попытки ---


def начать_попытку(session: str) -> dict:
	"""Создаёт попытку и возвращает первый вопрос."""
	занятие = frappe.get_doc("Agent Learning Session", session)
	квиз = _квиз_урока(занятие.lesson)
	if not квиз:
		raise Отказ(КВИЗА_НЕТ, "У этого урока нет квиза")

	вопросы = _вопросы_квиза(квиз)
	if not вопросы:
		# Frappe Learning не даёт смешивать Open Ended с другими типами:
		# «make sure each question in the quiz is of open ended type». Значит
		# квиз либо весь открытый — и проверить его сервер не может, — либо
		# проверяемый целиком. Промежуточного случая не существует.
		raise Отказ(
			НЕЧЕГО_ПРОВЕРЯТЬ,
			"Квиз состоит из открытых вопросов — их разбирают на занятии, а не засчитывают",
		)

	# Проверка доступа повторяется здесь намеренно: занятие может быть создано
	# раньше, а доступ отозван позже — приостановкой организации или снятием
	# зачисления. Без неё квиз сдаётся по курсу, к которому доступа уже нет.
	можно, причина = доступен_курс(занятие.student, занятие.course)
	if not можно:
		raise Отказ(причина, "Этот курс сейчас недоступен", course=занятие.course)

	политика = политика_квиза_для_курса(занятие.student, занятие.course)

	# Открытая попытка возвращается, а не заводится новая: иначе ученик
	# бросает попытку после каждого вердикта и перебирает варианты, а лимит
	# считает только завершённые.
	открытая = _открытая_попытка(занятие.name)
	if открытая:
		# По занятию, а не по квизу: один квиз может быть привязан к двум
		# урокам, и попытка чужого занятия закрыла бы не тот урок.
		занятие.записать_событие(СОБЫТИЕ_КВИЗ_НАЧАТ, "продолжение попытки")
		попытка = frappe._dict(
			name=открытая,
			session=занятие.name,
			student=занятие.student,
			course=занятие.course,
			lesson=занятие.lesson,
		)
		return {"attempt": открытая, "question": _выдать_вопрос(попытка, вопросы)}

	отбор = попытки_квиза(занятие.student, квиз)
	проверить_право_на_попытку(отбор, политика)

	попытка = frappe.get_doc(
		{
			"doctype": "Agent Quiz Attempt",
			"session": занятие.name,
			"student": занятие.student,
			"quiz": квиз,
			"lesson": занятие.lesson,
			"course": занятие.course,
			"attempt_number": прошлых_попыток(отбор) + 1,
			"status": ПОПЫТКА_ИДЁТ,
			"started_at": now_datetime(),
		}
	).insert(ignore_permissions=True)

	if занятие.status == ЗАНЯТИЕ_ИДЁТ:
		занятие.status = ЗАНЯТИЕ_ЖДЁТ_КВИЗ
		занятие.save(ignore_permissions=True)
	занятие.записать_событие(СОБЫТИЕ_КВИЗ_НАЧАТ, f"попытка {попытка.attempt_number}")

	return {"attempt": попытка.name, "question": _выдать_вопрос(попытка, вопросы)}


def попытки_квиза(student: str, квиз: str) -> dict:
	"""Отбор попыток квиза Frappe Learning, которые идут в лимит и паузу: ученик и квиз."""
	return {"student": student, "quiz": квиз}


def попытки_урока(student: str, course: str, lesson_key: str) -> dict:
	"""Отбор попыток урока из релиза, которые идут в лимит и паузу: ученик, курс, ключ урока.

	`Why:` квиза Frappe Learning у такого урока нет, а ключ урока стабилен
	между релизами: новый релиз не обнуляет ни лимит, ни паузу.
	"""
	return {"student": student, "course": course, "lesson_key": lesson_key}


def проверить_право_на_попытку(отбор: dict, политика: dict) -> None:
	"""Лимит попыток и пауза перед повтором — из политики платформы.

	`отбор` — попытки, которые идут в счёт: `попытки_квиза` или `попытки_урока`.
	"""
	прошлых = прошлых_попыток(отбор)
	лимит = политика["max_attempts"]
	if лимит and прошлых >= лимит:  # ноль означает «без лимита»
		raise Отказ(
			ПОПЫТКИ_ИСЧЕРПАНЫ, f"Использованы все попытки ({лимит})", attempts_used=прошлых
		)

	последняя = frappe.get_all(
		"Agent Quiz Attempt",
		filters={**отбор, "status": ("!=", ПОПЫТКА_ИДЁТ)},
		fields=["finished_at"],
		order_by="finished_at desc",
		limit=1,
	)
	if not последняя or not последняя[0].finished_at:
		return

	можно_с = _можно_с(последняя[0].finished_at, политика)
	if now_datetime() < можно_с:
		raise Отказ(
			СЛИШКОМ_РАНО,
			"Повторить попытку можно позже",
			retry_after=_с_поясом(можно_с),
		)


def _можно_с(закончена: datetime, политика: dict) -> datetime:
	"""Когда можно начать следующую попытку после завершённой — наивное время сайта.

	Наивное, потому что сравнивается с `now_datetime()`, а он тоже без пояса.
	Наружу момент уходит только через `_с_поясом`.
	"""
	return add_to_date(закончена, minutes=политика["retry_delay_minutes"])


def _с_поясом(момент: datetime) -> str:
	"""ISO 8601 со смещением часового пояса сайта.

	`Why:` Frappe хранит и отдаёт время наивным, в поясе сайта. Строка без
	смещения читается как UTC, и агент называл ученику время пересдачи со
	сдвигом на пояс сервера.
	"""
	return момент.replace(tzinfo=ZoneInfo(get_system_timezone())).isoformat()


def осталось_попыток(отбор: dict, политика: dict) -> int | None:
	"""Сколько попыток ещё можно начать; `None` — лимита нет.

	`отбор` — как у `проверить_право_на_попытку`.
	"""
	лимит = политика["max_attempts"]
	if not лимит:  # ноль означает «без лимита»
		return None
	return max(0, лимит - прошлых_попыток(отбор))


def прошлых_попыток(отбор: dict) -> int:
	"""Сколько попыток ученик уже израсходовал.

	Считаются **все**, включая открытые. `Why:` иначе брошенная попытка не
	стоит ничего: ученик отвечает наугад, видит вердикт, бросает и начинает
	заново — перебором до верного варианта. Лимит попыток и пауза перед
	повтором при этом остаются на бумаге.
	"""
	return frappe.db.count("Agent Quiz Attempt", отбор)


def _открытая_попытка(session: str) -> str | None:
	"""Незавершённая попытка этого занятия, если она есть."""
	открытые = frappe.get_all(
		"Agent Quiz Attempt",
		filters={"session": session, "status": ПОПЫТКА_ИДЁТ},
		pluck="name",
		order_by="creation desc",
		limit=1,
	)
	return открытые[0] if открытые else None


def требуется_квиз(lesson: str, student: str, course: str) -> bool:
	"""Нужно ли сдавать квиз, чтобы урок считался пройденным.

	`Why:` без этого правила закрытие урока стало бы способом обойти
	проверку — агент вызвал бы его вместо квиза, и серверный зачёт, на
	котором держится вся схема, потерял бы смысл.

	Урок из релиза — тот, что есть в действующем релизе курса: квиз у него
	есть, когда у урока там есть вопросы.
	"""
	квиз = _квиз_урока(lesson)
	есть = bool(квиз and _вопросы_квиза(квиз)) or _квиз_в_релизе(lesson, course)
	return есть and bool(политика_квиза_для_курса(student, course)["quiz_required"])


def _квиз_в_релизе(lesson: str, course: str) -> bool:
	"""У урока есть вопросы в действующем релизе курса."""
	релиз = прохождения.действующий(course)
	ключ = index.ключ_урока(релиз, lesson) if релиз else None
	return bool(ключ and index.вопросы_урока(релиз, ключ))


def _квиз_урока(lesson: str) -> str | None:
	"""Квиз, привязанный к уроку.

	Frappe Learning допускает две привязки: поле `quiz_id` у урока и поле
	`lesson` у квиза. Смотрим обе — иначе квиз, заведённый вторым способом,
	для нас не существует.
	"""
	квиз = frappe.db.get_value("Course Lesson", lesson, "quiz_id")
	if квиз and frappe.db.exists("LMS Quiz", квиз):
		return квиз
	return frappe.db.get_value("LMS Quiz", {"lesson": lesson}, "name")


# --- вопросы ---


def вопросы_урока(lesson: str) -> set[str]:
	"""Все вопросы квиза урока, включая непроверяемые сервером.

	`Why:` «вопрос этого урока» и «вопрос, который сервер берётся проверить» —
	разные множества, и путать их нельзя. Открытый вопрос или вопрос, где ни
	один вариант не отмечен верным, из проверки выпадает, но уроку принадлежит
	— и именно о таком агент сообщает репортом.
	"""
	квиз = _квиз_урока(lesson)
	if not квиз:
		return set()
	return set(
		frappe.get_all("LMS Quiz Question", filters={"parent": квиз}, pluck="question")
	)


def _вопросы_квиза(квиз: str) -> list[dict]:
	"""Вопросы квиза, которые сервер может проверить сам.

	Open Ended отсеиваются: их проверка требует человека, а зачёт, который
	ставит агент, не зачёт вовсе. Такие вопросы остаются материалом для
	устного разбора на занятии.
	"""
	строки = frappe.get_all(
		"LMS Quiz Question",
		filters={"parent": квиз},
		fields=["question", "marks"],
		order_by="idx asc",
	)
	if not строки:
		return []

	# Один запрос на все типы вместо запроса на каждый вопрос: функция
	# переисполняется на каждый ответ, и квиз из тридцати вопросов давал
	# около шестидесяти лишних обращений на одну отправку.
	типы = {
		запись.name: запись.type
		for запись in frappe.get_all(
			"LMS Question",
			filters={"name": ("in", [строка.question for строка in строки])},
			fields=["name", "type"],
		)
	}
	пригодные = [
		строка for строка in строки if типы.get(строка.question) in ПРОВЕРЯЕМЫЕ_ТИПЫ
	]
	# Вопрос с вариантами, где ни один не отмечен верным, непроверяем так же,
	# как открытый. Why: пробовалось отвечать на него отказом — попытка
	# оставалась открытой навсегда, а каждый следующий ответ падал: ученик
	# запирался в квизе без выхода. Кривой контент должен мешать одному
	# вопросу, а не всему курсу.
	с_эталоном = _вопросы_с_эталоном([строка.question for строка in пригодные], типы)
	return [
		{"question": строка.question, "marks": строка.marks or 1, "type": типы[строка.question]}
		for строка in пригодные
		if строка.question in с_эталоном
	]


def _вопросы_с_эталоном(вопросы: list[str], типы: dict[str, str]) -> set[str]:
	"""Вопросы, у которых есть с чем сверять ответ."""
	if not вопросы:
		return set()
	поля = ["name", *поля_вопроса("is_correct", "possibility")]
	годные = set()
	for запись in frappe.get_all("LMS Question", filters={"name": ("in", вопросы)}, fields=поля):
		эталон = "is_correct" if типы.get(запись.name) == ВЫБОР else "possibility"
		if заполненные(запись, эталон):
			годные.add(запись.name)
	return годные


def следующий_вопрос(attempt: str, вопросы: list[dict] | None = None) -> dict | None:
	"""Первый неотвеченный вопрос попытки — без единого поля эталона.

	Состав квиза принимается готовым: вызывающий его уже собрал, а сборка
	стоит трёх запросов плюс чтение попытки ради одного поля `quiz`. На приёме
	ответа это повторялось дважды за вызов.
	"""
	if вопросы is None:
		вопросы = _вопросы_квиза(frappe.db.get_value("Agent Quiz Attempt", attempt, "quiz"))
	отвеченные = set(
		frappe.get_all("Agent Quiz Answer", filters={"attempt": attempt}, pluck="question")
	)
	for номер, вопрос in enumerate(вопросы, start=1):
		if вопрос["question"] not in отвеченные:
			return _вопрос_для_агента(вопрос, номер, len(вопросы))
	return None


def _выдать_вопрос(попытка, вопросы: list[dict]) -> dict | None:
	"""Следующий вопрос попытки — с записью «выдан» в журнал проверки.

	`Why:` журнал нужен для разбора, и выданный вопрос без ответа — тоже
	факт: по нему видно, где ученик остановился и сколько раз возвращался.
	"""
	вопрос = следующий_вопрос(попытка.name, вопросы)
	if вопрос:
		_в_журнал(ПРОВЕРКА_ВОПРОС_ВЫДАН, попытка, вопрос["id"])
	return вопрос


def _в_журнал(вид: str, попытка, вопрос: str, **ответ) -> None:
	"""Пишет событие журнала проверки.

	`попытка` — запись попытки или словарь с теми же полями: `name`,
	`session`, `student`, `course`, `lesson`. Пишется в транзакции вызова:
	откат попытки откатывает и журнал, и расхождения между ними не бывает.
	"""
	frappe.get_doc(
		{
			"doctype": "Agent Quiz Event",
			"kind": вид,
			"attempt": попытка.name,
			"session": попытка.session,
			"student": попытка.student,
			"course": попытка.course,
			"lesson": попытка.lesson,
			"question": вопрос,
			**ответ,
		}
	).insert(ignore_permissions=True)


def _вопрос_для_агента(вопрос: dict, номер: int, всего: int) -> dict:
	"""Вопрос в том виде, в каком его может увидеть агент.

	Здесь нет и не может быть `is_correct_*`, `explanation_*` и
	`possibility_*`: любой из них — готовый ответ.
	"""
	запись = frappe.get_doc("LMS Question", вопрос["question"])
	отдать = {
		"id": запись.name,
		"text": _очистить(запись.question),
		"kind": "choice" if запись.type == ВЫБОР else "input",
		"index": номер,
		"total": всего,
	}
	if запись.type == ВЫБОР:
		отдать["multiple"] = bool(запись.multiple)
		отдать["options"] = [
			{"id": str(номер), "text": _очистить(текст)}
			for номер, текст in заполненные(запись, "option")
		]
	return отдать


# --- ответ и вердикт ---


def принять_ответ(attempt: str, question: str, answer: str, student_words: str) -> dict:
	"""Сверяет ответ, возвращает вердикт и следующий вопрос.

	`student_words` — что ученик написал в ответ, дословно. Не проверяется и
	на вердикт не влияет: судит сервер по `answer`. `Why:` на квиз отвечает
	агент, и вердикт не говорит, отвечал ли сам ученик; слова кладутся в
	журнал проверки рядом с ответом — для разбора курса.
	"""
	слова = str(student_words or "").strip()
	if not слова:
		raise Отказ(НУЖНЫ_СЛОВА, "Передайте, что ученик написал в ответ, дословно")

	попытка = frappe.get_doc("Agent Quiz Attempt", attempt)
	if попытка.status != ПОПЫТКА_ИДЁТ:
		raise Отказ(ПОПЫТКА_ЗАВЕРШЕНА, "Эта попытка уже завершена")

	состав = _вопросы_квиза(попытка.quiz)
	вопросы = {в["question"]: в for в in состав}
	if question not in вопросы:
		raise Отказ(ЧУЖОЙ_ВОПРОС, "Вопрос не из этой попытки")
	if frappe.db.exists("Agent Quiz Answer", {"attempt": attempt, "question": question}):
		raise Отказ(ЧУЖОЙ_ВОПРОС, "На этот вопрос уже отвечено")

	запись = frappe.get_doc("LMS Question", question)
	верно, пояснение = _сверить(запись, answer)
	баллы = вопросы[question]["marks"]
	присланный = str(answer)[:500]

	frappe.get_doc(
		{
			"doctype": "Agent Quiz Answer",
			"attempt": attempt,
			"question": question,
			"answer": присланный,
			"is_correct": int(верно),
			"marks": баллы if верно else 0,
			"marks_out_of": баллы,
			"answered_at": now_datetime(),
		}
	).insert(ignore_permissions=True)

	вердикт = {"correct": верно}
	if пояснение:
		# При верном ответе — пояснение верных вариантов, при неверном —
		# только выбранных неверных. Пояснение верного варианта ошибившемуся
		# не отдаётся: это готовый ответ перед следующей попыткой, и лимит
		# попыток терял бы смысл. Пояснение неверного варианта ответа не
		# называет.
		вердикт["explanation" if верно else "why_wrong"] = пояснение

	_в_журнал(
		ПРОВЕРКА_ОТВЕТ_ПРИНЯТ,
		попытка,
		question,
		answer=присланный,
		student_words=слова[:ДЛИНА_СЛОВ],
		is_correct=int(верно),
	)

	следующий = _выдать_вопрос(попытка, состав)
	ответ = {
		"verdict": вердикт,
		"next_question": следующий,
		"attempt_finished": следующий is None,
	}
	if следующий is None:
		ответ["result"] = _завершить(попытка)
	return ответ


def _сверить(запись, answer: str) -> tuple[bool, str | None]:
	"""Сверка с эталоном. Возвращает вердикт и пояснение.

	Пояснение при верном ответе — к верным вариантам, при неверном — к
	выбранным неверным. Пояснение верного варианта при неверном ответе не
	возвращается никогда: это эталон.

	Тривиальна намеренно: ценность не в сверке, а в том, какие вопросы
	задаются и как они порождаются, — а это закрытая часть. Взамен получаем
	гарантию, что эталоны не утекают через агента.
	"""
	if запись.type == ВЫБОР:
		выбранные = _разобрать_выбор(answer, запись)
		верные = {str(номер) for номер, _ in заполненные(запись, "is_correct")}
		# Строгое равенство, а не вхождение: иначе «выбрать все варианты»
		# засчитывалось бы как верный ответ.
		верно = выбранные == верные
		пояснить = верные if верно else выбранные - верные
		пояснение = " ".join(
			_очистить(текст)
			for номер, текст in заполненные(запись, "explanation")
			if str(номер) in пояснить
		)
		return верно, пояснение or None

	эталоны = {_привести(эталон) for _, эталон in заполненные(запись, "possibility")}
	return _привести(answer) in эталоны, None


def _разобрать_выбор(answer, запись) -> set[str]:
	"""Номера выбранных вариантов из ответа агента.

	Принимаем «2», «1,3», список — и текст варианта: агенты форматируют
	по-разному, а модели передают текст вместо номера (lms-platform#148). Отказ
	из-за формата ученик воспринял бы как «ответил неверно».

	Номера важнее текста: у варианта может быть текст «3», а «1,3» — это
	номера. Ответ целиком сверяется с текстом раньше, чем режется по запятым:
	иначе вариант «Москва, Россия» не нашёлся бы.
	"""
	тексты = {_привести(текст): str(номер) for номер, текст in заполненные(запись, "option")}
	номера = set(тексты.values())
	if isinstance(answer, (list, tuple, set)):
		части = [str(часть).strip() for часть in answer]
	else:
		строка = str(answer or "")
		части = [часть.strip() for часть in строка.replace(";", ",").split(",")]
		целиком = _привести(строка)
		if not all(часть in номера for часть in части if часть) and целиком in тексты:
			return {тексты[целиком]}
	# Нераспознанная часть остаётся как есть и просто не совпадёт с верными:
	# неизвестный текст — неверный ответ, а не ошибка.
	return {
		часть if часть in номера else тексты.get(_привести(часть), часть)
		for часть in части
		if часть
	}


def _привести(значение) -> str:
	return " ".join(str(значение or "").lower().split())


# --- завершение ---


def _завершить(попытка) -> dict:
	"""Считает итог, пишет стандартные записи Frappe Learning, закрывает занятие."""
	ответы = frappe.get_all(
		"Agent Quiz Answer",
		filters={"attempt": попытка.name},
		fields=["question", "answer", "is_correct", "marks", "marks_out_of"],
	)
	всего = sum(о.marks_out_of or 0 for о in ответы)
	набрано = sum(о.marks or 0 for о in ответы)
	доля = (набрано / всего) if всего else 0.0

	политика = политика_квиза_для_курса(попытка.student, попытка.course)
	зачтено = доля >= политика["pass_threshold"]

	попытка.status = ПОПЫТКА_ЗАЧТЕНА if зачтено else ПОПЫТКА_НЕ_ЗАЧТЕНА
	попытка.score = round(доля, 3)
	попытка.passed = int(зачтено)
	попытка.finished_at = now_datetime()
	попытка.submission = _записать_итог_frappe(
		попытка, ответы, набрано, всего, доля, политика["pass_threshold"]
	)
	попытка.save(ignore_permissions=True)

	занятие = frappe.get_doc("Agent Learning Session", попытка.session)
	if зачтено:
		отметить_урок_пройденным(попытка)
		if занятие.status in ОТКРЫТЫЕ:
			занятие.status = ЗАНЯТИЕ_ЗАВЕРШЕНО
			занятие.save(ignore_permissions=True)
		# Занятие, закрытое по бездействию, переводить некуда: у брошенного
		# статуса выхода нет. Результат квиза от этого не страдает — иначе
		# ученик, вернувшийся к последнему вопросу через сутки, ронял бы
		# транзакцию и терял всю попытку.
	занятие.записать_событие(
		СОБЫТИЕ_ВЕРДИКТ, f"итог {попытка.score}, {'зачтено' if зачтено else 'не зачтено'}"
	)

	итог = {
		"score": попытка.score,
		"passed": зачтено,
		"pass_threshold": политика["pass_threshold"],
		"session_status": занятие.status,
	}
	if not зачтено:
		# Пауза и остаток попыток — сразу в итоге, по тем же правилам, что
		# проверит следующий `request_quiz`. Без них агент узнавал о паузе
		# только отказом `retry_too_soon`, уже предложив пересдачу.
		осталось = осталось_попыток(попытки_квиза(попытка.student, попытка.quiz), политика)
		итог["attempts_left"] = осталось
		итог["retry_after"] = (
			None if осталось == 0 else _с_поясом(_можно_с(попытка.finished_at, политика))
		)
	return итог


def _записать_итог_frappe(
	попытка, ответы, набрано: int, всего: int, доля: float, порог_доли: float
) -> str:
	"""Стандартный `LMS Quiz Submission` — чтобы результат был виден в браузере.

	Оба канала обязаны сходиться в одной записи: ученик начинает урок с
	агентом и видит результат в браузере, потому что запись физически одна.
	"""
	# Порог берётся из политики организации, а не из настроек квиза. Иначе в
	# нашей записи «зачтено», а в браузерной — ниже проходного балла, и два
	# канала, которые обязаны сходиться, показывают разное.
	порог = round(порог_доли * 100)
	# Тексты вопросов одним запросом, а не по одному на ответ.
	тексты = {
		запись.name: запись.question
		for запись in frappe.get_all(
			"LMS Question",
			filters={"name": ("in", [о.question for о in ответы])},
			fields=["name", "question"],
		)
	} if ответы else {}
	итог = frappe.get_doc(
		{
			"doctype": "LMS Quiz Submission",
			"quiz": попытка.quiz,
			"course": попытка.course,
			"member": попытка.student,
			"score": набрано,
			"score_out_of": всего,
			"percentage": round(доля * 100),
			"passing_percentage": порог,
			"result": [
				{
					"question_name": о.question,
					"question": тексты.get(о.question),
					"answer": о.answer,
					"marks": о.marks,
					"marks_out_of": о.marks_out_of,
					"is_correct": о.is_correct,
				}
				for о in ответы
			],
		}
	).insert(ignore_permissions=True)
	return итог.name


def отметить_урок_пройденным(запись, подтверждённые_цели=()) -> None:
	"""Пишет `LMS Course Progress` — тот же прогресс, что видит браузер, — и
	`passed` у прохождения урока из релиза.

	Принимает и попытку квиза, и занятие: у обеих есть ученик, урок и курс, а
	прогресс от способа закрытия урока не зависит. `подтверждённые_цели` —
	цели, которые сданная попытка из релиза подтвердила квизом
	(`runs.service.отметить_пройденным`).
	"""
	if ключ := _ключ_урока_в_релизе(запись):
		прохождения.отметить_пройденным(запись.student, запись.course, ключ, подтверждённые_цели)
	# Домашка выдаётся на каждое закрытие: повторное ничего не меняет, а закрытие
	# в другом пространстве даёт свою сдачу (learning-services#439). Why: фоном и
	# после коммита — зачёт квиза и закрытие урока не зависят от домашки: гонка
	# за сдачу на MariaDB со снимочной изоляцией откатывает транзакцию целиком.
	# В тестах — сразу: `now` Frappe выполняет вызов синхронно, мимо очереди.
	# Задача ставится только уроку с заданием, и сбой постановки не срывает
	# закрытие: `enqueue` синхронно проверяет размер очереди (`QueueOverloaded`).
	if frappe.db.exists("Agent Lesson Homework", {"lesson": запись.lesson}):
		try:
			frappe.enqueue(
				"lms_frappe_app.agent_learning.homework.выдать_по_записи",
				queue="short",
				enqueue_after_commit=True,
				now=frappe.in_test,
				doctype=запись.doctype,
				name=запись.name,
			)
		except Exception:
			frappe.log_error(title="Домашка не поставлена в очередь выдачи (learning-services#439)")
	уже = frappe.db.exists(
		"LMS Course Progress", {"member": запись.student, "lesson": запись.lesson}
	)
	if уже:
		frappe.db.set_value("LMS Course Progress", уже, "status", ПРОЙДЕН)
		return
	frappe.get_doc(
		{
			"doctype": "LMS Course Progress",
			"member": запись.student,
			"lesson": запись.lesson,
			"chapter": frappe.db.get_value("Course Lesson", запись.lesson, "chapter"),
			"course": запись.course,
			"status": ПРОЙДЕН,
		}
	).insert(ignore_permissions=True)


def _ключ_урока_в_релизе(запись) -> str | None:
	"""Ключ урока из релиза: у попытки — свой, у занятия — его прохождения или действующего релиза.

	Урок не из релиза — `None`.
	"""
	if запись.get("lesson_key"):
		return запись.lesson_key
	if запись.get("run"):
		return frappe.db.get_value(прохождения.ПРОХОЖДЕНИЕ, запись.run, "lesson_key")
	релиз = прохождения.действующий(запись.course)
	return index.ключ_урока(релиз, запись.lesson) if релиз else None
