"""Правила серверного квиза вокруг попытки: отказы, лимит и пауза, журнал проверки, закрытие урока.

Несущее решение всей схемы зачёта: агент работает на стороне ученика и судьёй
быть не может. Сервер выдаёт вопрос, принимает ответ и возвращает вердикт —
**эталон при этом не покидает сервер ни в одном ответе**.

Поэтому утечка директивы урока портит педагогику одного занятия, но не даёт
незаслуженного зачёта: зачёт не зависит от добросовестности агента.

Сам квиз — старт попытки, ответ и итог — живёт в `release_quiz`. Здесь то, что
нужно не только ему: `отметить_урок_пройденным` закрывает урок и после
сданной попытки, и в `complete_lesson`; коды отказов квиза отдают и методы
контракта.
"""

from __future__ import annotations

from collections.abc import Collection
from datetime import datetime
from zoneinfo import ZoneInfo

import frappe
from frappe.utils import add_to_date, get_system_timezone, now_datetime

from lms_frappe_app.agent_learning.browser_progress import закрытие_урока
from lms_frappe_app.agent_learning.constants import ПОПЫТКА_АННУЛИРОВАНА, ПОПЫТКА_ИДЁТ, ПРОЙДЕН
from lms_frappe_app.agent_learning.errors import Отказ
from lms_frappe_app.agent_learning.releases import index
from lms_frappe_app.agent_learning.runs import service as прохождения

КВИЗА_НЕТ = "quiz_not_configured"
ПОПЫТКИ_ИСЧЕРПАНЫ = "quiz_attempts_exhausted"
СЛИШКОМ_РАНО = "retry_too_soon"
ПОПЫТКА_ЗАВЕРШЕНА = "attempt_finished"
ЧУЖОЙ_ВОПРОС = "question_mismatch"
НУЖНЫ_СЛОВА = "student_words_required"

#: Сколько слов ученика ложится в журнал. Обрезка, а не отказ: слова только
#: для разбора и на вердикт не влияют, а отказ из-за длины стоил бы ученику
#: ответа. Предел — про читателя журнала: две тысячи знаков хватает на
#: развёрнутый ответ и не хватает на пересказ всего разговора.
ДЛИНА_СЛОВ = 2000


# --- лимит попыток и пауза ---


def попытки_урока(student: str, course: str, lesson_key: str) -> dict:
	"""Отбор попыток урока, которые идут в лимит и паузу: ученик, курс, ключ урока, кроме аннулированных.

	`Why:` ключ урока стабилен между релизами: новый релиз не обнуляет ни
	лимит, ни паузу.

	`Why:` аннулированная (`Cancelled`) не в счёт: аннуляция — следствие
	публикации автора, а не действия ученика; лимит и пауза защищают от
	перебора, которого здесь нет. Поэтому и номер следующей попытки — тот же,
	что у аннулированной.
	"""
	return {
		"student": student,
		"course": course,
		"lesson_key": lesson_key,
		"status": ("!=", ПОПЫТКА_АННУЛИРОВАНА),
	}


def проверить_право_на_попытку(отбор: dict, политика: dict) -> None:
	"""Лимит попыток и пауза перед повтором — из политики платформы.

	`отбор` — попытки, которые идут в счёт: `попытки_урока`.
	"""
	прошлых = прошлых_попыток(отбор)
	лимит = политика["max_attempts"]
	if лимит and прошлых >= лимит:  # ноль означает «без лимита»
		raise Отказ(
			ПОПЫТКИ_ИСЧЕРПАНЫ, f"Использованы все попытки ({лимит})", attempts_used=прошлых
		)

	# Пауза — от последней завершённой: не открытой и не аннулированной.
	последняя = frappe.get_all(
		"Agent Quiz Attempt",
		filters={**отбор, "status": ("not in", (ПОПЫТКА_ИДЁТ, ПОПЫТКА_АННУЛИРОВАНА))},
		fields=["finished_at"],
		order_by="finished_at desc",
		limit=1,
	)
	if not последняя or not последняя[0].finished_at:
		return

	можно_с = _можно_с(последняя[0].finished_at, политика)
	if now_datetime() < можно_с:
		raise Отказ(
			СЛИШКОМ_РАНО,
			"Повторить попытку можно позже",
			retry_after=_с_поясом(можно_с),
		)


def _можно_с(закончена: datetime, политика: dict) -> datetime:
	"""Когда можно начать следующую попытку после завершённой — наивное время сайта.

	Наивное, потому что сравнивается с `now_datetime()`, а он тоже без пояса.
	Наружу момент уходит только через `_с_поясом`.
	"""
	return add_to_date(закончена, minutes=политика["retry_delay_minutes"])


def _с_поясом(момент: datetime) -> str:
	"""ISO 8601 со смещением часового пояса сайта.

	`Why:` Frappe хранит и отдаёт время наивным, в поясе сайта. Строка без
	смещения читается как UTC, и агент называл ученику время пересдачи со
	сдвигом на пояс сервера.
	"""
	return момент.replace(tzinfo=ZoneInfo(get_system_timezone())).isoformat()


def осталось_попыток(отбор: dict, политика: dict) -> int | None:
	"""Сколько попыток ещё можно начать; `None` — лимита нет.

	`отбор` — как у `проверить_право_на_попытку`.
	"""
	лимит = политика["max_attempts"]
	if not лимит:  # ноль означает «без лимита»
		return None
	return max(0, лимит - прошлых_попыток(отбор))


def пересдача(отбор: dict, политика: dict, закончена: datetime) -> dict:
	"""Остаток попыток и время пересдачи для итога незачтённой попытки: `{attempts_left, retry_after}`.

	`отбор` — как у `проверить_право_на_попытку`, `закончена` — `finished_at`
	попытки. Попыток не осталось — `retry_after` пуст: пересдавать нечем.

	`Why:` пауза и остаток — сразу в итоге, по тем же правилам, что проверит
	следующий старт попытки. Без них агент узнавал о паузе только отказом
	`retry_too_soon`, уже предложив пересдачу.
	"""
	осталось = осталось_попыток(отбор, политика)
	return {
		"attempts_left": осталось,
		"retry_after": None if осталось == 0 else _с_поясом(_можно_с(закончена, политика)),
	}


def прошлых_попыток(отбор: dict) -> int:
	"""Сколько попыток ученик уже израсходовал: `отбор` — `попытки_урока`.

	Считаются **все**, включая открытые, кроме аннулированных публикацией
	(`попытки_урока`). `Why:` иначе брошенная попытка не стоит ничего: ученик
	отвечает наугад, видит вердикт, бросает и начинает заново — перебором до
	верного варианта. Лимит попыток и пауза перед повтором при этом остаются на
	бумаге.
	"""
	return frappe.db.count("Agent Quiz Attempt", отбор)


# --- журнал проверки ---


def _в_журнал(вид: str, попытка, **поля) -> None:
	"""Пишет событие журнала проверки: `вид` и `поля` — ключ вопроса, ответ, слова ученика, вердикт.

	`попытка` — запись попытки или словарь с теми же полями: `name`,
	`session`, `student`, `course`, `lesson`. Пишется в транзакции вызова:
	откат попытки откатывает и журнал, и расхождения между ними не бывает.
	"""
	frappe.get_doc(
		{
			"doctype": "Agent Quiz Event",
			"kind": вид,
			"attempt": попытка.name,
			"session": попытка.session,
			"student": попытка.student,
			"course": попытка.course,
			"lesson": попытка.lesson,
			**поля,
		}
	).insert(ignore_permissions=True)


def _привести(значение) -> str:
	return " ".join(str(значение or "").lower().split())


# --- закрытие урока ---


def отметить_урок_пройденным(запись, подтверждённые_цели: Collection[str] = ()) -> None:
	"""Пишет `LMS Course Progress` — тот же прогресс, что видит браузер, — и
	`passed` у прохождения урока из релиза.

	Принимает и попытку квиза, и занятие: у обеих есть ученик, урок и курс, а
	прогресс от способа закрытия урока не зависит. `подтверждённые_цели` —
	цели, которые сданная попытка подтвердила квизом
	(`runs.service.отметить_пройденным`).
	"""
	if ключ := _ключ_урока_в_релизе(запись):
		прохождения.отметить_пройденным(запись.student, запись.course, ключ, подтверждённые_цели)
	# Домашка выдаётся на каждое закрытие: повторное ничего не меняет, а закрытие
	# в другом пространстве даёт свою сдачу (learning-services#439). Why: фоном и
	# после коммита — зачёт квиза и закрытие урока не зависят от домашки: гонка
	# за сдачу на MariaDB со снимочной изоляцией откатывает транзакцию целиком.
	# В тестах — сразу: `now` Frappe выполняет вызов синхронно, мимо очереди.
	# Задача ставится только уроку с действующим заданием — снятое из релиза
	# (`retired`) не выдаётся, — и сбой постановки не срывает закрытие:
	# `enqueue` синхронно проверяет размер очереди (`QueueOverloaded`).
	if frappe.db.exists("Agent Lesson Homework", {"lesson": запись.lesson, "retired": 0}):
		try:
			frappe.enqueue(
				"lms_frappe_app.agent_learning.homework.выдать_по_записи",
				queue="short",
				enqueue_after_commit=True,
				now=frappe.in_test,
				doctype=запись.doctype,
				name=запись.name,
			)
		except Exception:
			frappe.log_error(title="Домашка не поставлена в очередь выдачи (learning-services#439)")
	уже = frappe.db.exists(
		"LMS Course Progress", {"member": запись.student, "lesson": запись.lesson}
	)
	# Урок курса из релиза отметкой закрывает только занятие (learning-services#525).
	with закрытие_урока(запись.student, запись.lesson):
		if уже:
			frappe.db.set_value("LMS Course Progress", уже, "status", ПРОЙДЕН)
			return
		frappe.get_doc(
			{
				"doctype": "LMS Course Progress",
				"member": запись.student,
				"lesson": запись.lesson,
				"chapter": frappe.db.get_value("Course Lesson", запись.lesson, "chapter"),
				"course": запись.course,
				"status": ПРОЙДЕН,
			}
		).insert(ignore_permissions=True)


def _ключ_урока_в_релизе(запись) -> str | None:
	"""Ключ урока из релиза: у попытки — свой, у занятия — его прохождения или действующего релиза.

	Занятие без прохождения — по действующему релизу курса. Урок не из
	релиза — `None`.
	"""
	if запись.get("lesson_key"):
		return запись.lesson_key
	if запись.get("run"):
		return frappe.db.get_value(прохождения.ПРОХОЖДЕНИЕ, запись.run, "lesson_key")
	релиз = прохождения.действующий(запись.course)
	return index.ключ_урока(релиз, запись.lesson) if релиз else None
