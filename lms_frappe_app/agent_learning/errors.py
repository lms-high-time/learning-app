"""Доменные отказы контракта.

Отказ несёт **машинный код**, а не только текст: агент по нему решает, что
делать дальше, и объясняет ученику. Тексты меняются и переводятся, коды нет.

`Why:` тело ошибки HTTP формирует Frappe — в API v1 туда попадают `exc_type` и
`exception`, причём последнее только при разрешённом traceback. В проде его
нет, и машинного кода в ответе не остаётся. Поэтому ожидаемые отказы едут
успешным ответом с полем `error.code`.
"""

import frappe


#: Коды, которыми отказывают разные модули. Дом здесь у тех, кого называют
#: двое и больше: разъехавшись, две копии кода дают агенту два разных отказа
#: на одну и ту же беду. Код, который знает один модуль, живёт в этом модуле.
УРОК_НЕ_НАЙДЕН = "lesson_not_found"
НЕИЗВЕСТНЫЙ_ВИД_РЕПОРТА = "unknown_report_kind"
НЕТ_ПРАВА = "not_allowed"
КУРС_НЕ_НАЙДЕН = "course_not_found"
#: Курс снят и закрыт для занятий; записи и документы учеников целы (learning-services#500).
КУРС_В_АРХИВЕ = "course_archived"


class Отказ(frappe.ValidationError):
	"""Ожидаемый отказ: у ученика кончились попытки, курс не назначен и т.п."""

	def __init__(self, код: str, сообщение: str, **подробности):
		super().__init__(сообщение)
		self.код = код
		self.сообщение = сообщение
		self.подробности = подробности
