"""Доменные отказы контракта.

Отказ несёт **машинный код**, а не только текст: агент по нему решает, что
делать дальше, и объясняет ученику. Тексты меняются и переводятся, коды нет.

`Why:` тело ошибки HTTP формирует Frappe — в API v1 туда попадают `exc_type` и
`exception`, причём последнее только при разрешённом traceback. В проде его
нет, и машинного кода в ответе не остаётся. Поэтому ожидаемые отказы едут
успешным ответом с полем `error.code`.
"""

import frappe


#: Коды, которыми отказывают разные модули. Дом здесь у тех, кого называют
#: двое и больше: разъехавшись, две копии кода дают агенту два разных отказа
#: на одну и ту же беду. Код, который знает один модуль, живёт в этом модуле.
УРОК_НЕ_НАЙДЕН = "lesson_not_found"
НЕИЗВЕСТНЫЙ_ВИД_РЕПОРТА = "unknown_report_kind"
НЕТ_ПРАВА = "not_allowed"
КУРС_НЕ_НАЙДЕН = "course_not_found"
ЧУЖОЕ_ЗАНЯТИЕ = "not_your_session"
ЗАНЯТО = "busy"
#: Методы ученика работают только с курсом из релиза: у курса нет действующего
#: релиза или урока в нём (learning-services#506).
КУРС_НЕ_В_РЕЛИЗЕ = "course_not_released"
#: Урока с этим ключом нет в действующем релизе курса.
УРОК_НЕ_В_РЕЛИЗЕ = "lesson_not_in_release"
#: Прохождение урока в архиве: сброс прогресса отвязал его от ученика.
ПРОХОЖДЕНИЕ_В_АРХИВЕ = "run_archived"
#: Курс собран из релиза и правится только новым релизом: методы авторинга и
#: охрана структуры курса в Learning (`releases.course_guard`).
КУРС_ИЗ_РЕЛИЗА = "course_from_release"
#: `<` или `>` в названии, где их быть не может: проверка релиза
#: (`releases.checks`) и сохранение шаблона домашки и схемы документа.
НАЗВАНИЕ_С_УГЛОВЫМИ = "title_forbidden_chars"
#: Знаки, запрещённые в таких названиях.
УГЛОВЫЕ = "<>"


class Отказ(frappe.ValidationError):
	"""Ожидаемый отказ: у ученика кончились попытки, курс не назначен и т.п."""

	def __init__(self, код: str, сообщение: str, **подробности):
		super().__init__(сообщение)
		self.код = код
		self.сообщение = сообщение
		self.подробности = подробности


def запретить_угловые(название: str | None, где: str) -> None:
	"""Отказ `title_forbidden_chars`, если в названии есть `<` или `>`.

	`Why:` название шаблона домашки и схемы документа — `title_field` своего
	доктайпа: Desk выводит его в Report view и в выпадающем списке ссылки без
	экранирования, а Frappe чистит HTML в нём при сохранении. Запрет держит
	название текстом на любом пути записи — релиз, Desk, REST.
	"""
	if знаки := [з for з in УГЛОВЫЕ if з in (название or "")]:
		raise Отказ(НАЗВАНИЕ_С_УГЛОВЫМИ, "В названии не бывает < и >", where=где, chars=знаки)
