"""Сборка курса: вопросы квиза и готовность к публикации.

Здесь только хранение и нормализация. Педагогика — как формулировать вопрос,
на сколько уроков резать тему, что писать в директиве — живёт в агенте
куратора и в промпте авторского эндпоинта, а не в этом файле.
`Why:` приложение публикуется под AGPL; уехав сюда, эта логика перестанет
быть нашей.
"""

import frappe

from lms_frappe_app.agent_learning.artifacts.templates import последние_версии
from lms_frappe_app.agent_learning.constants import ВАРИАНТОВ_МАКСИМУМ, ВЫБОР, ПРОВЕРЯЕМЫЕ_ТИПЫ
from lms_frappe_app.agent_learning.errors import Отказ

СЛИШКОМ_МНОГО_ВАРИАНТОВ = "too_many_options"
НЕИЗВЕСТНЫЙ_ТИП = "unknown_question_type"


# --- плоские поля вопроса ---


def поля_вопроса(*виды: str) -> list[str]:
	"""Имена полей вопроса перечисленных видов: `option`, `is_correct`, …

	`Why:` Frappe Learning хранит варианты, эталоны и пояснения десятью
	плоскими полями на каждый вид, и перебор `1..ВАРИАНТОВ_МАКСИМУМ` был
	переписан в шести местах — в квизе, в авторинге и здесь. Предел при этом
	жил в двух модулях: добавить одиннадцатое поле и не забыть ни об одном из
	шести циклов было нельзя.
	"""
	return [f"{вид}_{номер}" for вид in виды for номер in range(1, ВАРИАНТОВ_МАКСИМУМ + 1)]


def заполненные(запись, вид: str) -> list[tuple[int, object]]:
	"""Заполненные поля одного вида — парами «номер, значение», по порядку.

	Незаполненным считается пустое значение, а у строк — ещё и строка из
	одних пробелов: вариант из пробелов агенту показывать нечего, сверять с
	ним нечего, и куратор его видит как пустой. Снятая галочка `is_correct`
	приезжает нулём и незаполненной же и считается.

	Принимает и документ, и строку выборки: у обоих есть `get`, а звать сюда
	полный документ ради десяти полей незачем.
	"""
	собранное = []
	for номер in range(1, ВАРИАНТОВ_МАКСИМУМ + 1):
		значение = запись.get(f"{вид}_{номер}")
		непусто = значение.strip() if isinstance(значение, str) else значение
		if непусто:
			собранное.append((номер, значение))
	return собранное


# --- вопросы ---


def создать_вопрос(вопрос: dict) -> tuple[str, str]:
	"""Заводит `LMS Question`, возвращает идентификатор и тип.

	Документ создаётся целиком, а не записью полей в базу: вся проверка
	вопроса у Frappe Learning живёт в `validate` (дубли вариантов, минимум
	два варианта, хотя бы один верный, образцы ответа для открытого), а в
	схеме не обязательно ни одно поле. Запись мимо документа обошла бы весь
	этот контроль молча.
	"""
	тип = вопрос.get("type") or ВЫБОР
	if тип not in ПРОВЕРЯЕМЫЕ_ТИПЫ:
		raise Отказ(
			НЕИЗВЕСТНЫЙ_ТИП,
			f"Тип вопроса должен быть одним из: {', '.join(ПРОВЕРЯЕМЫЕ_ТИПЫ)}",
			received=тип,
		)

	документ = frappe.new_doc("LMS Question")
	документ.question = (вопрос.get("text") or "").strip()
	документ.type = тип
	if тип == ВЫБОР:
		_проставить_варианты(документ, вопрос.get("options") or [])
	else:
		_проставить_образцы(документ, вопрос.get("answers") or [])
	документ.insert()
	return документ.name, тип


def заменить_варианты(документ, варианты: list[dict]) -> None:
	"""Переписывает варианты вопроса целиком.

	Старые поля очищаются: правка «трёх вариантов на два» иначе оставила бы
	третий на месте, и вопрос ответил бы не тем, что видит куратор.
	"""
	_очистить(документ, "option", "is_correct", "explanation")
	_проставить_варианты(документ, варианты)


def заменить_образцы(документ, ответы: list[str]) -> None:
	"""Переписывает образцы ответа целиком — по той же причине."""
	_очистить(документ, "possibility")
	_проставить_образцы(документ, ответы)


def _очистить(документ, *виды: str) -> None:
	for имя in поля_вопроса(*виды):
		документ.set(имя, None)


def _проставить_варианты(документ, варианты: list[dict]) -> None:
	_проверить_количество(варианты)
	for номер, вариант in enumerate(варианты, start=1):
		документ.set(f"option_{номер}", (вариант.get("text") or "").strip())
		документ.set(f"is_correct_{номер}", 1 if вариант.get("correct") else 0)
		пояснение = (вариант.get("explanation") or "").strip()
		if пояснение:
			документ.set(f"explanation_{номер}", пояснение)


def _проставить_образцы(документ, ответы: list[str]) -> None:
	_проверить_количество(ответы)
	for номер, ответ in enumerate(ответы, start=1):
		документ.set(f"possibility_{номер}", (ответ or "").strip())


def _проверить_количество(элементы: list) -> None:
	if len(элементы) > ВАРИАНТОВ_МАКСИМУМ:
		raise Отказ(
			СЛИШКОМ_МНОГО_ВАРИАНТОВ,
			f"Frappe Learning хранит не более {ВАРИАНТОВ_МАКСИМУМ} вариантов в вопросе",
			received=len(элементы),
		)


# --- готовность к публикации ---

ПУСТОЙ_КУРС = "empty_course"
ПУСТОЙ_УРОК = "empty_lesson"
ВОПРОС_БЕЗ_ТЕКСТА = "blank_question"
КВИЗ_БЕЗ_ВОПРОСОВ = "empty_quiz"
НЕТ_ОПИСАНИЯ = "no_summary"

БЕЗ_ДИРЕКТИВЫ = "lesson_without_directive"
БЕЗ_ДИРЕКТИВЫ_КУРСА = "course_without_directive"
БЕЗ_КВИЗОВ = "course_without_quiz"
БЕЗ_БЛОКОВ = "artifact_without_blocks"
ФАЙЛ_БЕЗ_ФОРМАТОВ = "artifact_file_without_accept"
БЕЗ_ОБЕЩАНИЯ = "course_without_promise"
БЕЗ_ЗАЧИНА = "lesson_without_hook"
ШАБЛОН_УШЁЛ_ВПЕРЁД = "artifact_template_outdated"


def проверить_готовность(курс: str) -> dict:
	"""Что мешает публикации и о чём стоит знать до неё.

	Возвращает всё разом, а не первую найденную беду: агент, получающий по
	одной ошибке за вызов, будет долбиться в публикацию по кругу, а куратор —
	смотреть на это.

	Проверяем только то, чего не проверяет Frappe Learning. Состав вариантов
	и наличие верного ответа он контролирует сам, в момент создания вопроса —
	см. `создать_вопрос`.
	"""
	from lms_frappe_app.agent_learning import quiz
	from lms_frappe_app.agent_learning.structure import уроки_курса

	# Курс из релиза проверен целиком при публикации релиза (learning-services#500):
	# директив, материала и квизов Learning у него нет, и проверка ниже отказала бы зря.
	if frappe.db.get_value("LMS Course", курс, "active_release"):
		return {"blocking": [], "warnings": []}

	мешает, стоит_знать = [], []

	if not frappe.db.get_value("LMS Course", курс, "short_introduction"):
		мешает.append({"code": НЕТ_ОПИСАНИЯ, "message": "Без краткого описания карточка в каталоге пустая"})

	if not frappe.db.exists("Agent Course Directive", {"course": курс, "is_active": 1}):
		стоит_знать.append(
			{
				"code": БЕЗ_ДИРЕКТИВЫ_КУРСА,
				"message": (
					"Курс без сквозной директивы: тон, роль преподавателя и "
					"терминология будут разными от занятия к занятию"
				),
			}
		)

	# Предупреждением, а не отказом: курсы, опубликованные до этих полей,
	# иначе разом перестали бы публиковаться (#238).
	if not frappe.db.get_value("LMS Course", курс, "course_promise"):
		стоит_знать.append(
			{
				"code": БЕЗ_ОБЕЩАНИЯ,
				"message": "Без обещания курса агенту нечем начать первое занятие — зачем курс и что человек получит",
			}
		)

	уроки = уроки_курса(курс)
	if not уроки:
		мешает.append({"code": ПУСТОЙ_КУРС, "message": "В курсе нет ни одного урока"})

	с_квизом = 0
	for урок in уроки:
		if not (frappe.db.get_value("Course Lesson", урок, "body") or "").strip():
			мешает.append({"code": ПУСТОЙ_УРОК, "lesson": урок, "message": "Урок без материала"})

		квиз = quiz._квиз_урока(урок)
		if квиз:
			с_квизом += 1
			мешает += _беды_квиза(квиз, урок)

		if not (frappe.db.get_value("Course Lesson", урок, "lesson_hook") or "").strip():
			стоит_знать.append(
				{
					"code": БЕЗ_ЗАЧИНА,
					"lesson": урок,
					"message": "Урок без зачина: агент начнёт с вопросов, не сказав, зачем тема ученику",
				}
			)

		if not frappe.db.exists("Agent Lesson Directive", {"lesson": урок, "is_active": 1}):
			стоит_знать.append(
				{
					"code": БЕЗ_ДИРЕКТИВЫ,
					"lesson": урок,
					"message": "Урок без директивы: агент поведёт занятие по одному материалу",
				}
			)

	if уроки and not с_квизом:
		стоит_знать.append(
			{"code": БЕЗ_КВИЗОВ, "message": "В курсе нет ни одного квиза: он зачтётся по прохождению уроков"}
		)

	# Артефакт публикацию не блокирует: курс без него — нормальный курс. Но
	# объявленный и пустой — ошибка автора, которую ученик увидит первым.
	схемы = frappe.get_all(
		"Agent Course Artifact",
		filters={"course": курс, "is_active": 1},
		fields=["name", "slug", "title", "template", "template_version"],
	)
	стоит_знать += _шаблоны_ушли_вперёд(схемы)
	for схема in схемы:
		if not frappe.db.exists("Agent Artifact Block", {"parent": схема.name}):
			стоит_знать.append(
				{
					"code": БЕЗ_БЛОКОВ,
					"artifact": схема.slug,
					"message": "Документ объявлен без блоков: ученику нечего заполнять",
				}
			)
		# Блок-файл без списка форматов примет что угодно — ученик загрузит
		# снимок экрана вместо таблицы, и агент не построит срез (#315).
		for блок in frappe.get_all(
			"Agent Artifact Block",
			filters={"parent": схема.name, "kind": "file"},
			fields=["block_key", "accept"],
		):
			if not (блок.accept or "").strip():
				стоит_знать.append(
					{
						"code": ФАЙЛ_БЕЗ_ФОРМАТОВ,
						"artifact": схема.slug,
						"key": блок.block_key,
						"message": "Блок-файл без допустимых форматов: укажите accept, например xlsx,csv",
					}
				)

	return {"blocking": мешает, "warnings": стоит_знать}


def _шаблоны_ушли_вперёд(схемы: list) -> list[dict]:
	"""Документы курса, чей шаблон вышел в новую версию (learning-services#376).

	Предупреждением, а не помехой: курс на закреплённой версии работает, как
	работал. Но автор узнаёт о новой версии здесь — и по `note` решает,
	переходить ли (`upgrade_course_artifact`).
	"""
	последние = последние_версии({с.template for с in схемы if с.template})
	предупреждения = []
	for схема in схемы:
		последняя = последние.get(схема.template)
		if not последняя or последняя["version"] <= (схема.template_version or 0):
			continue
		сообщение = (
			f"Документ «{схема.title}»: шаблон {схема.template} вышел в v{последняя['version']}, "
			f"курс на v{схема.template_version}."
		)
		if последняя["note"]:
			сообщение += f" {последняя['note']}"
		предупреждения.append(
			{
				"code": ШАБЛОН_УШЁЛ_ВПЕРЁД,
				"artifact": схема.slug,
				"template": схема.template,
				"message": сообщение,
			}
		)
	return предупреждения


def _беды_квиза(квиз: str, урок: str) -> list[dict]:
	вопросы = frappe.get_all("LMS Quiz Question", filters={"parent": квиз}, pluck="question")
	if not вопросы:
		return [
			{
				"code": КВИЗ_БЕЗ_ВОПРОСОВ,
				"lesson": урок,
				"message": "Квиз без вопросов: ученик упрётся в зачёт из ничего",
			}
		]

	# Единственное, чего Frappe Learning не ловит: пустой текст вопроса.
	# В схеме `LMS Question` не обязательно ни одно поле, включая сам вопрос.
	пустые = [
		вопрос
		for вопрос in вопросы
		if not (frappe.db.get_value("LMS Question", вопрос, "question") or "").strip()
	]
	return [
		{"code": ВОПРОС_БЕЗ_ТЕКСТА, "lesson": урок, "question": вопрос, "message": "Вопрос без текста"}
		for вопрос in пустые
	]
