"""Квиз урока из релиза: старт, ответ, итог и попытки между релизами (learning-services#504, #514).

Попытка — `Agent Quiz Attempt` с релизом, ключом урока, снимком вопросов и
порогом зачёта. Вопросы выдаются из снимка, верный вариант и пояснение сервер
берёт из релиза попытки. Эталон наружу не уходит: в снимке его нет, а неверный
ответ не получает ни верного варианта, ни пояснения — пояснения к неверно
отвеченным приходят только в итоге сданной попытки (F2).

Попытка проверяется по одному релизу. Публикация новой версии переносит
открытую попытку на неё, если квиз урока не изменился, иначе аннулирует
(`перенести_попытки`); попытку, которую публикация не застала, аннулирует
ленивая проверка в `ответить` и `начать`. Аннулированная (`Cancelled`) не
идёт в лимит и паузу, и следующий старт квиза даёт новую попытку.

Лимит попыток, пауза и обязательность — политика платформы, общая с `quiz`;
попытки считаются по ученику, курсу и ключу урока (`quiz.попытки_урока`).
Порог зачёта — `pass_percentage` урока, снятый в попытку на её старте (F1).
"""

