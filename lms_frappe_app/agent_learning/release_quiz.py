#: Поля открытой попытки, которые нужны переносу и журналу проверки.
ПОЛЯ_ОТКРЫТОЙ = ["name", "release", "lesson_key", "session", "student", "course", "lesson"]


def заблокировать_открытые(курс: str) -> list:
	"""Открытые попытки курса — с блокировкой, для `перенести_попытки`.

	Публикация зовёт её сразу после блокировки курса и проверки `unchanged`,
	до тяжёлых записей. Отбор идёт по индексу `(course, status)`
	(`install.обеспечить_индекс_попыток`).

	`Why:` без индекса MariaDB стенда (RR, `innodb_snapshot_isolation`)
	заблокировала бы строки и промежутки всей таблицы попыток всех курсов, и
	публикация падала бы на изменении любой попытки платформы. С индексом
	блокируются открытые попытки курса и промежуток `(course, In Progress)`
	вокруг них: попытки других курсов публикация не держит, но вставку
	попытки у соседнего по индексу курса может ненадолго задержать до своего
	коммита. Цикла с
	агентом нет: `ответить` берёт попытку первой, затем прохождение и
	занятие, а курс не блокирует; публикация не блокирует ни прохождений, ни
	занятий. Столкновение с ответом приходит взаимоблокировкой — ответ
	получает `busy`, а публикация — `busy` в `publish_release`.
	"""
	return frappe.db.get_values(
		ПОПЫТКА,
		{"course": курс, "status": ПОПЫТКА_ИДЁТ},
		ПОЛЯ_ОТКРЫТОЙ,
		as_dict=True,
		for_update=True,
	)


def перенести_попытки(попытки: list, релиз: str, строки: dict) -> dict[str, int]:
	"""Открытые попытки курса — на новый релиз `релиз` или в аннулированные: `{moved, cancelled}`.

	`попытки` — `заблокировать_открытые`, `строки` — индекс нового релиза в
	форме `index.строки` с вопросами, какими их записала база (строки
	вставленной записи релиза). Квиз урока попытки сравнивается в форме строк индекса
	(`квиз_тот_же`): совпал — у попытки новый `release`, а снимок вопросов,
	ответы и журнал не трогаются; не совпал — аннулирование `quiz_changed`,
	урока нет в новом релизе — `lesson_removed`. Релиз попытки уже освобождён
	(пустой снимок или нет строк вопросов урока) — `quiz_changed` без
	сравнения, если урок в новом релизе есть. Перенос и аннулирование пишут
	событие журнала проверки.

	Без открытых попыток — ни одного запроса. Прежние строки всех нужных пар
	«релиз, урок» — одной выборкой, записи — по одной на перенос и на причину
	аннулирования, событие — на попытку.

	`Why:` переносить можно только квиз, проверка которого не меняется:
	попытку проверяют по одному релизу, а её снимок и ответы сняты с
	прежнего.
	"""
	if not попытки:
		return {"moved": 0, "cancelled": 0}
	новые = index.вопросы_из_строк(строки["questions"])
	уроки = {у["lesson_key"] for у in строки["lessons"]}
	прежние = index.вопросы_релизов({(п.release, п.lesson_key) for п in попытки if п.lesson_key in уроки})
	перенесены: list = []
	аннулированы: dict[str, list] = {}
	for п in попытки:
		if п.lesson_key not in уроки:
			аннулированы.setdefault(АННУЛИРОВАНА_УРОК_СНЯТ, []).append(п)
		elif (п.release, п.lesson_key) in прежние and квиз_тот_же(
			прежние[(п.release, п.lesson_key)], новые.get(п.lesson_key, [])
		):
			перенесены.append(п)
		else:
			аннулированы.setdefault(АННУЛИРОВАНА_КВИЗ_ИЗМЕНИЛСЯ, []).append(п)
	if перенесены:
		frappe.db.set_value(ПОПЫТКА, {"name": ("in", [п.name for п in перенесены])}, "release", релиз)
		for п in перенесены:
			_в_журнал(ПРОВЕРКА_ПОПЫТКА_ПЕРЕНЕСЕНА, п)
	for причина, список in аннулированы.items():
		_аннулировать(список, причина)
	return {"moved": len(перенесены), "cancelled": sum(map(len, аннулированы.values()))}


def квиз_тот_же(прежний: list[dict], новый: list[dict]) -> bool:
	"""Проверка квиза не меняется: те же вопросы по ключам и порядку, с тем же
	текстом, целью, вариантами (ключи, тексты, порядок) и верным вариантом.

	Оба квиза — в форме строк индекса с ответами (`index.вопросы`,
	`index.вопросы_из_строк`). Пояснения не сравниваются, порог — тоже: он в
	попытке со старта. Пустой квиз ни с чем не совпадает — сравнивать нечего.

	`Why:` вердикт и `objective_results` зависят только от вопросов,
	вариантов, верного варианта и цели вопроса; пояснение на проверку не
	влияет, а правка пояснений по репортам — самая частая, и аннулировать из-за
	неё попытки незачем.
	"""
	return bool(прежний) and list(map(_проверяемое, прежний)) == list(map(_проверяемое, новый))


def _проверяемое(вопрос: dict) -> tuple:
	"""Что из вопроса решает проверку: ключ, цель, текст, варианты по порядку, верный вариант."""
	return (
		вопрос["key"],
		вопрос["objective"],
		вопрос["text"],
		tuple((в["key"], в["text"]) for в in вопрос["options"]),
		вопрос["correct"],
	)


def _аннулировать(попытки: list, причина: str) -> None:
	"""Открытые попытки — в `Cancelled` с причиной и `finished_at` — сейчас; событие журнала на каждую.

	Ответы и журнал остаются. Одной записью на все попытки, мимо `validate`:
	у попытки нет правил сохранения, а меняются только статус и итог.
	"""
	frappe.db.set_value(
		ПОПЫТКА,
		{"name": ("in", [п.name for п in попытки])},
		{"status": ПОПЫТКА_АННУЛИРОВАНА, "cancel_reason": причина, "finished_at": now_datetime()},
	)
	for п in попытки:
		_в_журнал(ПРОВЕРКА_ПОПЫТКА_АННУЛИРОВАНА, п)


def _аннулировать_отставшую(попытка, релиз: str | None) -> str:
	"""Открытая попытка не на действующем релизе `релиз` — аннулирована без сравнения; отдаёт причину.

	Такую попытку завели в гонке: старт квиза прочёл прежний действующий
	релиз и вставил попытку после того, как публикация отобрала открытые.
	Её релиз — прежний, и сравнивать не с чем: после публикации его
	содержимое освобождается. Урока нет в действующем релизе —
	`lesson_removed`, иначе `quiz_changed`.
	"""
	есть = bool(релиз) and index.есть_урок(релиз, попытка.lesson_key)
	причина = АННУЛИРОВАНА_КВИЗ_ИЗМЕНИЛСЯ if есть else АННУЛИРОВАНА_УРОК_СНЯТ
	_аннулировать([попытка], причина)
	return причина


def _отказ_аннулирована(попытка, причина: str, *, отставшая: bool = False) -> Отказ:
	"""Отказ `quiz_attempt_cancelled`: при `quiz_changed` — запросить квиз
	заново; при `lesson_removed` — без обещания нового квиза: `request_quiz`
	по снятому уроку ответит `lesson_not_in_release`.

	`отставшая` — попытку аннулировал этот ответ (`_аннулировать_отставшую`):
	квиз сравнивать было не с чем, и сообщение не говорит, что он изменился."""
	if причина == АННУЛИРОВАНА_УРОК_СНЯТ:
		сообщение = "Урок снят из курса"
	elif отставшая:
		сообщение = "Попытка начата на прежней версии курса — запросите квиз заново: request_quiz"
	else:
		сообщение = "Квиз изменился в новой версии курса — запросите его заново: request_quiz"
	return Отказ(АННУЛИРОВАНА, сообщение, attempt=попытка.name, session=попытка.session, reason=причина)


# --- выдача вопроса ---


def _ответы(попытка: str, *, блокировать: bool = False) -> dict[str, bool]:
	"""Ответы попытки: ключ вопроса → верен ли."""
	строки = frappe.db.get_values(
		ОТВЕТ, {"attempt": попытка}, ["question_key", "is_correct"], as_dict=True, for_update=блокировать
	)
	return {с.question_key: bool(с.is_correct) for с in строки}


def _снимок(попытка) -> list[dict]:
	return frappe.parse_json(попытка.questions) or []


def _выдать_вопрос(попытка, вопросы: list[dict], *, блокировать: bool = False) -> dict | None:
	"""Первый неотвеченный вопрос снимка — с записью «выдан» в журнал проверки; все отвечены — `None`.

	`блокировать` — читать отвеченные с блокировкой (`ответить`).
	"""
	отвеченные = set(_ответы(попытка.name, блокировать=блокировать))
	for номер, вопрос in enumerate(вопросы, start=1):
		if вопрос["key"] not in отвеченные:
			_в_журнал(ПРОВЕРКА_ВОПРОС_ВЫДАН, попытка, question_key=вопрос["key"])
			return _вопрос_для_агента(вопрос, номер, len(вопросы))
	return None


def _вопрос_для_агента(вопрос: dict, номер: int, всего: int) -> dict:
	"""Вопрос агенту: `id`, `text`, `kind: choice`, номер `index` из `total`,
	`multiple` и варианты `{id, text}` с ключами релиза, без эталона.

	В релизе верный вариант у вопроса один — отсюда `multiple: false`.
	"""
	return {
		"id": вопрос["key"],
		"text": вопрос["text"],
		"kind": "choice",
		"index": номер,
		"total": всего,
		"multiple": False,
		"options": [{"id": в["key"], "text": в["text"]} for в in вопрос["options"]],
	}


def _требовать_доступ(ученик: str, курс: str) -> None:
	можно, причина = доступен_курс(ученик, курс)
	if not можно:
		raise Отказ(причина, "Этот курс сейчас недоступен", course=курс)
