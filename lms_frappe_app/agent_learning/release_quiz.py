# --- начало попытки ---


def начать(run, занятие: str) -> dict:
	"""Попытка квиза урока и её первый неотвеченный вопрос: `{attempt, question}`.

	`run` — прохождение урока (`runs.service.прохождение`), `занятие` — имя
	занятия по нему. Открытая попытка занятия по этому уроку на действующем
	релизе возвращается, а не заводится новая, — со своим снимком вопросов.
	Открытая попытка на другом релизе — заведённая в гонке с публикацией,
	которая её не застала, — аннулируется (`_аннулировать`), и ответ несёт
	`previous_attempt_cancelled` — `{attempt, reason}` прежней; дальше — как
	без открытой. Новая попытка снимает все вопросы урока действующего релиза
	по порядку релиза и его порог зачёта.

	Отказы: прохождение в архиве — `run_archived`; занятие другого ученика,
	урока, прохождения — `not_your_session`; курс недоступен; новой попытке — урока
	нет в действующем релизе (`lesson_not_in_release`), у урока нет вопросов
	(`quiz_not_configured`), лимит попыток платформы исчерпан или пауза перед
	повтором не вышла (`quiz.проверить_право_на_попытку`).

	Блокировки — в порядке «прохождение, занятие, открытая попытка»:
	прохождение читает с блокировкой `runs.service.прохождение`, занятие и
	попытку — здесь; попытку — только не на действующем релизе
	(`_открытая_попытка`). Метод контракта обязан брать их в том же порядке.
	`ответить` берёт попытку первой: два вызова агента навстречу друг другу
	могут сойтись взаимоблокировкой — её метод контракта отдаёт как `busy`.

	`Why:` занятие читается с блокировкой, чтобы два параллельных старта по
	одному занятию не завели две попытки. Держит это не ожидание, а запись:
	выигравший старт пишет строку занятия (событие двигает отметку
	активности), и блокирующее чтение проигравшего на MariaDB стенда
	(`innodb_snapshot_isolation`) падает `frappe.QueryDeadlockError` — метод
	контракта отдаёт его агенту как `busy`.

	Принято: два разных занятия одного урока, начавшие квиз одновременно,
	могут превысить лимит попыток на одну — блокировки на «ученик, курс,
	ключ урока» нет.
	"""
	прохождения.требовать_живое(run)
	прохождения.проверить_занятие(run, занятие)
	_требовать_доступ(run.student, run.course)
	сессия = frappe.get_doc("Agent Learning Session", занятие, for_update=True)
	релиз = прохождения.действующий(run.course)

	прежняя = None
	if открытая := _открытая_попытка(занятие, run.lesson_key, релиз):
		if открытая.release == релиз:
			сессия.записать_событие(СОБЫТИЕ_КВИЗ_НАЧАТ, "продолжение попытки")
			return {"attempt": открытая.name, "question": _выдать_вопрос(открытая, _снимок(открытая))}
		прежняя = {"attempt": открытая.name, "reason": _аннулировать_отставшую(открытая, релиз)}

	урок = index.урок(релиз, run.lesson_key) if релиз else None
	if not урок:
		raise прохождения.урок_не_в_релизе(run.course, run.lesson_key, релиз)
	вопросы = index.вопросы_урока(релиз, run.lesson_key)
	if not вопросы:
		raise Отказ(КВИЗА_НЕТ, "У этого урока нет квиза")
	отбор = попытки_урока(run.student, run.course, run.lesson_key)
	проверить_право_на_попытку(отбор, политика_квиза_для_курса(run.student, run.course))

	попытка = frappe.get_doc(
		{
			"doctype": ПОПЫТКА,
			"session": занятие,
			"student": run.student,
			"lesson": run.lesson,
			"course": run.course,
			"release": релиз,
			"lesson_key": run.lesson_key,
			"questions": json.dumps(вопросы, ensure_ascii=False),
			"attempt_number": прошлых_попыток(отбор) + 1,
			"pass_percentage": урок.pass_percentage,
			"status": ПОПЫТКА_ИДЁТ,
			"started_at": now_datetime(),
		}
	).insert(ignore_permissions=True)

	if сессия.status == ЗАНЯТИЕ_ИДЁТ:
		сессия.status = ЗАНЯТИЕ_ЖДЁТ_КВИЗ
		сессия.save(ignore_permissions=True)
	сессия.записать_событие(СОБЫТИЕ_КВИЗ_НАЧАТ, f"попытка {попытка.attempt_number}")

	ответ = {"attempt": попытка.name, "question": _выдать_вопрос(попытка, вопросы)}
	if прежняя:
		ответ["previous_attempt_cancelled"] = прежняя
	return ответ


def _открытая_попытка(занятие: str, ключ_урока: str, релиз: str | None):
	"""Незавершённая попытка занятия по уроку из релиза, если она есть.

	Попытка не на действующем релизе `релиз` перечитывается с блокировкой и
	отдаётся, только если она всё ещё не завершена; на действующем — без
	блокировки.

	`Why:` обычное чтение видит снимок транзакции, и публикация, закоммиченная
	после её начала, в нём не видна: перенесённая попытка показалась бы
	отставшей и была бы аннулирована. Блокирующее чтение видит последнюю
	версию строки — на стенде (MariaDB, `innodb_snapshot_isolation`) попытка,
	изменённая после начала транзакции, даёт на нём взаимоблокировку
	(`CHECKREAD`), и метод контракта отвечает `busy`, а повтор читает свежий
	снимок. Поэтому блокируется только попытка, которую иначе аннулировали бы:
	продолжение попытки на действующем релизе такой гонки не знает.
	"""
	открытые = frappe.get_all(
		ПОПЫТКА,
		filters={"session": занятие, "lesson_key": ключ_урока, "status": ПОПЫТКА_ИДЁТ},
		fields=["name", "release"],
		order_by="creation desc",
		limit=1,
	)
	if not открытые:
		return None
	if открытые[0].release == релиз:
		return frappe.get_doc(ПОПЫТКА, открытые[0].name)
	попытка = frappe.get_doc(ПОПЫТКА, открытые[0].name, for_update=True)
	return попытка if попытка.status == ПОПЫТКА_ИДЁТ else None


# --- ответ ---


def ответить(попытка: str, ключ_вопроса: str, ответ, слова_ученика: str) -> dict:
	"""Сверяет ответ по релизу попытки: `{verdict, next_question, attempt_finished}`, после последнего — и `result`.

	`ответ` — ключ варианта или его текст, без учёта регистра и пробелов
	(агенты присылают текст, lms-platform#148); список из одного элемента —
	как сам элемент, из нескольких — неверный ответ: верный вариант у вопроса
	один. Неузнанный ответ — неверный, а не ошибка. Верный ответ получает пояснение вопроса, неверный —
	только `correct: false` (F2). `слова_ученика` — что ученик написал в ответ,
	дословно: в журнал проверки, на вердикт не влияют.

	`attempt_finished` — на все вопросы снимка отвечено, `next_question` пуст,
	а `result` — итог попытки (`завершить`).

	Отказы: нет слов ученика — `student_words_required`; попытка
	аннулирована — `quiz_attempt_cancelled` (`attempt`, `session`, `reason`);
	попытка завершена — `attempt_finished`; курс недоступен; вопроса нет в
	снимке или на него уже отвечено — `question_mismatch`.

	Попытка не на действующем релизе — заведённая в гонке с публикацией,
	которая её не застала, — аннулируется здесь, до вставки ответа, и
	получает тот же отказ `quiz_attempt_cancelled`. `Why:` аннулирование
	перед отказом фиксируется намеренно: отказ контракта — успешный ответ, и
	Frappe фиксирует записанное до него; гонка редкая, а проверка стоит один
	запрос на ответ и не заставляет старт квиза ждать публикацию.

	`Why:` ответ на вопрос один на попытку, и держит это уникальный индекс
	(`install.обеспечить_индекс_ответов_квиза`): второй ответ — второй
	вердикт, а он назвал бы верный вариант. Проверка «уже отвечено» читает без
	блокировки и параллельный ответ не видит; вставка дубля падает на индексе
	и откатывается к точке сохранения в тот же отказ. Блокировка попытки только
	выстраивает ответы по очереди; при настоящей гонке MariaDB стенда
	(`innodb_snapshot_isolation`) может ответить на неё
	`frappe.QueryDeadlockError` — метод контракта отдаёт его как `busy`.

	`Why:` отвеченные вопросы для выдачи следующего и для итога читаются с
	блокировкой. Обычное чтение видит снимок транзакции, взятый до ожидания
	блокировки попытки: два ответа на разные последние вопросы не увидели бы
	друг друга, и попытку не завершил бы ни один. Блокирующее чтение видит
	ответ соседа или падает взаимоблокировкой — `busy`, а не застрявшая попытка.
	"""
	слова = str(слова_ученика or "").strip()
	if not слова:
		raise Отказ(НУЖНЫ_СЛОВА, "Передайте, что ученик написал в ответ, дословно")

	запись = frappe.get_doc(ПОПЫТКА, попытка, for_update=True)
	if запись.status == ПОПЫТКА_АННУЛИРОВАНА:
		raise _отказ_аннулирована(запись, запись.cancel_reason)
	if запись.status != ПОПЫТКА_ИДЁТ:
		raise Отказ(ПОПЫТКА_ЗАВЕРШЕНА, "Эта попытка уже завершена")
	# Доступ — на каждом ответе: приостановка организации или снятое
	# зачисление посреди квиза иначе не мешали бы довести его до зачёта.
	_требовать_доступ(запись.student, запись.course)
	релиз = прохождения.действующий(запись.course)
	if запись.release != релиз:
		raise _отказ_аннулирована(запись, _аннулировать_отставшую(запись, релиз), отставшая=True)

	вопросы = _снимок(запись)
	вопрос = next((в for в in вопросы if в["key"] == ключ_вопроса), None)
	if not вопрос:
		raise Отказ(ЧУЖОЙ_ВОПРОС, "Вопрос не из этой попытки")
	if _отвечено(запись.name, ключ_вопроса):
		raise _уже_отвечено()

	эталон = index.эталон(запись.release, запись.lesson_key, ключ_вопроса)
	if not эталон:
		raise Отказ(ЧУЖОЙ_ВОПРОС, "Вопроса нет в релизе попытки")
	верно = _выбранный(ответ, вопрос["options"]) == эталон.correct
	присланный = str(ответ or "")[:500]
	_записать_ответ(
		{
			"doctype": ОТВЕТ,
			"attempt": запись.name,
			"question_key": ключ_вопроса,
			"objective_key": вопрос["objective"],
			"answer": присланный,
			"is_correct": int(верно),
			"marks": int(верно),
			"marks_out_of": 1,
			"answered_at": now_datetime(),
		}
	)
	_в_журнал(
		ПРОВЕРКА_ОТВЕТ_ПРИНЯТ,
		запись,
		question_key=ключ_вопроса,
		answer=присланный,
		student_words=слова[:ДЛИНА_СЛОВ],
		is_correct=int(верно),
	)

	вердикт = {"correct": верно}
	if верно and эталон.explanation:
		вердикт["explanation"] = эталон.explanation
	следующий = _выдать_вопрос(запись, вопросы, блокировать=True)
	ответ_агенту = {"verdict": вердикт, "next_question": следующий, "attempt_finished": следующий is None}
	if следующий is None:
		ответ_агенту["result"] = завершить(запись)
	return ответ_агенту


def _отвечено(попытка: str, ключ_вопроса: str) -> bool:
	return bool(frappe.db.exists(ОТВЕТ, {"attempt": попытка, "question_key": ключ_вопроса}))


def _уже_отвечено() -> Отказ:
	return Отказ(ЧУЖОЙ_ВОПРОС, "На этот вопрос уже отвечено")


def _записать_ответ(поля: dict) -> None:
	"""Вставка ответа; дубль по индексу «попытка, ключ вопроса» — отказ «уже отвечено»."""
	frappe.db.savepoint(ТОЧКА_ОТВЕТА)
	try:
		frappe.get_doc(поля).insert(ignore_permissions=True)
	except (frappe.UniqueValidationError, frappe.DuplicateEntryError):
		frappe.db.rollback(save_point=ТОЧКА_ОТВЕТА)
		# Сообщение Frappe «must be unique» ответ не несёт: отказ скажет сам.
		frappe.clear_last_message()
		raise _уже_отвечено() from None
	frappe.db.release_savepoint(ТОЧКА_ОТВЕТА)


def _выбранный(ответ, варианты: list[dict]) -> str | None:
	"""Ключ выбранного варианта: по ключу, иначе — по тексту варианта; не узнан — `None`.

	Ключ важнее текста: у варианта может быть текст, совпадающий с ключом другого.
	"""
	if isinstance(ответ, (list, tuple)):
		if len(ответ) != 1:
			return None
		[ответ] = ответ
	строка = _привести(ответ)
	for поле in ("key", "text"):
		if найден := next((в["key"] for в in варианты if _привести(в[поле]) == строка), None):
			return найден
	return None


# --- итог ---


def завершить(запись) -> dict:
	"""Итог попытки, на все вопросы которой отвечено; сданная закрывает урок.

	Зачёт — `верных × 100 ≥ порог × всего`, порог — `pass_percentage`
	попытки, снятый с урока на её старте (F1). `score` — доля верных; `objective_results` —
	`{цель: {correct, total}}` по вопросам снимка. Сданная попытка закрывает урок
	(`quiz.отметить_урок_пройденным`: прогресс Learning, домашка, `passed` у
	прохождения), подтверждает квизом цели, все вопросы которых отвечены
	верно, и завершает открытое занятие.

	Ответ — `score`, `passed`, `correct`, `total`, `pass_threshold` (порог
	долей, как `score`), `objective_results` и `session_status`.
	Сданная попытка отдаёт `explanations` — пояснения к неверно отвеченным
	вопросам; несданная — остаток попыток и время пересдачи, но ни пояснений,
	ни верных вариантов (F2).

	Попытка без вопросов не сдана: зачёт ни на чём не стоит.

	`запись` — попытка, прочитанная с блокировкой (`ответить`); ответы
	читаются с блокировкой (`Why:` у `ответить`); прохождение блокируется
	раньше записи занятия — порядок старта квиза. Завершённая попытка —
	отказ `attempt_finished`.
	"""
	if запись.status != ПОПЫТКА_ИДЁТ:
		raise Отказ(ПОПЫТКА_ЗАВЕРШЕНА, "Эта попытка уже завершена")
	вопросы = _снимок(запись)
	верные = {ключ for ключ, верно in _ответы(запись.name, блокировать=True).items() if верно}
	по_целям: dict[str, dict] = {}
	for вопрос in вопросы:
		цель = по_целям.setdefault(вопрос["objective"], {"correct": 0, "total": 0})
		цель["total"] += 1
		цель["correct"] += вопрос["key"] in верные
	верных, всего = sum(ц["correct"] for ц in по_целям.values()), len(вопросы)
	порог = запись.pass_percentage
	# Why: в целых, а не долей: доля в плавающей точке теряет границу —
	# 57 из 100 дают 56.99… процента при пороге 57. `Decimal` — для дробного
	# порога: релиз допускает любое число от 0 до 100.
	зачтено = bool(всего) and верных * 100 >= Decimal(str(порог)) * всего

	запись.status = ПОПЫТКА_ЗАЧТЕНА if зачтено else ПОПЫТКА_НЕ_ЗАЧТЕНА
	запись.score = round(верных / всего, 3) if всего else 0.0
	запись.passed = int(зачтено)
	запись.objective_results = json.dumps(по_целям, ensure_ascii=False)
	запись.finished_at = now_datetime()
	запись.save(ignore_permissions=True)

	if зачтено:
		подтверждённые = {к for к, итог in по_целям.items() if итог["correct"] == итог["total"]}
		отметить_урок_пройденным(запись, подтверждённые)
	занятие = frappe.get_doc("Agent Learning Session", запись.session)
	if зачтено and занятие.status in ОТКРЫТЫЕ:
		занятие.status = ЗАНЯТИЕ_ЗАВЕРШЕНО
		занятие.save(ignore_permissions=True)
	занятие.записать_событие(
		СОБЫТИЕ_ВЕРДИКТ, f"итог {запись.score}, {'зачтено' if зачтено else 'не зачтено'}"
	)

	итог = {
		"score": запись.score,
		"passed": зачтено,
		"correct": верных,
		"total": всего,
		"pass_threshold": порог / 100,
		"objective_results": по_целям,
		"session_status": занятие.status,
	}
	if зачтено:
		итог["explanations"] = _пояснения_к_неверным(запись, вопросы, верные)
	else:
		отбор = попытки_урока(запись.student, запись.course, запись.lesson_key)
		итог.update(
			пересдача(отбор, политика_квиза_для_курса(запись.student, запись.course), запись.finished_at)
		)
	return итог


def _пояснения_к_неверным(запись, вопросы: list[dict], верные: set[str]) -> list[dict]:
	"""Пояснения релиза попытки к неверно отвеченным вопросам — по порядку снимка; без пояснения — пропуск.

	У перенесённой попытки релиз — новый: пояснения тоже его."""
	пояснения = []
	for вопрос in вопросы:
		if вопрос["key"] in верные:
			continue
		эталон = index.эталон(запись.release, запись.lesson_key, вопрос["key"])
		if эталон and эталон.explanation:
			пояснения.append({"id": вопрос["key"], "text": вопрос["text"], "explanation": эталон.explanation})
	return пояснения


