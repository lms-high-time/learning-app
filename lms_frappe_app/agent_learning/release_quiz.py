"""Квиз урока из релиза: старт и ответ (learning-services#504).

Попытка — `Agent Quiz Attempt` с релизом, ключом урока и снимком вопросов
вместо `LMS Quiz`. Вопросы выдаются из снимка, верный вариант и пояснение
сервер берёт из релиза попытки, а не из действующего: новый релиз посреди
попытки её не ломает. Эталон наружу не уходит: в снимке его нет, а неверный
ответ не получает ни верного варианта, ни пояснения (F2).

Лимит попыток, пауза и обязательность — политика платформы, общая с `quiz`;
попытки считаются по ученику, курсу и ключу урока (`quiz.попытки_урока`).
"""

import json

import frappe
from frappe.utils import now_datetime

from lms_frappe_app.agent_learning.access import доступен_курс, политика_квиза_для_курса
from lms_frappe_app.agent_learning.constants import (
	ЗАНЯТИЕ_ЖДЁТ_КВИЗ,
	ЗАНЯТИЕ_ИДЁТ,
	ПОПЫТКА_ИДЁТ,
	ПРОВЕРКА_ВОПРОС_ВЫДАН,
	ПРОВЕРКА_ОТВЕТ_ПРИНЯТ,
	СОБЫТИЕ_КВИЗ_НАЧАТ,
)
from lms_frappe_app.agent_learning.errors import ЧУЖОЕ_ЗАНЯТИЕ, Отказ
from lms_frappe_app.agent_learning.quiz import (
	ДЛИНА_СЛОВ,
	КВИЗА_НЕТ,
	НУЖНЫ_СЛОВА,
	ПОПЫТКА_ЗАВЕРШЕНА,
	ЧУЖОЙ_ВОПРОС,
	_в_журнал,
	_привести,
	_проверить_право_на_попытку,
	_прошлых_попыток,
	попытки_урока,
)
from lms_frappe_app.agent_learning.releases import index
from lms_frappe_app.agent_learning.runs import service as прохождения

ПОПЫТКА = "Agent Quiz Attempt"
ОТВЕТ = "Agent Quiz Answer"


# --- начало попытки ---


def начать(run, занятие: str) -> dict:
	"""Попытка квиза урока и её первый неотвеченный вопрос: `{attempt, question}`.

	`run` — прохождение урока (`runs.service.прохождение`), `занятие` — имя
	занятия по нему. Открытая попытка занятия по этому уроку возвращается, а
	не заводится новая, — со своим снимком вопросов. Новая попытка снимает
	все вопросы урока действующего релиза по порядку релиза.

	Отказы: прохождение в архиве или занятие другого ученика, урока,
	прохождения — `not_your_session`; урока нет в действующем релизе —
	`lesson_not_in_release`; курс недоступен; у урока нет вопросов —
	`quiz_not_configured`; лимит попыток и пауза — как у `quiz.начать_попытку`.

	`Why:` занятие читается с блокировкой: два параллельных старта по одному
	занятию иначе завели бы две попытки и сожгли две из лимита.
	"""
	if not run.student:
		raise Отказ(ЧУЖОЕ_ЗАНЯТИЕ, "Прохождение в архиве: прогресс ученика сброшен", run=run.name)
	прохождения._проверить_занятие(run, занятие)
	релиз = прохождения._действующий(run.course)
	if not релиз or not index.урок(релиз, run.lesson_key):
		raise прохождения._урок_не_в_релизе(run.course, run.lesson_key, релиз)
	_требовать_доступ(run.student, run.course)
	сессия = frappe.get_doc("Agent Learning Session", занятие, for_update=True)

	if открытая := _открытая_попытка(занятие, run.lesson_key):
		сессия.записать_событие(СОБЫТИЕ_КВИЗ_НАЧАТ, "продолжение попытки")
		return {"attempt": открытая.name, "question": _выдать_вопрос(открытая, _снимок(открытая))}

	вопросы = index.вопросы_урока(релиз, run.lesson_key)
	if not вопросы:
		raise Отказ(КВИЗА_НЕТ, "У этого урока нет квиза")
	отбор = попытки_урока(run.student, run.course, run.lesson_key)
	_проверить_право_на_попытку(отбор, политика_квиза_для_курса(run.student, run.course))

	попытка = frappe.get_doc(
		{
			"doctype": ПОПЫТКА,
			"session": занятие,
			"student": run.student,
			"lesson": run.lesson,
			"course": run.course,
			"release": релиз,
			"lesson_key": run.lesson_key,
			"questions": json.dumps(вопросы, ensure_ascii=False),
			"attempt_number": _прошлых_попыток(отбор) + 1,
			"status": ПОПЫТКА_ИДЁТ,
			"started_at": now_datetime(),
		}
	).insert(ignore_permissions=True)

	if сессия.status == ЗАНЯТИЕ_ИДЁТ:
		сессия.status = ЗАНЯТИЕ_ЖДЁТ_КВИЗ
		сессия.save(ignore_permissions=True)
	сессия.записать_событие(СОБЫТИЕ_КВИЗ_НАЧАТ, f"попытка {попытка.attempt_number}")

	return {"attempt": попытка.name, "question": _выдать_вопрос(попытка, вопросы)}


def _открытая_попытка(занятие: str, ключ_урока: str):
	"""Незавершённая попытка занятия по уроку из релиза, если она есть."""
	открытые = frappe.get_all(
		ПОПЫТКА,
		filters={"session": занятие, "lesson_key": ключ_урока, "status": ПОПЫТКА_ИДЁТ},
		pluck="name",
		order_by="creation desc",
		limit=1,
	)
	return frappe.get_doc(ПОПЫТКА, открытые[0]) if открытые else None


# --- ответ ---


def ответить(попытка: str, ключ_вопроса: str, ответ, слова_ученика: str) -> dict:
	"""Сверяет ответ по релизу попытки: `{verdict, next_question, all_answered}`.

	`ответ` — ключ варианта; не ключ — текст варианта, без учёта регистра и
	пробелов (агенты присылают текст, lms-platform#148). Неузнанный ответ —
	неверный, а не ошибка. Верный ответ получает пояснение вопроса, неверный —
	только `correct: false` (F2). `слова_ученика` — что ученик написал в ответ,
	дословно: в журнал проверки, на вердикт не влияют.

	`all_answered` — на все вопросы снимка отвечено, `next_question` пуст.

	Отказы: нет слов ученика — `student_words_required`; попытка завершена —
	`attempt_finished`; курс недоступен; вопроса нет в снимке или на него уже
	отвечено — `question_mismatch`.

	`Why:` попытка читается с блокировкой: параллельные ответы на один вопрос
	иначе оба прошли бы проверку «уже отвечено» и записали бы два ответа.
	"""
	слова = str(слова_ученика or "").strip()
	if not слова:
		raise Отказ(НУЖНЫ_СЛОВА, "Передайте, что ученик написал в ответ, дословно")

	запись = frappe.get_doc(ПОПЫТКА, попытка, for_update=True)
	if запись.status != ПОПЫТКА_ИДЁТ:
		raise Отказ(ПОПЫТКА_ЗАВЕРШЕНА, "Эта попытка уже завершена")
	# Доступ — на каждом ответе: приостановка организации или снятое
	# зачисление посреди квиза иначе не мешали бы довести его до зачёта.
	_требовать_доступ(запись.student, запись.course)

	вопросы = _снимок(запись)
	вопрос = next((в for в in вопросы if в["key"] == ключ_вопроса), None)
	if not вопрос:
		raise Отказ(ЧУЖОЙ_ВОПРОС, "Вопрос не из этой попытки")
	if frappe.db.exists(ОТВЕТ, {"attempt": запись.name, "question_key": ключ_вопроса}):
		raise Отказ(ЧУЖОЙ_ВОПРОС, "На этот вопрос уже отвечено")

	эталон = _эталон(запись, ключ_вопроса)
	верно = _выбранный(ответ, вопрос["options"]) == эталон["correct"]
	присланный = str(ответ or "")[:500]
	frappe.get_doc(
		{
			"doctype": ОТВЕТ,
			"attempt": запись.name,
			"question_key": ключ_вопроса,
			"objective_key": вопрос["objective"],
			"answer": присланный,
			"is_correct": int(верно),
			"marks": int(верно),
			"marks_out_of": 1,
			"answered_at": now_datetime(),
		}
	).insert(ignore_permissions=True)
	_в_журнал(
		ПРОВЕРКА_ОТВЕТ_ПРИНЯТ,
		запись,
		None,
		question_key=ключ_вопроса,
		answer=присланный,
		student_words=слова[:ДЛИНА_СЛОВ],
		is_correct=int(верно),
	)

	вердикт = {"correct": верно}
	if верно and эталон["explanation"]:
		вердикт["explanation"] = эталон["explanation"]
	следующий = _выдать_вопрос(запись, вопросы)
	return {"verdict": вердикт, "next_question": следующий, "all_answered": следующий is None}


def _выбранный(ответ, варианты: list[dict]) -> str | None:
	"""Ключ выбранного варианта: ключ как есть, иначе — по тексту варианта; не узнан — `None`.

	Ключ важнее текста: у варианта может быть текст, совпадающий с ключом другого.
	"""
	строка = str(ответ or "").strip()
	if any(в["key"] == строка for в in варианты):
		return строка
	return next((в["key"] for в in варианты if _привести(в["text"]) == _привести(строка)), None)


def _эталон(попытка, ключ_вопроса: str) -> dict:
	"""Верный вариант и пояснение вопроса — из релиза попытки."""
	return next(
		в
		for в in index.вопросы_урока(попытка.release, попытка.lesson_key, с_ответами=True)
		if в["key"] == ключ_вопроса
	)


# --- выдача вопроса ---


def _снимок(попытка) -> list[dict]:
	return json.loads(попытка.questions or "[]")


def _выдать_вопрос(попытка, вопросы: list[dict]) -> dict | None:
	"""Первый неотвеченный вопрос снимка — с записью «выдан» в журнал проверки; все отвечены — `None`."""
	отвеченные = set(frappe.get_all(ОТВЕТ, filters={"attempt": попытка.name}, pluck="question_key"))
	for номер, вопрос in enumerate(вопросы, start=1):
		if вопрос["key"] not in отвеченные:
			_в_журнал(ПРОВЕРКА_ВОПРОС_ВЫДАН, попытка, None, question_key=вопрос["key"])
			return _вопрос_для_агента(вопрос, номер, len(вопросы))
	return None


def _вопрос_для_агента(вопрос: dict, номер: int, всего: int) -> dict:
	"""Вопрос в форме `quiz._вопрос_для_агента`: варианты — с ключами релиза, без эталона.

	В релизе верный вариант у вопроса один — отсюда `multiple: false`.
	"""
	return {
		"id": вопрос["key"],
		"text": вопрос["text"],
		"kind": "choice",
		"index": номер,
		"total": всего,
		"multiple": False,
		"options": [{"id": в["key"], "text": в["text"]} for в in вопрос["options"]],
	}


def _требовать_доступ(ученик: str, курс: str) -> None:
	можно, причина = доступен_курс(ученик, курс)
	if not можно:
		raise Отказ(причина, "Этот курс сейчас недоступен", course=курс)
