"""Сигналы агенту — выводы сервера из истории ученика (learning-services#416).

Агент видит один разговор, сервер — все занятия ученика, его отметки и
попытки. Сигнал — код и данные: «эта цель не даётся второе занятие подряд», а
не сырые записи. Фразу для агента складывает потребитель контракта — готовые
тексты для агента сюда не входят (CONTRIBUTING.md).

Время сервер использует только сам — решить, что занятие брошено, посчитать
срок, — а наружу отдаёт вывод. `Why:` агенты не отслеживают реальное время и
неверно толкуют его внутри урока: в одном чате бывают паузы, ученик
возвращается назавтра (решение владельца, #416). По той же причине сигналов
«прошло N минут» здесь нет.
"""

from __future__ import annotations

from math import ceil

import frappe
from frappe.utils import getdate, nowdate

from lms_frappe_app.agent_learning.constants import ЗАНЯТИЕ_БРОШЕНО, ПРОЙДЕН

ИТОГ_УРОКА = "lesson_wrapup"
ЦЕЛЬ_НЕ_ДАЁТСЯ = "objective_struggling"
БРОШЕНЫ_ПОДРЯД = "abandoned_in_row"
ДОКУМЕНТ_ПУСТ = "blocks_empty"
ТЕМП_К_СРОКУ = "deadline_pace"

#: Порядок — приоритет: когда кандидатов больше предела, остаются первые.
ПРИОРИТЕТ = (ИТОГ_УРОКА, ЦЕЛЬ_НЕ_ДАЁТСЯ, БРОШЕНЫ_ПОДРЯД, ДОКУМЕНТ_ПУСТ, ТЕМП_К_СРОКУ)

#: Сколько сигналов в одном ответе. `Why:` подсказка, которая приходит пачкой,
#: перестаёт читаться — агент обработает первую и забудет остальные.
НЕ_БОЛЬШЕ = 3

#: В скольких занятиях цель урока должна остаться `touched`, чтобы считаться
#: не дающейся. Одно — обычное «не успели»; два — объяснение не работает.
ЗАНЯТИЙ_ДО_ТРУДНОЙ = 2

#: Сколько последних занятий по уроку брошены подряд без единой отметки.
БРОШЕННЫХ_ПОДРЯД = 2

#: С какого темпа к сроку курса стоит сказать ученику: уроков в неделю.
УРОКОВ_В_НЕДЕЛЮ = 3


def история_урока(ученик: str, lesson: str, кроме: str) -> list[dict]:
	"""Прошлые занятия ученика по уроку, новые первыми, — с отметками целей.

	Одним запросом на оба сигнала урока: и трудные цели, и брошенные подряд
	читают одну и ту же историю, а `start_lesson` зовут на каждом старте.
	"""
	строки = frappe.db.sql(
		"""
		select s.name, s.status, o.objective, o.status as outcome
		from `tabAgent Learning Session` s
		left join `tabAgent Objective Outcome` o
			on o.parent = s.name and o.parenttype = 'Agent Learning Session'
		where s.student = %(student)s and s.lesson = %(lesson)s and s.name != %(session)s
		order by s.creation desc, o.idx asc
		""",
		{"student": ученик, "lesson": lesson, "session": кроме},
		as_dict=True,
	)
	занятия: dict[str, dict] = {}
	for строка in строки:
		занятие = занятия.setdefault(строка.name, {"status": строка.status, "outcomes": {}})
		if строка.objective:
			занятие["outcomes"][строка.objective] = строка.outcome
	return list(занятия.values())


def цели_не_даются(история: list[dict], цели: list[str], текущее: str | None = None) -> list[dict]:
	"""Цели урока, оставшиеся `touched` в нескольких занятиях ученика.

	`текущее` — цель, которую только что отметили `touched` в этом занятии: в
	истории его нет, и отметка засчитывается сверху. Без `текущее` — все цели
	урока, как на старте.
	"""
	итог = []
	for номер, цель in enumerate(цели, start=1):
		if текущее is not None and цель != текущее:
			continue
		занятий = sum(1 for з in история if з["outcomes"].get(цель) == "touched")
		занятий += 1 if текущее is not None else 0
		if занятий >= ЗАНЯТИЙ_ДО_ТРУДНОЙ:
			итог.append(
				{"code": ЦЕЛЬ_НЕ_ДАЁТСЯ, "objective": номер, "text": цель, "sessions": занятий}
			)
	return sorted(итог, key=lambda с: -с["sessions"])


def брошены_подряд(история: list[dict]) -> list[dict]:
	"""Последние занятия по уроку, брошенные подряд без единой отметки.

	Брошенное с отметками — не срыв: урок прошли в два приёма, а занятие
	закрыл таймаут. Сигнал — о попытках, которые обрывались, не начавшись.
	"""
	подряд = 0
	for занятие in история:
		if занятие["status"] != ЗАНЯТИЕ_БРОШЕНО or занятие["outcomes"]:
			break
		подряд += 1
	if подряд < БРОШЕННЫХ_ПОДРЯД:
		return []
	return [{"code": БРОШЕНЫ_ПОДРЯД, "attempts": подряд}]


def осталось_уроков(ученик: str, курс: str) -> int:
	"""Непройденные уроки курса — одним запросом.

	Порядок уроков здесь не нужен, только их число, поэтому без обхода глав
	`уроки_курса`: тот стоит запроса на каждую главу.
	"""
	return frappe.db.sql(
		"""
		select count(*)
		from `tabCourse Lesson` l
		join `tabCourse Chapter` c on c.name = l.chapter
		where c.course = %(course)s and not exists (
			select 1 from `tabLMS Course Progress` p
			where p.member = %(student)s and p.course = %(course)s
				and p.lesson = l.name and p.status = %(done)s
		)
		""",
		{"course": курс, "student": ученик, "done": ПРОЙДЕН},
	)[0][0]


def темп_к_сроку(срок, просрочен: bool, осталось_уроков: int) -> list[dict]:
	"""Темп к сроку курса в уроках в неделю — когда срок жмёт или прошёл.

	Даты наружу не идут: агенту нужен вывод «успеваем ли», а не календарь.
	"""
	if not срок or осталось_уроков <= 0:
		return []
	if просрочен:
		return [
			{"code": ТЕМП_К_СРОКУ, "lessons_left": осталось_уроков, "lessons_per_week": None, "overdue": True}
		]
	дней = max((getdate(срок) - getdate(nowdate())).days, 1)
	в_неделю = ceil(осталось_уроков * 7 / дней)
	if в_неделю < УРОКОВ_В_НЕДЕЛЮ:
		return []
	return [
		{"code": ТЕМП_К_СРОКУ, "lessons_left": осталось_уроков, "lessons_per_week": в_неделю, "overdue": False}
	]


def _ключ(сигнал: dict) -> str:
	# Цель, которая не даётся, — сигнал на каждую цель, а не один на урок.
	if сигнал["code"] == ЦЕЛЬ_НЕ_ДАЁТСЯ:
		return f"{сигнал['code']}:{сигнал['objective']}"
	return сигнал["code"]


def отобрать(занятие, кандидаты: list[dict]) -> list[dict]:
	"""Сигналы ответа: новые для занятия, по приоритету, не больше предела.

	Показанный сигнал занятие помнит и второй раз не отдаёт. `Why:`
	`start_lesson` зовут повторно — продолжение, рамка по запросу, веб-чат на
	каждой странице, — и одно и то же наблюдение на каждом вызове стало бы
	шумом, который агент научится пропускать.
	"""
	показанные = set((занятие.get("signals_shown") or "").split())
	новые = [с for с in кандидаты if _ключ(с) not in показанные]
	новые.sort(key=lambda с: ПРИОРИТЕТ.index(с["code"]))
	новые = новые[:НЕ_БОЛЬШЕ]
	if новые:
		занятие.db_set(
			"signals_shown",
			"\n".join(sorted(показанные | {_ключ(с) for с in новые})),
			update_modified=False,
		)
	return новые


def итог_урока(прогресс: dict, пустые_блоки) -> list[dict]:
	"""Все цели урока отмечены — пора подводить итог.

	`пустые_блоки` — функция, а не список: блоки документа читаются, только
	когда итог действительно наступил.
	"""
	if прогресс["open"] or not прогресс["total"]:
		return []
	return [{"code": ИТОГ_УРОКА, "empty_blocks": пустые_блоки()}]


def документ_пуст(прогресс: dict, блоки: list[dict], пустые: list[dict]) -> list[dict]:
	"""Половина целей разобрана, а ни один блок документа урока не начат.

	`Why:` ранний видимый результат — первый блок документа; к середине урока
	его всё ещё нет, и в конце занятия документ собирают наспех или не
	собирают вовсе.
	"""
	if not блоки or len(пустые) < len(блоки) or 2 * прогресс["marked"] < прогресс["total"]:
		return []
	return [
		{
			"code": ДОКУМЕНТ_ПУСТ,
			"blocks": [{"artifact": б["artifact"], "key": б["key"], "title": б["title"]} for б in пустые],
		}
	]
